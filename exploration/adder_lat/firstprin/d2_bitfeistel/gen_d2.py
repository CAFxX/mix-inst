#!/usr/bin/env python3
"""Generate Direction-2 bit-Feistel Verilog with LITERAL bit indices.

Matches d2_model.apply (1-AND) / d2_sweep.apply2 (2-AND) bit-exactly:
  half A: y[2i]   = x[2i] ^ ANDs(x[2i+a]&x[2i+b], ...) ^ ka[2i]; y[2i+1]=x[2i+1]
  half B: z[2i+1] = y[2i+1] ^ ANDs(y[2i+1+c]&y[2i+1+d], ...) ^ kb[2i+1]; z[2i]=y[2i]
Indices mod 64, taps odd (parity split preserved).
"""
import sys

TAPS_1A = (3, 13)          # placeholder; replaced by sweep winner
TAPS_2A = (3, 13, 5, 15)   # placeholder; replaced by sweep winner


def emit_round(f, x, ka, kb, z, w, tapsA, tapsB):
    """One full round: A then B. taps = tuple of odd offsets (len 2 or 4)."""
    def ands(sig, i, taps):
        terms = [f"({sig}[{(i + t) % 64}] & {sig}[{(i + t2) % 64}])"
                 for t, t2 in zip(taps[0::2], taps[1::2])]
        return " ^ ".join(terms)
    f.write(f"  // half-round A: even update, taps={tapsA}\n")
    for i in range(0, 64, 2):
        f.write(f"  assign {w}[{i}] = {x}[{i}] ^ {ands(x, i, tapsA)} ^ {ka}[{i}];\n")
        f.write(f"  assign {w}[{i+1}] = {x}[{i+1}];\n")
    f.write(f"  // half-round B: odd update, taps={tapsB}\n")
    for i in range(0, 64, 2):
        f.write(f"  assign {z}[{i}] = {w}[{i}];\n")
        f.write(f"  assign {z}[{i+1}] = {w}[{i+1}] ^ {ands(w, i+1, tapsB)} ^ {kb}[{i+1}];\n")


def gen(top, rounds, tapsA, tapsB, path):
    with open(path, "w") as f:
        f.write(f"// Direction-2 bit-Feistel: {rounds} full round(s), "
                f"{len(tapsA)//2} AND(s)/bit, tapsA={tapsA} tapsB={tapsB}\n")
        f.write(f"// Generated by gen_d2.py -- literal indices, no rotl ambiguity.\n")
        f.write(f"module {top}(\n")
        ports = ["input  [63:0] x"]
        for r in range(rounds):
            ports += [f"input  [63:0] ka{r}", f"input  [63:0] kb{r}"]
        ports += ["output [63:0] z"]
        f.write("  " + ",\n  ".join(ports) + "\n);\n")
        sig = "x"
        for r in range(rounds):
            out = "z" if r == rounds - 1 else f"w{r}"
            if r < rounds - 1:
                f.write(f"  wire [63:0] {out};\n")
            emit_round(f, sig, f"ka{r}", f"kb{r}", out, f"y{r}", tapsA, tapsB)
            sig = out
        f.write("endmodule\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    tapsA = tuple(int(v) for v in sys.argv[1].split(","))
    tapsB = tuple(int(v) for v in sys.argv[2].split(","))
    top, rounds, path = sys.argv[3], int(sys.argv[4]), sys.argv[5]
    assert all(t % 2 == 1 for t in tapsA + tapsB), "taps must be odd"
    assert len(tapsA) == len(tapsB) and len(tapsA) in (2, 4)
    gen(top, rounds, tapsA, tapsB, path)
