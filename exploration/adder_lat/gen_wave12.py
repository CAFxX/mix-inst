#!/usr/bin/env python3
"""Wave-12 generator: hetero 5-stage (and/t3) from first-principles design rules.

Design rules applied (rootcause/DESIGN_RULES.md):
- Rule 1/2: 4-stage prefix must maximize difference uniformity (triple fan-out)
- Rule 3: s2proxy-predicted max|z| < 9 before building
- Rule 4: 2x t3 + 3x and = 19.05u est, under 20.1u frontier
- Rule 5: spread early (t3 front-loaded where possible)

Candidates from rootcause/candidates5b.json (strict-verified).
Stage types: ('and',a,b,c): x^=(ra&rb)^rc ; ('t3',a,b,c,e): x^=(ra&rb)^rc^re
Key schedule: pre-whiten x^=k, post x^=rotl(k,13) (al_and6a convention).
"""
import os, sys, json

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_wave1 import PY_PREAMBLE, RC, FB, vl_rotl  # noqa: E402

def load_candidates():
    p = os.path.join(HERE, "rootcause", "candidates5b.json")
    if not os.path.exists(p):
        p = os.path.join(HERE, "rootcause", "candidates5.json")
    return json.load(open(p))

def gen_model(name, stages, desc):
    rc = ", ".join(hex(v) for v in RC[:12])
    s = PY_PREAMBLE % (desc, rc)
    s += "STAGES = %s\n" % (stages,)
    s += "def mix_np(V, K):\n"
    s += "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)\n"
    s += "    x = (x ^ k) & M64\n"
    s += "    for i, st in enumerate(STAGES):\n"
    s += "        ra, rb = _rotl(x, st[1]), _rotl(x, st[2])\n"
    s += "        if st[0] == 't3':\n"
    s += "            t = (x ^ (ra & rb) ^ _rotl(x, st[3]) ^ _rotl(x, st[4])) & M64\n"
    s += "        else:\n"
    s += "            t = (x ^ (ra & rb) ^ _rotl(x, st[3])) & M64\n"
    s += "        x = t\n"
    s += "    x = (x ^ _rotl(k, 13)) & M64\n"
    s += "    return x & M64\n"
    s += "def mix(v, k):\n    return int(mix_np(np.uint64(v), np.uint64(k)))\n"
    return s

def gen_impl(name, stages, desc):
    s = "#include <stdint.h>\n"
    s += "static inline uint64_t rotl64(uint64_t x, int r) {\n    r &= 63;\n    return r ? (x << r) | (x >> (64 - r)) : x;\n}\n"
    s += f"// {desc}\n"
    s += "uint64_t mix_hash(uint64_t val, uint64_t key) {\n"
    s += "    uint64_t x = val ^ key;\n"
    for i, st in enumerate(stages):
        a, b = st[1], st[2]
        s += f"    {{ uint64_t ra = rotl64(x,{a}), rb = rotl64(x,{b});\n"
        if st[0] == "t3":
            s += f"      x ^= (ra & rb) ^ rotl64(x,{st[3]}) ^ rotl64(x,{st[4]}); }}\n"
        else:
            s += f"      x ^= (ra & rb) ^ rotl64(x,{st[3]}); }}\n"
    s += "    x ^= rotl64(key, 13);\n    return x;\n}"
    return s

def gen_rtl(name, stages, desc):
    s = f"// {name}: {desc} (generated by gen_wave12.py)\n"
    s += f"module {name}(\n    input [63:0] val,\n    input [63:0] key,\n    output [63:0] out\n);\n"
    s += "    wire [63:0] x0 = val ^ key;\n"
    for i, st in enumerate(stages):
        a, b = st[1], st[2]
        s += f"    wire [63:0] s{i}a = {vl_rotl('x%d' % i, a)};\n"
        s += f"    wire [63:0] s{i}b = {vl_rotl('x%d' % i, b)};\n"
        s += f"    wire [63:0] s{i}c = {vl_rotl('x%d' % i, st[3])};\n"
        if st[0] == "t3":
            s += f"    wire [63:0] s{i}e = {vl_rotl('x%d' % i, st[4])};\n"
            s += f"    wire [63:0] x{i+1} = x{i} ^ (s{i}a & s{i}b) ^ s{i}c ^ s{i}e;\n"
        else:
            s += f"    wire [63:0] x{i+1} = x{i} ^ (s{i}a & s{i}b) ^ s{i}c;\n"
    s += f"    wire [63:0] kr = {vl_rotl('key', 13)};\n"
    s += f"    assign out = x{len(stages)} ^ kr;\n"
    s += "endmodule\n"
    return s

def main():
    cands = load_candidates()
    # take top 3 strict-verified with z < 9
    n = 0
    for idx, entry in enumerate(cands):
        if len(entry) == 4:
            z, ce, n_t3, st = entry
        else:
            z, st = entry
            ce, n_t3 = 19.05, 2
        if z >= 9.0:
            continue
        n += 1
        if n > 3:
            break
        name = f"al_ht5{n}"
        stages = [tuple(s) for s in st]
        desc = f"Wave-12: hetero 5-stage {n_t3}x t3 + {5-n_t3}x and, proxy z={z:.1f}, est {ce:.2f}u (design-rules)"
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(gen_model(name, stages, desc))
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_impl(name, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_rtl(name, stages, desc))
        # bit-exact check: model vs impl.c
        import importlib.util, subprocess
        spec = importlib.util.spec_from_file_location(f"w12_{name}", os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
        # compile impl.c test
        test_c = os.path.join(cdir, "test_impl.c")
        with open(test_c, "w") as f:
            f.write('#include <stdio.h>\n#include <stdint.h>\nuint64_t mix_hash(uint64_t,uint64_t);\n')
            f.write('int main(){uint64_t vs[3]={0,0x123456789ABCDEF0ULL,0xFFFFFFFFFFFFFFFFULL};\n')
            f.write('uint64_t ks[2]={0x123456789ABCDEF0ULL,0};\n')
            f.write('for(int i=0;i<3;i++)for(int j=0;j<2;j++)printf("%llx\\n",(unsigned long long)mix_hash(vs[i],ks[j]));return 0;}\n')
        r = subprocess.run(["gcc", "-O2", "-o", os.path.join(cdir, "test_impl"),
                            test_c, os.path.join(cdir, "impl.c")],
                           capture_output=True, text=True)
        assert r.returncode == 0, r.stderr
        r = subprocess.run([os.path.join(cdir, "test_impl")], capture_output=True, text=True)
        # test_impl.c iterates vs outer, ks inner: (v,k) in
        # [(0,K),(0,0),(V,K),(V,0),(F,K),(F,0)] where K=0x123.., V=0x123.., F=0xFF..
        K = 0x123456789ABCDEF0; V = 0x123456789ABCDEF0; F = 0xFFFFFFFFFFFFFFFF
        vals = [(0,K),(0,0),(V,K),(V,0),(F,K),(F,0)]
        ok = True
        for (v,k), line in zip(vals, r.stdout.strip().split("\n")):
            if m.mix(v,k) != int(line.strip(),16):
                ok = False; print(f"MISMATCH {name} v={v:#x} k={k:#x}")
        assert ok, "bit-exact FAILED"
        g1 = m.mix(0x0, 0x123456789ABCDEF0); g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {"name": name, "description": desc,
                "screen_keys": ["0x123456789abcdef0", "0x0"],
                "practrand_keys": ["0x123456789abcdef0", "0x0"],
                "rtl_top": name,
                "goldens": [{"val":"0x0","key":"0x123456789abcdef0","out":hex(g1)},
                            {"val":"0x123456789ABCDEF0","key":"0x0","out":hex(g2)}]}
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        print(f"Created {name}: proxy z={z:.1f}, bit-exact OK", flush=True)
    if n == 0:
        print("No candidates with z<9; nothing built.")

if __name__ == "__main__":
    main()
