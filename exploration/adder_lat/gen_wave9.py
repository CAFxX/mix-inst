def check_danger(stages, name):
    """Verify no rotations in danger zones."""
    bad = []
    for i, (a, b, c) in enumerate(stages):
        for r, label in [(a, 'a'), (b, 'b'), (c, 'c')]:
            if 28 <= r <= 36:
                bad.append(f"stage {i} {label}={r} (near 32)")
            if r >= 54:
                bad.append(f"stage {i} {label}={r} (near 64)")
    if bad:
        print(f"WARNING {name}: {bad}")
        return False
    return True

def write_candidate(name, stages, desc, template=MODEL_TEMPLATE, ops=None, key_out=13):
    check_danger(stages, name)
    cdir = os.path.join(FB, name)
    os.makedirs(cdir, exist_ok=True)
    if ops is not None:
        content = template.format(desc=desc, stages=stages, ops=ops, key_out=key_out)
    else:
        content = template.format(desc=desc, stages=stages, key_in=0, key_out=key_out)
    with open(os.path.join(cdir, "model.py"), "w") as f:
        f.write(content)
    # meta.json via mk_candidate logic
    sys.path.insert(0, cdir)
    import importlib.util
    # Force reimport
    modname = f"wave9_{name}"
    if modname in sys.modules:
        del sys.modules[modname]
    spec = importlib.util.spec_from_file_location(modname, os.path.join(cdir, "model.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    g1 = m.mix(0x0, 0x123456789ABCDEF0)
    g2 = m.mix(0x123456789ABCDEF0, 0x0)
    meta = {
        "name": name,
        "description": desc,
        "screen_keys": ["0x123456789abcdef0", "0x0"],
        "practrand_keys": ["0x123456789abcdef0", "0x0"],
        "rtl_top": name,
        "goldens": [
            {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
            {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
        ],
    }
    with open(os.path.join(cdir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=1)
    # Stub impl.c and rtl.v (real ones generated separately for S0/S3)
    with open(os.path.join(cdir, "impl.c"), "w") as f:
        f.write("// Stub - real impl needed for S3/S4\n")
        f.write("#include <stdint.h>\nuint64_t mix_hash(uint64_t v, uint64_t k) { return 0; }\n")
    with open(os.path.join(cdir, "rtl.v"), "w") as f:
        f.write(f"// Stub - real RTL needed for S0\nmodule {name}(input [63:0] v, input [63:0] k, output [63:0] o);\nassign o = 64'h0;\nendmodule\n")
    print(f"Created {name}: {desc}")

