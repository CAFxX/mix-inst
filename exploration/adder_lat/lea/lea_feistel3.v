module lea_feistel3(
  input [63:0] v,
  input [63:0] k,
  output [63:0] out
);
  // 3-round Feistel, 32-bit halves, LEA-style F with 4 AND pairs.
  // F(R) = (p1^p2^p3^p4) ^ rotl(R,i) ^ k_i  (pN = AND pairs)
  wire [31:0] L0 = v[63:32];
  wire [31:0] R0 = v[31:0];

  // Round 0: k0 = k[31:0]
  wire [31:0] p1_0 = {R0[28:0], R0[31:29]} & {R0[24:0], R0[31:25]}; // (3,7)
  wire [31:0] p2_0 = {R0[20:0], R0[31:21]} & {R0[16:0], R0[31:17]}; // (11,15)
  wire [31:0] p3_0 = {R0[26:0], R0[31:27]} & {R0[22:0], R0[31:23]}; // (5,9)
  wire [31:0] p4_0 = {R0[18:0], R0[31:19]} & {R0[14:0], R0[31:15]}; // (13,17)
  wire [31:0] lin0 = {R0[10:0], R0[31:11]}; // rotl 21
  wire [31:0] F0 = p1_0 ^ p2_0 ^ p3_0 ^ p4_0 ^ lin0 ^ k[31:0];
  wire [31:0] L1 = R0;
  wire [31:0] R1 = L0 ^ F0;

  // Round 1: k1 = k[63:32]
  wire [31:0] p1_1 = {R1[26:0], R1[31:27]} & {R1[22:0], R1[31:23]}; // (5,9)
  wire [31:0] p2_1 = {R1[18:0], R1[31:19]} & {R1[14:0], R1[31:15]}; // (13,17)
  wire [31:0] p3_1 = {R1[24:0], R1[31:25]} & {R1[20:0], R1[31:21]}; // (7,11)
  wire [31:0] p4_1 = {R1[16:0], R1[31:17]} & {R1[12:0], R1[31:13]}; // (15,19)
  wire [31:0] lin1 = {R1[8:0], R1[31:9]}; // rotl 23
  wire [31:0] F1 = p1_1 ^ p2_1 ^ p3_1 ^ p4_1 ^ lin1 ^ k[63:32];
  wire [31:0] L2 = R1;
  wire [31:0] R2 = L1 ^ F1;

  // Round 2: k2 = k[31:0] ^ k[63:32]
  wire [31:0] p1_2 = {R2[24:0], R2[31:25]} & {R2[20:0], R2[31:21]}; // (7,11)
  wire [31:0] p2_2 = {R2[16:0], R2[31:17]} & {R2[12:0], R2[31:13]}; // (15,19)
  wire [31:0] p3_2 = {R2[22:0], R2[31:23]} & {R2[18:0], R2[31:19]}; // (9,13)
  wire [31:0] p4_2 = {R2[14:0], R2[31:15]} & {R2[10:0], R2[31:11]}; // (17,21)
  wire [31:0] lin2 = {R2[6:0], R2[31:7]}; // rotl 25
  wire [31:0] F2 = p1_2 ^ p2_2 ^ p3_2 ^ p4_2 ^ lin2 ^ (k[31:0] ^ k[63:32]);
  wire [31:0] L3 = R2;
  wire [31:0] R3 = L2 ^ F2;

  assign out = {R3, L3};
endmodule
