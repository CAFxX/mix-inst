#!/usr/bin/env python3
"""Bundle w4t screen keeps: bit-exact Verilog + numpy model + meta.json.

Form (must match screen_w4t.py w4t_model EXACTLY):
  x = val ^ key
  3 stages:
    2 AND layers: x ^= rotl(x,a) & rotl(x,b)   (sequential)
    4-term linear: x ^= rotl(x,p)^rotl(x,q)^rotl(x,r)^rotl(x,s)
  out = x ^ rotl(key,13)

Verilog rotl(x,r) = {x[63-r:0], x[63:64-r]} (wires, zero delay).
"""
import json, os, sys

BASE = "/home/hatch/workspace/mix/exploration/adder_lat/w4term"
BDIR = os.path.join(BASE, "bundles")
os.makedirs(BDIR, exist_ok=True)


def rotl_v(sig, r):
    r %= 64
    if r == 0:
        return sig
    return "{%s[%d:0], %s[63:%d]}" % (sig, 63 - r, sig, 64 - r)


def emit_verilog(name, stages, pqrs):
    p, q, r, s = pqrs
    L = []
    L.append("// w4t bundle %s -- auto-generated by bundle_w4t.py." % name)
    L.append("// Bit-exact with screen_w4t.py w4t_model (stages=%s pqrs=%s)." % (stages, list(pqrs)))
    L.append("module %s(input [63:0] val, input [63:0] key, output [63:0] out);" % name)
    L.append("  wire [63:0] x0 = val ^ key;")
    cur = "x0"
    n = 0
    for si, ands in enumerate(stages):
        for a, b in ands:
            n += 1
            w = "w%d" % n
            L.append("  wire [63:0] %s = %s ^ ((%s) & (%s));" % (
                w, cur, rotl_v(cur, a), rotl_v(cur, b)))
            cur = w
        n += 1
        w = "w%d" % n
        L.append("  wire [63:0] %s = %s ^ (%s) ^ (%s) ^ (%s) ^ (%s);" % (
            w, cur, rotl_v(cur, p), rotl_v(cur, q), rotl_v(cur, r), rotl_v(cur, s)))
        cur = w
    L.append("  assign out = %s ^ %s;" % (cur, rotl_v("key", 13)))
    L.append("endmodule")
    return "\n".join(L) + "\n"


MODEL_TMPL = '''"""w4t bundle {name} -- numpy model, bit-exact with screen w4t_model."""
import numpy as np
M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
STAGES = {stages}
PQRS = {pqrs}

def rotl(x, r):
    r %= 64
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64 if r else x

def mix(val, key):
    V = np.uint64(val); K = np.uint64(key)
    p, q, r, s = PQRS
    x = (V ^ K) & M64
    for ands in STAGES:
        for a, b in ands:
            x = (x ^ (rotl(x, a) & rotl(x, b))) & M64
        x = (x ^ rotl(x, p) ^ rotl(x, q) ^ rotl(x, r) ^ rotl(x, s)) & M64
    return int((x ^ rotl(K, 13)) & M64)

def mix_np(V, key):
    V = np.asarray(V, dtype=np.uint64); K = np.uint64(key)
    p, q, r, s = PQRS
    x = (V ^ K) & M64
    for ands in STAGES:
        for a, b in ands:
            x = (x ^ (rotl(x, a) & rotl(x, b))) & M64
        x = (x ^ rotl(x, p) ^ rotl(x, q) ^ rotl(x, r) ^ rotl(x, s)) & M64
    return (x ^ rotl(K, 13)) & M64
'''


def main():
    keeps = []
    with open(os.path.join(BASE, "w4t_screen.jsonl")) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            if d.get("verdict") == "KEEP":
                keeps.append(d)
    print("keeps: %d" % len(keeps))
    for k in keeps:
        name = "w4t_%d" % k["idx"]
        cdir = os.path.join(BDIR, name)
        os.makedirs(cdir, exist_ok=True)
        stages, pqrs = k["stages"], k["pqrs"]
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(emit_verilog(name, stages, pqrs))
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(MODEL_TMPL.format(name=name, stages=stages, pqrs=pqrs))
        sys.path.insert(0, cdir)
        import importlib.util
        spec = importlib.util.spec_from_file_location("m_%s" % name,
                                                      os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        sys.path.pop(0)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": "w4t 4-term rotl-xor linear, screen keep idx %d (fr=%d)" % (k["idx"], k["full_rank"]),
            "screen_idx": k["idx"],
            "stages": stages,
            "pqrs": pqrs,
            "full_rank": k["full_rank"],
            "rtl_top": name,
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
    print("bundled %d -> %s" % (len(keeps), BDIR))


if __name__ == "__main__":
    main()
