#!/usr/bin/env python3
"""Wave-13 stage cost probe: bit-exact single-stage Verilog + numpy model.

Stage (bit-exact mirror of triage_wave13.py 1-stage, K=key):
    x = val ^ key            (pre-whiten; in full chain only before stage 1)
    y = nibble_sbox(x)       (BOYAR19_GF4INV on all 16 nibbles, parallel)
    out = transpose64(y)     (bit(4a+b) -> bit(16b+a), 0-delay wiring)

Two DUTs emitted:
  wave13_stage      : pure stage (sbox + transpose), ports val/key/out,
                      key unused internally (kept for bundle port hygiene)
  wave13_stage_pre  : stage with pre-whiten XOR on the input (real chain stage 1)

Also emits model.py (mix_np) matching wave13_stage_pre, and meta.json.
RTLCHECK via rtl_sim_check.py; S0 via run_synth.py (the only authorized path).
"""
import json
import os

POOL_PATH = ("/home/hatch/workspace/mix/exploration/round24/sbox_pool/"
             "literature_lowlatency_add2.txt")


def load_pool():
    pool = {}
    for line in open(POOL_PATH):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        pool[parts[0]] = [int(x, 16) for x in parts[1:]]
    return pool


BOX = os.environ.get("W13_BOX", "BOYAR19_GF4INV")
TAB = load_pool()[BOX]
assert sorted(TAB) == list(range(16)), f"S-box {BOX} not bijective"

BASE = "/home/hatch/workspace/mix/exploration/adder_lat/wave13"
SBOXDIR = os.path.join(BASE, "sbox_cost", BOX)
CDIR = os.path.join(SBOXDIR, "bundle")
os.makedirs(CDIR, exist_ok=True)


def sbox_case_lines(sig_in, sig_out):
    """Verilog case statement mapping 4-bit nibbles via TAB."""
    lines = [f"    case ({sig_in})"]
    for i, v in enumerate(TAB):
        lines.append(f"      4'h{i:x}: {sig_out} = 4'h{v:x};")
    lines.append("      default: %s = 4'hx;" % sig_out)
    lines.append("    endcase")
    return lines


def emit_stage(name, prewhiten):
    lines = [f"// Wave-13 single stage ({'pre-whitened' if prewhiten else 'pure'}).",
             "// Auto-generated by wave13/gen_stage_bundle.py -- bit-exact with triage_wave13.py",
             f"module {name}(input [63:0] val, input [63:0] key, output [63:0] out);",
             "  wire [63:0] xin;",
             "  wire [63:0] sx;"]
    if prewhiten:
        lines.append("  assign xin = val ^ key;")
    else:
        lines.append("  assign xin = val;")
    # 16 parallel nibble S-boxes
    for a in range(16):
        lines.append(f"  reg [3:0] s{a};")
        lines.append(f"  always @(*) begin")
        lines += ["    " + l for l in sbox_case_lines(f"xin[{4*a+3}:{4*a}]", f"s{a}")]
        lines.append("  end")
        lines.append(f"  assign sx[{4*a+3}:{4*a}] = s{a};")
    # nibble-transpose wiring: out[16*b+a] = sx[4*a+b]
    for a in range(16):
        for b in range(4):
            lines.append(f"  assign out[{16*b+a}] = sx[{4*a+b}];")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def emit_model():
    tablist = ",".join(hex(v) for v in TAB)
    return f'''"""numpy model for {BOX} stage bundle (bit-exact with triage_wave13.py)."""
import numpy as np

_TAB = np.array([{tablist}], dtype=np.uint64)
M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
_TRANS = np.zeros((16, 16), dtype=np.uint64)
for _a in range(16):
    for _v in range(16):
        _w = np.uint64(0)
        for _b in range(4):
            if (_v >> _b) & 1:
                _w |= np.uint64(1) << np.uint64(16 * _b + _a)
        _TRANS[_a, _v] = _w

def _sbox64(x):
    y = np.zeros_like(x)
    for i in range(16):
        y |= _TAB[(x >> np.uint64(4*i)) & np.uint64(0xF)] << np.uint64(4*i)
    return y & M64

def _transpose64(x):
    y = np.zeros_like(x)
    for a in range(16):
        y |= _TRANS[a, (x >> np.uint64(4*a)) & np.uint64(0xF)]
    return y

def mix_np(V, K):
    return _transpose64(_sbox64((V ^ K) & M64)) & M64

def mix(v, k):
    return int(mix_np(np.array([np.uint64(v)]), np.array([np.uint64(k)]))[0])
'''


def main():
    top = f"w13s_{BOX.lower()}"
    with open(os.path.join(CDIR, "rtl.v"), "w") as f:
        f.write(emit_stage(top, prewhiten=True))
    with open(os.path.join(SBOXDIR, "stage_pure.v"), "w") as f:
        f.write(emit_stage(top + "_pure", prewhiten=False))
    with open(os.path.join(CDIR, "model.py"), "w") as f:
        f.write(emit_model())
    import importlib.util
    spec = importlib.util.spec_from_file_location("m", os.path.join(CDIR, "model.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    g1 = m.mix(0x0, 0x123456789ABCDEF0)
    g2 = m.mix(0x123456789ABCDEF0, 0x0)
    meta = {
        "name": top,
        "description": f"Wave-13 single stage ({BOX} nibble-S-box + transpose + pre-whiten); stage-cost probe, not a candidate",
        "rtl_top": top,
        "goldens": [
            {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
            {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
        ],
    }
    with open(os.path.join(CDIR, "meta.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print(f"BOX={BOX} top={top} bundle -> {CDIR}; pure-stage RTL -> {SBOXDIR}/stage_pure.v")


if __name__ == "__main__":
    main()
