#!/usr/bin/env python3
"""Generate bit-exact C implementations (impl.c) for directed-design candidates.

Reads a spec dict (as in specs/batchN_specs.json) and emits impl.c defining
  uint64_t mix_hash(uint64_t v, uint64_t k)
bit-exact vs the candidate's model.py, for the S2/S3/S4 C stages.

Construction: nrounds of x = LIN_r(P_r(SBOX_r(x ^ rk_r)))
  LIN_r(x) = x ^ rotl64(x,a_r) ^ rotl64(x,b_r)
  P: out[pbox[i]] = in[i]
  rk_r = rotl64(key, rot_step*(r+1)) ^ RC[r]

Key schedule spec ("ks" field):
  "golden"                    -> {"rot_step": 13, "rc": RC_GOLDEN}
  {"rot_step": s, "rc": [...]} -> explicit
  {"rot_step": s, "rc": "zero"} -> RC[r] = 0

Usage: mk_c_impl.py <specs.json> <name> <outdir>
       mk_c_impl.py --spec-json '<json>' <name> <outdir>
"""
import json
import os
import sys

RC_GOLDEN = [0x9E3779B97F4A7C15, 0x3C6EF372FE94F82A,
             0xDAA66D2C7DDF743F, 0x78DDE6E5FD29F054,
             0x2545F4914F6CDD1D, 0x94D049BB133111EB]  # spare for 5r/6r

KS_PRESETS = {
    "golden": {"rot_step": 13, "rc": "golden"},
    "norc": {"rot_step": 13, "rc": "zero"},
}


def resolve_ks(ks, nrounds):
    if isinstance(ks, str):
        if ks not in KS_PRESETS:
            raise ValueError(f"unknown ks preset {ks!r}")
        ks = dict(KS_PRESETS[ks])
    rs = ks.get("rot_step", 13)
    rot_steps = list(rs) if isinstance(rs, (list, tuple)) else [rs]
    rc = ks.get("rc", "golden")
    if rc == "golden":
        rc = list(RC_GOLDEN[:nrounds])
    elif rc == "zero":
        rc = [0] * nrounds
    else:
        rc = list(rc)
    assert len(rc) >= nrounds, f"ks rc too short: {len(rc)} < {nrounds}"
    return rot_steps, rc[:nrounds]


def resolve_lin_terms(spec):
    """[(kind, n), ...] for the LIN layer. 'lin_terms' wins; legacy 'rots'
    is interpreted as a rotation pair (D10 batch-13 axis-1 extension)."""
    lt = spec.get("lin_terms")
    if lt is not None:
        terms = [(str(k), int(n)) for k, n in lt]
    else:
        terms = [("rotl", int(v)) for v in spec["rots"]]
    for kind, n in terms:
        assert kind in ("rotl", "shl", "shr"), f"bad lin term {kind!r}"
        assert 0 <= n < 64, f"bad lin amount {n!r}"
    assert 1 <= len(terms) <= 3, f"lin_terms len {len(terms)}"
    return terms


def c_term_expr(kind, n):
    """C expression for one LIN term applied to pre-LIN z (uint64_t wraps)."""
    if n == 0:
        return "z"
    if kind == "rotl":
        return f"rotl64(z, {n})"
    if kind == "shl":
        return f"(z << {n})"
    if kind == "shr":
        return f"(z >> {n})"
    raise ValueError(kind)


def gen_mixed_impl_c(spec):
    """Bit-exact C for a mixed-function-type spec (batch-9+).

    Round i: t = x ^ rk_r; NL (sbox nibble table | chi); P-box; [LIN if enabled].
    """
    nrounds = spec["nrounds"]
    layers = spec["layers"]
    assert len(layers) == nrounds
    pbox = list(spec["pbox"])
    assert len(pbox) == 64 and sorted(pbox) == list(range(64)), "pbox must be a permutation"
    terms = resolve_lin_terms(spec)
    lin_terms = " ^ ".join(["z"] + [c_term_expr(k, n) for k, n in terms])
    lin_mode = spec.get("lin", "all")
    rot_steps, rc = resolve_ks(spec.get("ks", "golden"), nrounds)
    name = spec["name"]
    rk_terms = " ^ ".join(f"rotl64(k, {s}u * (unsigned)(r + 1))" for s in rot_steps)

    L = []
    pat = "".join("S" if x["type"] == "sbox" else "C" for x in layers)
    L.append(f"/* Bit-exact C model for {name} (generated by mk_c_impl.py, mixed layers).")
    L.append(f" * Construction: {nrounds}r mixed NL ({pat}), rk_r = {rk_terms} ^ RC[r] */")
    L.append("#include <stdint.h>")
    L.append("")
    # emit one SBOX table per sbox round
    sbox_rounds = []
    for r, ly in enumerate(layers):
        if ly["type"] == "sbox":
            sb = ", ".join(str(v) for v in ly["sbox"])
            L.append(f"static const uint8_t SBOX_R{r}[16] = {{{sb}}};")
            sbox_rounds.append(r)
        elif ly["type"] == "chi":
            pass
        else:
            raise ValueError(f"unknown layer type {ly['type']!r}")
    L.append("")
    L.append("static const uint8_t PBOX[64] = {%s};" % ", ".join(str(v) for v in pbox))
    L.append("")
    L.append("static const uint64_t RC[%d] = {%s};" % (
        nrounds, ", ".join("0x%016XULL" % v for v in rc)))
    L.append("")
    L.append("static uint64_t rotl64(uint64_t x, unsigned r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    L.append("")
    L.append("uint64_t mix_hash(uint64_t v, uint64_t k) {")
    L.append("    uint64_t x = v;")
    L.append(f"    for (int r = 0; r < {nrounds}; r++) {{")
    L.append(f"        uint64_t rk = ({rk_terms}) ^ RC[r];")
    L.append("        uint64_t t = x ^ rk;")
    L.append("        uint64_t y;")
    L.append("        switch (r) {")
    for r, ly in enumerate(layers):
        if ly["type"] == "sbox":
            L.append(f"            case {r}: {{ /* S-box round */")
            L.append("                y = 0;")
            L.append("                for (int n = 0; n < 16; n++)")
            L.append(f"                    y |= (uint64_t)SBOX_R{r}[(t >> (4*n)) & 0xF] << (4*n);")
            L.append("                break;")
            L.append("            }")
        else:
            a, b, c = (int(v) for v in ly["chi"])
            flavor = ly["flavor"]
            L.append(f"            case {r}: {{ /* chi round ({flavor}) */")
            L.append(f"                uint64_t ra = rotl64(t, {a});")
            L.append(f"                uint64_t rb = rotl64(t, {b});")
            L.append(f"                uint64_t rc_ = rotl64(t, {c});")
            if flavor == "and":
                L.append("                y = t ^ (ra & rb) ^ rc_;")
            elif flavor == "keccak":
                L.append("                y = t ^ (ra & ~rb) ^ rc_;")
            else:
                raise ValueError(f"unknown chi flavor {flavor!r}")
            L.append("                break;")
            L.append("            }")
    L.append("            default: y = t; break;")
    L.append("        }")
    L.append("        /* P-box */")
    L.append("        uint64_t z = 0;")
    L.append("        for (int i = 0; i < 64; i++)")
    L.append("            z |= ((y >> i) & 1ULL) << PBOX[i];")
    for r, ly in enumerate(layers):
        lt = ly["type"]
        do_lin = (lin_mode == "all"
                  or (lin_mode == "sbox" and lt == "sbox")
                  or (lin_mode == "chi" and lt == "chi"))
        if do_lin:
            L.append(f"        if (r == {r}) z = {lin_terms};")
    L.append("        x = z;")
    L.append("    }")
    L.append("    return x;")
    L.append("}")
    return "\n".join(L) + "\n"


def gen_impl_c(spec):
    nrounds = spec["nrounds"]
    if spec.get("sbox_rounds"):
        sboxes = [list(s) for s in spec["sbox_rounds"]]
    else:
        sboxes = [list(spec["sbox"])] * nrounds
    assert len(sboxes) == nrounds
    pbox = list(spec["pbox"])
    assert len(pbox) == 64 and sorted(pbox) == list(range(64)), "pbox must be a permutation"
    rots = spec["rots"]
    if spec.get("rots_varying"):
        rots_per = [tuple(r) for r in rots]
    elif isinstance(rots[0], (list, tuple)):
        rots_per = [tuple(r) for r in rots]
    else:
        rots_per = [tuple(rots)] * nrounds
    assert len(rots_per) == nrounds
    rot_steps, rc = resolve_ks(spec.get("ks", "golden"), nrounds)
    name = spec["name"]
    rk_terms = " ^ ".join(f"rotl64(k, {s}u * (unsigned)(r + 1))" for s in rot_steps)

    L = []
    L.append(f"/* Bit-exact C model for {name} (generated by mk_c_impl.py).")
    L.append(f" * Construction: {nrounds}r SPN, rk_r = {rk_terms} ^ RC[r] */")
    L.append("#include <stdint.h>")
    L.append("")
    for r in range(nrounds):
        sb = ", ".join(str(v) for v in sboxes[r])
        L.append(f"static const uint8_t SBOX_R{r}[16] = {{{sb}}};")
    L.append("")
    L.append("static const uint8_t PBOX[64] = {%s};" % ", ".join(str(v) for v in pbox))
    L.append("")
    L.append("static const uint64_t RC[%d] = {%s};" % (
        nrounds, ", ".join("0x%016XULL" % v for v in rc)))
    L.append("")
    L.append("static uint64_t rotl64(uint64_t x, unsigned r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    L.append("")
    L.append("uint64_t mix_hash(uint64_t v, uint64_t k) {")
    L.append("    uint64_t x = v;")
    L.append(f"    for (int r = 0; r < {nrounds}; r++) {{")
    L.append(f"        uint64_t rk = ({rk_terms}) ^ RC[r];")
    L.append("        uint64_t t = x ^ rk;")
    L.append("        /* S-box (per-round table) */")
    L.append("        uint64_t y = 0;")
    L.append("        for (int n = 0; n < 16; n++) {")
    L.append("            uint8_t nib;")
    L.append("            switch (r) {")
    for r in range(nrounds):
        L.append(f"                case {r}: nib = SBOX_R{r}[(t >> (4*n)) & 0xF]; break;")
    L.append("                default: nib = 0; break;")
    L.append("            }")
    L.append("            y |= (uint64_t)nib << (4*n);")
    L.append("        }")
    L.append("        /* P-box */")
    L.append("        uint64_t z = 0;")
    L.append("        for (int i = 0; i < 64; i++)")
    L.append("            z |= ((y >> i) & 1ULL) << PBOX[i];")
    L.append("        /* LIN: per-round rotation pair */")
    L.append("        switch (r) {")
    for r in range(nrounds):
        a, b = rots_per[r]
        L.append(f"            case {r}: x = z ^ rotl64(z, {a}) ^ rotl64(z, {b}); break;")
    L.append("            default: x = z; break;")
    L.append("        }")
    L.append("    }")
    L.append("    return x;")
    L.append("}")
    return "\n".join(L) + "\n"


def main():
    args = sys.argv[1:]
    if args[0] == "--spec-json":
        spec = json.loads(args[1])
        name, outdir = args[2], args[3]
    else:
        specs = json.load(open(args[0]))
        name, outdir = args[1], args[2]
        spec = next(s for s in specs if s["name"] == name)
    os.makedirs(outdir, exist_ok=True)
    if "layers" in spec:
        with open(os.path.join(outdir, "impl.c"), "w") as f:
            f.write(gen_mixed_impl_c(spec))
        print(f"Wrote {outdir}/impl.c for {name} (mixed)")
        return
    with open(os.path.join(outdir, "impl.c"), "w") as f:
        f.write(gen_impl_c(spec))
    print(f"Wrote {outdir}/impl.c for {name}")


if __name__ == "__main__":
    main()
