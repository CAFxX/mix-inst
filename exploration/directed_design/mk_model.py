#!/usr/bin/env python3
"""Generate model.py + meta.json for a directed-design candidate.

Reads a spec dict (specs/batchN_specs.json) and writes into
fast_battery/candidates/<name>/: model.py (numpy bit-exact model),
meta.json (with goldens computed from the model).

Supports: nrounds, sbox/sbox_rounds, pbox, rots (fixed or per-round),
ks dict {"rot_step": s|[s1,s2], "rc": "golden"|"zero"|[..]}.

Usage: mk_model.py <specs.json> <name>
       mk_model.py --spec-json '<json>' <name>
Does NOT overwrite an existing model.py (safety: S1 results may exist).
Pass --force to overwrite.
"""
import importlib.util
import json
import os
import sys

FB = "/home/hatch/workspace/mix/exploration/fast_battery"
RC_GOLDEN = [0x9E3779B97F4A7C15, 0x3C6EF372FE94F82A,
             0xDAA66D2C7DDF743F, 0x78DDE6E5FD29F054,
             0x2545F4914F6CDD1D, 0x94D049BB133111EB]


def resolve_ks(ks, nrounds):
    if ks is None or ks == "golden":
        return [13], list(RC_GOLDEN[:nrounds])
    if ks == "norc":
        return [13], [0] * nrounds
    assert isinstance(ks, dict)
    rs = ks.get("rot_step", 13)
    steps = list(rs) if isinstance(rs, (list, tuple)) else [rs]
    rc = ks.get("rc", "golden")
    if rc == "golden":
        rc = list(RC_GOLDEN[:nrounds])
    elif rc == "zero":
        rc = [0] * nrounds
    else:
        rc = list(rc[:nrounds])
    return steps, rc


MODEL_TMPL = '''"""Self-contained numpy model for {name} (generated by mk_model.py).

Construction (matches directed_design/gen_verilog.py):
  round i: x = LIN_i(P(SBOX_i(x ^ rk_i)))
  LIN_i(x) = x ^ rotl64(x,a) ^ rotl64(x,b)  (a,b per round: {rots_desc})
  P: out[P[i]] = in[i]
  rk_i = {ks_desc}
"""
import numpy as np

SBOX_ROUNDS = {sbox_rounds}
PBOX = {pbox}
RC = np.array([{rc}], dtype=np.uint64)
M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
ROUNDS = {nrounds}
ROTS = {rots}
KS_ROT_STEPS = {ks_steps}


def _rots(r):
    if isinstance(ROTS[0], (list, tuple)):
        return ROTS[r][0], ROTS[r][1]
    return ROTS[0], ROTS[1]


def _rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def _sbox64(x, r):
    sb = np.array(SBOX_ROUNDS[r], dtype=np.uint64)
    y = np.zeros_like(x)
    for i in range(16):
        y |= sb[((x >> np.uint64(4 * i)) & np.uint64(0xF))] << np.uint64(4 * i)
    return y & M64


def _pbox64(x):
    y = np.zeros_like(x)
    for i in range(64):
        y |= ((x >> np.uint64(i)) & np.uint64(1)) << np.uint64(PBOX[i])
    return y & M64


def _lin(x, r):
    a, b = _rots(r)
    return (x ^ _rotl(x, a) ^ _rotl(x, b)) & M64


def _round(x, key, i):
    rk = np.uint64(0)
    for s in KS_ROT_STEPS:
        rk ^= _rotl(key, s * (i + 1))
    rk ^= RC[i]
    return _lin(_pbox64(_sbox64(x ^ rk, i)), i)


def mix_np(V, K):
    x = np.asarray(V, dtype=np.uint64)
    k = np.asarray(K, dtype=np.uint64)
    for i in range(ROUNDS):
        x = _round(x, k, i)
    return x & M64


def mix(v, k):
    return int(mix_np(np.uint64(v), np.uint64(k)))
'''


MIXED_MODEL_TMPL = '''"""Self-contained numpy model for {name} (generated by mk_model.py, mixed layers).

Construction (matches directed_design/gen_verilog.py gen_mixed_verilog):
  round i: x = LIN?(P(NL_i(x ^ rk_i)))
  NL_i = SBOX (nibble table) | chi: x ^ (rotl(x,a)&rotl(x,b)) ^ rotl(x,c)  [and]
                                 x ^ (rotl(x,a)&~rotl(x,b)) ^ rotl(x,c) [keccak]
  P: out[P[i]] = in[i]
  LIN (where enabled): {lin_desc}
  rk_i = {ks_desc}
  pattern: {pattern}
"""
import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
SBOXES = {sboxes}
PBOX = {pbox}
RC = np.array([{rc}], dtype=np.uint64)
ROUNDS = {nrounds}
# LAYERS[i] = ("sbox", sbox_key) | ("chi", (a,b,c), flavor) ; LIN_ON[i] bool
LAYERS = {layers}
LIN_ON = {lin_on}
KS_ROT_STEPS = {ks_steps}


def _rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def _sbox64(x, key):
    sb = np.array(SBOXES[key], dtype=np.uint64)
    y = np.zeros_like(x)
    for i in range(16):
        y |= sb[((x >> np.uint64(4 * i)) & np.uint64(0xF))] << np.uint64(4 * i)
    return y & M64


def _chi(x, a, b, c, flavor):
    ra, rb, rc = _rotl(x, a), _rotl(x, b), _rotl(x, c)
    if flavor == "and":
        return (x ^ (ra & rb) ^ rc) & M64
    if flavor == "keccak":
        return (x ^ (ra & ((~rb) & M64)) ^ rc) & M64
    raise ValueError(flavor)


def _pbox64(x):
    y = np.zeros_like(x)
    for i in range(64):
        y |= ((x >> np.uint64(i)) & np.uint64(1)) << np.uint64(PBOX[i])
    return y & M64


def _lin(x):
    return ({lin_expr}) & M64


def _round(x, key, i):
    rk = np.uint64(0)
    for s in KS_ROT_STEPS:
        rk ^= _rotl(key, s * (i + 1))
    rk ^= RC[i]
    t = x ^ rk
    typ = LAYERS[i][0]
    if typ == "sbox":
        y = _sbox64(t, LAYERS[i][1])
    elif typ == "chi":
        (a, b, c), flavor = LAYERS[i][1], LAYERS[i][2]
        y = _chi(t, a, b, c, flavor)
    else:
        raise ValueError(typ)
    z = _pbox64(y)
    if LIN_ON[i]:
        z = _lin(z)
    return z


def mix_np(V, K):
    x = np.asarray(V, dtype=np.uint64)
    k = np.asarray(K, dtype=np.uint64)
    for i in range(ROUNDS):
        x = _round(x, k, i)
    return x & M64


def mix(v, k):
    return int(mix_np(np.uint64(v), np.uint64(k)))
'''


def _resolve_sbox_key(sb):
    for k, v in SBOXES_NAMED.items():
        if list(v) == list(sb):
            return k
    raise ValueError("sbox table not in named set")


SBOXES_NAMED = {}


def main_mixed(spec, name, force):
    nrounds = spec["nrounds"]
    layers = spec["layers"]
    assert len(layers) == nrounds
    # collect named sboxes
    sboxes = {}
    layer_reprs = []
    lin_mode = spec.get("lin", "all")
    lin_on = []
    for L in layers:
        if L["type"] == "sbox":
            sb = list(L["sbox"])
            key = "R"
            # name by matching known tables
            for nk, nv in KNOWN_SBOXES.items():
                if list(nv) == sb:
                    key = nk
                    break
            sboxes[key] = sb
            layer_reprs.append(("sbox", key))
        elif L["type"] == "chi":
            a, b, c = (int(v) for v in L["chi"])
            flavor = L["flavor"]
            assert flavor in ("and", "keccak")
            layer_reprs.append(("chi", (a, b, c), flavor))
        else:
            raise ValueError(L["type"])
        lt = L["type"]
        lin_on.append(lin_mode == "all"
                      or (lin_mode == "sbox" and lt == "sbox")
                      or (lin_mode == "chi" and lt == "chi"))
    pbox = list(spec["pbox"])
    terms = resolve_lin_terms(spec)
    lin_expr = " ^ ".join(["x"] + [model_term_expr(k, n) for k, n in terms])
    lin_desc = " ^ ".join(["x"] + [f"{k}{n}" for k, n in terms])
    ks_steps, rc = resolve_ks(spec.get("ks", "golden"), nrounds)
    ks_desc = " ^ ".join([f"rotl64(key,{s}*(i+1))" for s in ks_steps] + ["RC[i]"])
    pattern = "".join("S" if L["type"] == "sbox" else "C" for L in layers)

    outdir = os.path.join(FB, "candidates", name)
    os.makedirs(outdir, exist_ok=True)
    mpath = os.path.join(outdir, "model.py")
    if os.path.exists(mpath) and not force:
        print(f"SKIP {mpath} exists (use --force)")
        return
    with open(mpath, "w") as f:
        f.write(MIXED_MODEL_TMPL.format(
            name=name,
            ks_desc="rk_i = " + ks_desc,
            pattern=pattern,
            sboxes=sboxes,
            pbox=pbox,
            rc=", ".join(str(int(v)) for v in rc),
            nrounds=nrounds,
            layers=layer_reprs,
            lin_on=lin_on,
            ks_steps=ks_steps,
            lin_expr=lin_expr,
            lin_desc=lin_desc,
        ))
    # compute goldens from the fresh model
    spec_mod = importlib.util.spec_from_file_location("model_" + name, mpath)
    m = importlib.util.module_from_spec(spec_mod)
    spec_mod.loader.exec_module(m)
    keys = ["0x123456789abcdef0", "0x0"]
    goldens = []
    for vk, kk in [("0x0", keys[0]), (keys[0], keys[1])]:
        out = m.mix(int(vk, 16), int(kk, 16))
        goldens.append({"val": vk, "key": kk, "out": "0x%x" % out})
    meta = {
        "name": name,
        "description": spec.get("desc", ""),
        "batch": spec.get("batch", "batch9"),
        "screen_keys": keys,
        "practrand_keys": keys,
        "rtl_top": name,
        "goldens": goldens,
    }
    with open(os.path.join(outdir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print(f"Wrote {mpath} + meta.json; goldens: {[g['out'] for g in goldens]}")


KNOWN_SBOXES = {
    "R": [0,1,2,3,4,6,8,11,13,9,7,15,12,10,5,14],
    "M": [12,10,13,3,14,11,15,7,8,9,1,5,0,2,4,6],
    "U": [8,4,3,14,9,13,6,12,2,7,0,15,5,1,10,11],
}


def resolve_lin_terms(spec):
    """[(kind, n), ...] for the LIN layer. 'lin_terms' wins; legacy 'rots'
    is interpreted as a rotation pair (D10 batch-13 axis-1 extension)."""
    lt = spec.get("lin_terms")
    if lt is not None:
        terms = [(str(k), int(n)) for k, n in lt]
    else:
        terms = [("rotl", int(v)) for v in spec["rots"]]
    for kind, n in terms:
        assert kind in ("rotl", "shl", "shr"), f"bad lin term {kind!r}"
        assert 0 <= n < 64, f"bad lin amount {n!r}"
    assert 1 <= len(terms) <= 3, f"lin_terms len {len(terms)}"
    return terms


def model_term_expr(kind, n):
    """numpy expression for one LIN term applied to pre-LIN x (uint64 wraps)."""
    if n == 0:
        return "x"
    if kind == "rotl":
        return f"_rotl(x, {n})"
    if kind == "shl":
        return f"(x << np.uint64({n}))"
    if kind == "shr":
        return f"(x >> np.uint64({n}))"
    raise ValueError(kind)


def main():
    args = sys.argv[1:]
    force = "--force" in args
    args = [a for a in args if a != "--force"]
    if args[0] == "--spec-json":
        spec = json.loads(args[1]); name = args[2]
    else:
        specs = json.load(open(args[0])); name = args[1]
        spec = next(s for s in specs if s["name"] == name)
    if "layers" in spec:
        main_mixed(spec, name, force)
        return
    nrounds = spec["nrounds"]
    if spec.get("sbox_rounds"):
        sboxes = [list(s) for s in spec["sbox_rounds"]]
    else:
        sboxes = [list(spec["sbox"])] * nrounds
    pbox = list(spec["pbox"])
    rots = spec["rots"]
    ks_steps, rc = resolve_ks(spec.get("ks", "golden"), nrounds)
    ks_desc = " ^ ".join([f"rotl64(key,{s}*(i+1))" for s in ks_steps] + ["RC[i]"])

    outdir = os.path.join(FB, "candidates", name)
    os.makedirs(outdir, exist_ok=True)
    mpath = os.path.join(outdir, "model.py")
    if os.path.exists(mpath) and not force:
        print(f"SKIP {mpath} exists (use --force)")
        return
    with open(mpath, "w") as f:
        f.write(MODEL_TMPL.format(
            name=name,
            rots_desc=str(rots),
            ks_desc="rk_i = " + ks_desc,
            sbox_rounds=sboxes,
            pbox=pbox,
            rc=", ".join(str(int(v)) for v in rc),
            nrounds=nrounds,
            rots=rots,
            ks_steps=ks_steps,
        ))
    # compute goldens from the fresh model
    spec_mod = importlib.util.spec_from_file_location("model_" + name, mpath)
    m = importlib.util.module_from_spec(spec_mod)
    spec_mod.loader.exec_module(m)
    keys = ["0x123456789abcdef0", "0x0"]
    goldens = []
    for vk, kk in [("0x0", keys[0]), (keys[0], keys[1])]:
        out = m.mix(int(vk, 16), int(kk, 16))
        goldens.append({"val": vk, "key": kk, "out": "0x%x" % out})
    meta = {
        "name": name,
        "description": spec.get("desc", ""),
        "batch": "batch4",
        "screen_keys": keys,
        "practrand_keys": keys,
        "rtl_top": name,  # REQUIRED: s0_delay.py reads meta["rtl_top"]; dd7 batch-7 bundles shipped without it -> S0 INFRA_FAIL (KeyError) on all 6 shards of dd7-hetero-3r-20261009-b (run 37942134112), 2026-10-09. The bundle packager must always emit a valid rtl_top matching the top module in rtl.v.
        "goldens": goldens,
    }
    with open(os.path.join(outdir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print(f"Wrote {mpath} + meta.json; goldens: {[g['out'] for g in goldens]}")


if __name__ == "__main__":
    main()
