"""6-stage AND cascade, wider progressive (wave-9)
Adder-latency wave-9 (generated by gen_wave9.py). AND-specific co-design:
danger-zone-free rotations, progressive AND-pair differences.
"""
import numpy as np
M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
def _rotl(x, r):
    r %= 64
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64 if r else x
STAGES = [(2, 5, 11), (3, 13, 19), (7, 21, 5), (11, 25, 13), (13, 26, 7), (19, 43, 17)]
KEY_IN = 0
KEY_OUT = 13
def mix_np(V, K):
    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)
    x = (x ^ k) & M64
    for i,(a,b,c) in enumerate(STAGES):
        t = (x ^ (_rotl(x,a) & _rotl(x,b)) ^ _rotl(x,c)) & M64
        x = t
    x = (x ^ _rotl(k, KEY_OUT)) & M64
    return x & M64
def mix(v, k):
    return int(mix_np(np.uint64(v), np.uint64(k)))
