"""6-stage alternating AND/OR cascade (wave-9)
Adder-latency wave-9 (generated by gen_wave9.py). Alternating AND/OR cascade.
"""
import numpy as np
M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
def _rotl(x, r):
    r %= 64
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64 if r else x
STAGES = [(1, 3, 13), (5, 12, 7), (7, 18, 11), (11, 24, 5), (13, 26, 17), (17, 38, 23)]
# op[i] = 0 for AND, 1 for OR
OPS = [0, 1, 0, 1, 0, 1]
KEY_OUT = 13
def mix_np(V, K):
    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)
    x = (x ^ k) & M64
    for i,((a,b,c),op) in enumerate(zip(STAGES, OPS)):
        if op == 0:
            t = (x ^ (_rotl(x,a) & _rotl(x,b)) ^ _rotl(x,c)) & M64
        else:
            t = (x ^ (_rotl(x,a) | _rotl(x,b)) ^ _rotl(x,c)) & M64
        x = t
    x = (x ^ _rotl(k, KEY_OUT)) & M64
    return x & M64
def mix(v, k):
    return int(mix_np(np.uint64(v), np.uint64(k)))
