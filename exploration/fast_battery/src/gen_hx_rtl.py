#!/usr/bin/env python3
"""Generate combinational Verilog for h_xorspn3 (fast staged battery).

Emits candidates/h_xorspn3/rtl.v with the S-box as direct boolean assigns
(no Verilog functions: function-inlined wire names break analyze2.py's
parser). Bit-identical to impl.c / model.py (verified by iverilog RTLCHECK).

Usage: python3 src/gen_hx_rtl.py   # writes candidates/h_xorspn3/rtl.v
"""
import os
import re

FB = "/home/hatch/workspace/mix/exploration/fast_battery"

# S1 = THF/Blink 4-bit S-box, DNF per output bit (from round4/gen_hflat.py)
S1_DNF = [
    "(x[2] & ~x[0]) | (x[3] & ~x[0]) | (~x[2] & ~x[1] & x[0])",
    "(x[3] & x[2] & ~x[1]) | (~x[3] & x[2] & ~x[0]) | (x[3] & ~x[2] & x[1]) | (~x[3] & x[1] & ~x[0]) | (x[3] & x[2] & x[0])",
    "(x[3] & x[2] & ~x[1]) | (~x[3] & x[1] & x[0]) | (x[3] & ~x[2] & x[0]) | (x[2] & x[1] & ~x[0])",
    "(x[2] & x[1]) | (x[2] & x[0]) | (x[3] & ~x[2] & ~x[0])",
]
PERM = [0, 10, 5, 15, 14, 4, 11, 1, 9, 3, 12, 6, 7, 13, 2, 8]
GOLDEN = 0x9E3779B97F4A7C15
M64 = (1 << 64) - 1


def dnf(sig, base, bit):
    """S1_DNF[bit] with x[k] -> sig[base+k]."""
    return re.sub(r"x\[(\d)\]",
                  lambda m: "%s[%d]" % (sig, base + int(m.group(1))),
                  S1_DNF[bit])


def gen():
    L = []
    A = L.append
    A("// mix_h_xorspn3: GENERATED by fast_battery/src/gen_hx_rtl.py -- do not edit by hand")
    A("// xorshift64 pre-diffusion + 3-round SPN (S1 S-box + Midori M + nibble shuffle)")
    A("module mix_h_xorspn3(input wire [63:0] val, input wire [63:0] key,")
    A("                     output wire [63:0] out);")
    A("")
    A("  // xorshift64(val ^ key)")
    A("  wire [63:0] xs0 = val ^ key;")
    A("  wire [63:0] xs1 = xs0 ^ (xs0 >> 12);")
    A("  wire [63:0] xs2 = xs1 ^ (xs1 << 25);")
    A("  wire [63:0] x0  = xs2 ^ (xs2 >> 27);")
    A("")
    A("  // round keys rk_i = rotl64(key, 13*i) ^ i*GOLDEN")
    for i in range(1, 5):
        r = 13 * i
        A("  wire [63:0] rk%d = {key[%d:0], key[63:%d]} ^ 64'h%016x;"
          % (i, 63 - r, 64 - r, (i * GOLDEN) & M64))
    A("")
    prev = "x0"
    for rnd in range(1, 4):
        k, s, m, f = (("r%d%s" % (rnd, x)) for x in ("k", "s", "m", "f"))
        A("  // ---- round %d ----" % rnd)
        A("  wire [63:0] %s = %s ^ rk%d;" % (k, prev, rnd))
        for b in range(16):
            A("  wire [3:0] %s_%d;" % (s, b))
            for bit in range(4):
                A("  assign %s_%d[%d] = %s;" % (s, b, bit, dnf(k, 4 * b, bit)))
        A("  wire [63:0] %s = {%s};" % (s, ", ".join("%s_%d" % (s, b) for b in range(15, -1, -1))))
        A("  wire [63:0] %s;" % m)
        for c in range(4):
            n = ["%s[%d:%d]" % (s, 4 * (4 * c + j) + 3, 4 * (4 * c + j)) for j in range(4)]
            A("  wire [3:0] %s_p%d = %s ^ %s ^ %s ^ %s;" % (m, c, *n))
            for j in range(4):
                A("  assign %s[%d:%d] = %s_p%d ^ %s;"
                  % (m, 4 * (4 * c + j) + 3, 4 * (4 * c + j), m, c, n[j]))
        A("  wire [63:0] %s = {%s};" % (f, ", ".join(
            "%s[%d:%d]" % (m, 4 * PERM[i] + 3, 4 * PERM[i]) for i in range(15, -1, -1))))
        A("")
        prev = f
    A("  assign out = r3f ^ rk4;")
    A("")
    A("endmodule")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = os.path.join(FB, "candidates", "h_xorspn3", "rtl.v")
    open(out, "w").write(gen())
    print("wrote", out)
