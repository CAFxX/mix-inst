#!/usr/bin/env python3
"""Fused Wave-1 generator: single source of truth for fused nonlinear-diffusive candidates.

Each candidate spec -> fast_battery/candidates/<name>/{model.py, impl.c, rtl.v, meta.json}
with bit-identical semantics in Python/numpy, C, and Verilog.

Opcodes (x is the 64-bit state, r_ are rotl(x, rot)):
  wao  : x ^= (ra&rb)|(rc&rd)|(re&rf) ^ rg ^ rh      (wide AND-OR, degree 2, 8-input fan-in)
  maj  : x ^= maj(ra,rb,rc,rd,re) ^ rf ^ rg          (5-input majority, degree 3, 7-input fan-in)
  dchi : x ^= ((~ra)&rb) ^ ((~rc)&rd) ^ re ^ rf      (dual chi parallel, degree 2, 6-input fan-in)

Key schedule: pre-whiten x ^= k; post x ^= rotl(k,13) (al_cascad convention).
"""
import json, os, shutil, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

# Rotation sets: chosen for spread (distinct within stage, no small arithmetic progressions
# within a stage, covering low/mid/high ranges across stages).
# wao: 8 rots/stage; maj: 7 rots/stage; dchi: 6 rots/stage.
SPECS = [
    # (name, op, [stage rotation tuples], description)
    ("fz_wao3", "wao", [
        (1, 7, 13, 29, 41, 53, 5, 23),
        (3, 11, 19, 37, 47, 59, 9, 31),
        (7, 17, 23, 43, 51, 61, 13, 35),
    ], "3-stage wide AND-OR: x ^= (ra&rb)|(rc&rd)|(re&rf) ^ rg ^ rh"),
    ("fz_wao2", "wao", [
        (1, 9, 17, 29, 43, 55, 7, 25),
        (5, 15, 27, 39, 51, 61, 11, 33),
    ], "2-stage wide AND-OR: x ^= (ra&rb)|(rc&rd)|(re&rf) ^ rg ^ rh"),
    ("fz_maj3", "maj", [
        (1, 8, 15, 29, 43, 7, 23),
        (5, 13, 25, 39, 53, 11, 31),
        (9, 19, 33, 47, 59, 17, 37),
    ], "3-stage 5-input majority: x ^= maj(ra,rb,rc,rd,re) ^ rf ^ rg"),
    ("fz_maj2", "maj", [
        (1, 11, 23, 37, 51, 7, 29),
        (5, 17, 31, 45, 59, 13, 35),
    ], "2-stage 5-input majority: x ^= maj(ra,rb,rc,rd,re) ^ rf ^ rg"),
    ("fz_dchi3", "dchi", [
        (1, 5, 13, 29, 7, 23),
        (3, 11, 21, 39, 15, 33),
        (7, 17, 31, 47, 19, 41),
    ], "3-stage dual-chi: x ^= ((~ra)&rb) ^ ((~rc)&rd) ^ re ^ rf"),
    ("fz_dchi2", "dchi", [
        (1, 7, 17, 33, 9, 27),
        (5, 15, 29, 45, 19, 39),
    ], "2-stage dual-chi: x ^= ((~ra)&rb) ^ ((~rc)&rd) ^ re ^ rf"),
]

def rotl_expr_py(r):
    return f"_rotl(x,{r})"

def gen_model(name, op, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused1.py)."""',
        "import numpy as np",
        "",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0:",
        "        return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        "",
        "def _maj5(a, b, c, d, e):",
        "    return ((a&b)|(a&c)|(a&d)|(a&e)|(b&c)|(b&d)|(b&e)|(c&d)|(c&e)|(d&e)) & M64",
        "",
        f"STAGES = {stages!r}",
        "",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        rs = ", ".join(f"_rotl(x,{r})" for r in rots)
        lines.append(f"    # stage {i}")
        if op == "wao":
            a, b, c, d, e, f, g, h = [f"r{j}" for j in range(8)]
            lines.append(f"    {a},{b},{c},{d},{e},{f},{g},{h} = {rs}")
            lines.append(f"    x = (x ^ (({a}&{b})|({c}&{d})|({e}&{f})) ^ {g} ^ {h}) & M64")
        elif op == "maj":
            a, b, c, d, e, f, g = [f"r{j}" for j in range(7)]
            lines.append(f"    {a},{b},{c},{d},{e},{f},{g} = {rs}")
            lines.append(f"    x = (x ^ _maj5({a},{b},{c},{d},{e}) ^ {f} ^ {g}) & M64")
        elif op == "dchi":
            a, b, c, d, e, f = [f"r{j}" for j in range(6)]
            lines.append(f"    {a},{b},{c},{d},{e},{f} = {rs}")
            lines.append(f"    x = (x ^ ((~{a})&{b}) ^ ((~{c})&{d}) ^ {e} ^ {f}) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def rotl_c(var, r):
    if r == 0:
        return var
    return f"((({var}) << {r}) | (({var}) >> {64-r}))"

def gen_c(name, op, stages, desc):
    lines = [
        f"// Fused candidate {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x, int r) {",
        "    r &= 63; if (!r) return x;",
        "    return (x << r) | (x >> (64 - r));",
        "}",
        "static uint64_t maj5(uint64_t a, uint64_t b, uint64_t c, uint64_t d, uint64_t e) {",
        "    return (a&b)|(a&c)|(a&d)|(a&e)|(b&c)|(b&d)|(b&e)|(c&d)|(c&e)|(d&e);",
        "}",
        "uint64_t mix_hash(uint64_t v, uint64_t k) {",
        "    uint64_t x = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    uint64_t {rv} = rotl64(x, {r});")
            rvars.append(rv)
        if op == "wao":
            a, b, c, d, e, f, g, h = rvars
            lines.append(f"    x ^= (({a}&{b})|({c}&{d})|({e}&{f})) ^ {g} ^ {h};")
        elif op == "maj":
            a, b, c, d, e, f, g = rvars
            lines.append(f"    x ^= maj5({a},{b},{c},{d},{e}) ^ {f} ^ {g};")
        elif op == "dchi":
            a, b, c, d, e, f = rvars
            lines.append(f"    x ^= ((~{a})&{b}) ^ ((~{c})&{d}) ^ {e} ^ {f};")
    lines += [
        "    x ^= rotl64(k, 13);",
        "    return x;",
        "}",
        "",
    ]
    return "\n".join(lines)

def rotl_v(sig, r):
    # rotl by r: {x[63-r:0], x[63:64-r]}
    if r == 0:
        return sig
    return f"{{{sig}[{63-r}:0], {sig}[63:{64-r}]}}"

def gen_v(name, op, stages, desc):
    lines = [
        f"// {name}: {desc} (generated by gen_fused1.py)",
        f"module {name}(",
        "    input [63:0] v,",
        "    input [63:0] k,",
        "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    wire [63:0] {rv} = {rotl_v(f'x{i}', r)};")
            rvars.append(rv)
        if op == "wao":
            a, b, c, d, e, f, g, h = rvars
            lines.append(f"    wire [63:0] x{i+1} = x{i} ^ (({a}&{b})|({c}&{d})|({e}&{f})) ^ {g} ^ {h};")
        elif op == "maj":
            a, b, c, d, e, f, g = rvars
            maj = "|".join(f"({x}&{y})" for x in rvars[:5] for y in rvars[:5] if rvars.index(x) < rvars.index(y))
            lines.append(f"    wire [63:0] x{i+1} = x{i} ^ ({maj}) ^ {f} ^ {g};")
        elif op == "dchi":
            a, b, c, d, e, f = rvars
            lines.append(f"    wire [63:0] x{i+1} = x{i} ^ ((~{a})&{b}) ^ ((~{c})&{d}) ^ {e} ^ {f};")
    n = len(stages)
    lines += [
        "    wire [63:0] kr = {k[50:0], k[63:51]};",
        f"    assign o = x{n} ^ kr;",
        "endmodule",
        "",
    ]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, op, stages, desc) in SPECS:
        if only and name not in only:
            continue
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        model_src = gen_model(name, op, stages, desc)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(model_src)
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_c(name, op, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_v(name, op, stages, desc))
        # meta.json with goldens from the model
        sys.path.insert(0, cdir)
        import importlib.util
        # fresh module load under unique name
        spec = importlib.util.spec_from_file_location("fz_" + name, os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: golden1={g1:#018x} golden2={g2:#018x}", flush=True)

if __name__ == "__main__":
    main()
