#!/usr/bin/env python3
"""Fused Wave-11: pure chi replacement.

Wave-10 MUX: triage PASS but 31.6u (5.27u/stage, too slow).
Wave-9 chi(x,..): x cancels (chi linear in first arg).

Wave-11: x = chi(ra,rb,rc) ^ chi(rd,re,rf) ^ chi(rg,rh,ri)
Pure replacement (no ^x), no linear trail. Chi is fast.
3 chi per stage, XORed. Est ~4-5u/stage.
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_chir_5", 5, [
        (3, 11, 23, 31, 43, 53, 7, 17, 29),
        (7, 17, 29, 37, 47, 59, 5, 13, 27),
        (5, 13, 27, 41, 49, 61, 9, 19, 33),
        (9, 19, 33, 39, 51, 57, 11, 23, 35),
        (11, 23, 35, 45, 55, 63, 13, 25, 37),
    ], "5-stage pure chi replacement: x = chi(ra,rb,rc)^chi(rd,re,rf)^chi(rg,rh,ri)"),
    ("fz_chir_6", 6, [
        (3, 11, 23, 31, 43, 53, 7, 17, 29),
        (7, 17, 29, 37, 47, 59, 5, 13, 27),
        (5, 13, 27, 41, 49, 61, 9, 19, 33),
        (9, 19, 33, 39, 51, 57, 11, 23, 35),
        (11, 23, 35, 45, 55, 63, 13, 25, 37),
        (13, 25, 37, 47, 57, 61, 15, 27, 39),
    ], "6-stage pure chi replacement"),
]

def chi_expr(a, b, c):
    return f"({a} ^ ((({b})^_M64)&{c}))"

def gen_model(name, nstages, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused11.py)."""',
        "import numpy as np",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "_M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0: return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        f"STAGES = {stages!r}",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f,g,h,i_ = rots
        lines.append(f"    ra,rb,rc,rd,re,rf,rg,rh,ri = _rotl(x,{a}),_rotl(x,{b}),_rotl(x,{c}),_rotl(x,{d}),_rotl(x,{e}),_rotl(x,{f}),_rotl(x,{g}),_rotl(x,{h}),_rotl(x,{i_})")
        t1 = chi_expr("ra", "rb", "rc")
        t2 = chi_expr("rd", "re", "rf")
        t3 = chi_expr("rg", "rh", "ri")
        lines.append(f"    x = ({t1} ^ {t2} ^ {t3}) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, nstages, stages, desc):
    lines = [f"// {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x,int r){r&=63;if(!r)return x;return (x<<r)|(x>>(64-r));}",
        "static uint64_t chi64(uint64_t a,uint64_t b,uint64_t c){return a^((~b)&c);}",
        "uint64_t mix_hash(uint64_t v,uint64_t k){",
        "    uint64_t x=v^k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f,g,h,i_ = rots
        lines.append(f"    x=chi64(rotl64(x,{a}),rotl64(x,{b}),rotl64(x,{c}))^chi64(rotl64(x,{d}),rotl64(x,{e}),rotl64(x,{f}))^chi64(rotl64(x,{g}),rotl64(x,{h}),rotl64(x,{i_}));")
    lines += ["    x^=rotl64(k,13);", "    return x;", "}", ""]
    return "\n".join(lines)

def rotl_v(sig, r):
    return sig if r==0 else f"{{{sig}[{63-r}:0],{sig}[63:{64-r}]}}"

def gen_v(name, nstages, stages, desc):
    lines = [f"// {name}: {desc} (gen_fused11.py)", f"module {name}(",
        "    input [63:0] v,", "    input [63:0] k,", "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f,g,h,i_ = rots
        for j,r in enumerate(rots):
            lines.append(f"    wire [63:0] s{i}{chr(97+j)} = {rotl_v(f'x{i}',r)};")
        lines.append(f"    wire [63:0] t{i}a = s{i}a ^ ((~s{i}b)&s{i}c);")
        lines.append(f"    wire [63:0] t{i}b = s{i}d ^ ((~s{i}e)&s{i}f);")
        lines.append(f"    wire [63:0] t{i}c = s{i}g ^ ((~s{i}h)&s{i}i);")
        lines.append(f"    wire [63:0] x{i+1} = t{i}a ^ t{i}b ^ t{i}c;")
    n=len(stages)
    lines += ["    wire [63:0] kr = {k[50:0],k[63:51]};", f"    assign o = x{n} ^ kr;", "endmodule", ""]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, nstages, stages, desc) in SPECS:
        if only and name not in only: continue
        cdir = os.path.join(FB, name); os.makedirs(cdir, exist_ok=True)
        open(os.path.join(cdir, "model.py"), "w").write(gen_model(name, nstages, stages, desc))
        open(os.path.join(cdir, "impl.c"), "w").write(gen_c(name, nstages, stages, desc))
        open(os.path.join(cdir, "rtl.v"), "w").write(gen_v(name, nstages, stages, desc))
        meta = {
            "name": name,
            "description": desc,
            "rtl_top": name,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
        }
        open(os.path.join(cdir, "meta.json"), "w").write(json.dumps(meta, indent=1))
        print(f"generated {name}")

if __name__ == "__main__":
    main()
