#!/usr/bin/env python3
"""Fused Wave-12: Ch (choose) function.

Wave-11 conclusion: need nonlinear-in-x + fast + balanced. Tested:
- maj3: nonlinear-in-x, balanced, 5.94u/stage (too slow)
- MUX: nonlinear-in-x (select), balanced, 5.27u/stage (too slow, needs 6 stages)
- chi: LINEAR in x (degenerate)
- AND: biased (killed)

Wave-12: Ch(x,y,z) = (x&y)|(~x&z) — SHA-256 choose function.
Nonlinear in x, balanced (if y,z balanced/independent), simpler than maj3
(2 AND + 1 OR + 1 NOT vs 3 AND + 2 OR). May be faster per stage than maj3.

x = Ch(x,ra,rb) ^ Ch(rc,rd,re) ^ Ch(rf,rg,rh)
Pure replacement (no ^x linear trail), x included nonlinearly via Ch.
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_ch_5", 5, [
        (3, 11, 23, 31, 43, 53, 7, 17, 29),
        (7, 17, 29, 37, 47, 59, 5, 13, 27),
        (5, 13, 27, 41, 49, 61, 9, 19, 33),
        (9, 19, 33, 39, 51, 57, 11, 23, 35),
        (11, 23, 35, 45, 55, 63, 13, 25, 37),
    ], "5-stage Ch replacement: x = Ch(x,ra,rb)^Ch(rc,rd,re)^Ch(rf,rg,rh)"),
    ("fz_ch_6", 6, [
        (3, 11, 23, 31, 43, 53, 7, 17, 29),
        (7, 17, 29, 37, 47, 59, 5, 13, 27),
        (5, 13, 27, 41, 49, 61, 9, 19, 33),
        (9, 19, 33, 39, 51, 57, 11, 23, 35),
        (11, 23, 35, 45, 55, 63, 13, 25, 37),
        (13, 25, 37, 47, 57, 61, 15, 27, 39),
    ], "6-stage Ch replacement"),
]

def ch_expr(x, y, z):
    return f"((({x})&({y}))|((~({x}))&({z})))"

def gen_model(name, nstages, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused12.py)."""',
        "import numpy as np",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "_M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0: return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        f"STAGES = {stages!r}",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f,g,h,i_ = rots
        lines.append(f"    ra,rb,rc,rd,re,rf,rg,rh,ri = _rotl(x,{a}),_rotl(x,{b}),_rotl(x,{c}),_rotl(x,{d}),_rotl(x,{e}),_rotl(x,{f}),_rotl(x,{g}),_rotl(x,{h}),_rotl(x,{i_})")
        t1 = ch_expr("x", "ra", "rb")
        t2 = ch_expr("rc", "rd", "re")
        t3 = ch_expr("rf", "rg", "rh")
        lines.append(f"    x = (({t1} ^ {t2} ^ {t3}) & M64)")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x",
        "",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
    ]
    return "\n".join(lines)

def gen_c(name, nstages, stages, desc):
    lines = [
        f"/* Fused candidate {name}: {desc} */",
        "#include <stdint.h>",
        "static inline uint64_t rotl64(uint64_t x, int r) {",
        "    r &= 63; if (!r) return x;",
        "    return (x << r) | (x >> (64 - r));",
        "}",
        "#define CH(x,y,z) (((x)&(y))|((~(x))&(z)))",
        "uint64_t mix(uint64_t v, uint64_t k) {",
        "    uint64_t x = v ^ k;",
    ]
    for rots in stages:
        a,b,c,d,e,f,g,h,i_ = rots
        lines.append(f"    {{ uint64_t ra=rotl64(x,{a}),rb=rotl64(x,{b}),rc=rotl64(x,{c}),rd=rotl64(x,{d}),re=rotl64(x,{e}),rf=rotl64(x,{f}),rg=rotl64(x,{g}),rh=rotl64(x,{h}),ri=rotl64(x,{i_});")
        lines.append(f"      x = CH(x,ra,rb) ^ CH(rc,rd,re) ^ CH(rf,rg,rh); }}")
    lines += [
        "    x ^= rotl64(k, 13);",
        "    return x;",
        "}",
    ]
    return "\n".join(lines)

def gen_v(name, nstages, stages, desc):
    lines = [
        f"// Fused candidate {name}: {desc}",
        "module mix(input [63:0] v, input [63:0] k, output [63:0] out);",
        "function [63:0] rotl(input [63:0] x, input [5:0] r);",
        "    rotl = (x << r) | (x >> (6'd64 - r));",
        "endfunction",
        "function [63:0] ch(input [63:0] x, y, z);",
        "    ch = (x & y) | (~x & z);",
        "endfunction",
        "wire [63:0] x0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f,g,h,i_ = rots
        lines.append(f"wire [63:0] s{i}_ra=rotl(s{i}_x,{a}),s{i}_rb=rotl(s{i}_x,{b}),s{i}_rc=rotl(s{i}_x,{c}),s{i}_rd=rotl(s{i}_x,{d}),s{i}_re=rotl(s{i}_x,{e}),s{i}_rf=rotl(s{i}_x,{f}),s{i}_rg=rotl(s{i}_x,{g}),s{i}_rh=rotl(s{i}_x,{h}),s{i}_ri=rotl(s{i}_x,{i_});" if i>0 else f"wire [63:0] x=x0; wire [63:0] s0_ra=rotl(x,{a}),s0_rb=rotl(x,{b}),s0_rc=rotl(x,{c}),s0_rd=rotl(x,{d}),s0_re=rotl(x,{e}),s0_rf=rotl(x,{f}),s0_rg=rotl(x,{g}),s0_rh=rotl(x,{h}),s0_ri=rotl(x,{i_});")
        prev = f"s{i-1}_x" if i>0 else "x"
        # Simplified: use stage wires
    # Fallback: generate straightforward RTL
    lines = [
        f"// Fused candidate {name}: {desc}",
        "module mix(input [63:0] v, input [63:0] k, output [63:0] out);",
        "function [63:0] rotl(input [63:0] x, input integer r);",
        "    rotl = (x << r) | (x >> (64 - r));",
        "endfunction",
        "function [63:0] ch(input [63:0] x, y, z);",
        "    ch = (x & y) | (~x & z);",
        "endfunction",
        "wire [63:0] w0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f,g,h,i_ = rots
        pin = f"w{i}"
        pout = f"w{i+1}"
        lines.append(f"wire [63:0] {pout} = ch({pin}, rotl({pin},{a}), rotl({pin},{b})) ^ ch(rotl({pin},{c}), rotl({pin},{d}), rotl({pin},{e})) ^ ch(rotl({pin},{f}), rotl({pin},{g}), rotl({pin},{h}));")
    lines.append(f"assign out = w{nstages} ^ rotl(k, 13);")
    lines.append("endmodule")
    return "\n".join(lines)

def main():
    for name, nstages, stages, desc in SPECS:
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        model_src = gen_model(name, nstages, stages, desc)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(model_src)
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_c(name, nstages, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_v(name, nstages, stages, desc))
        sys.path.insert(0, cdir)
        import importlib.util
        spec = importlib.util.spec_from_file_location("fz12_" + name, os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: golden1={g1:#018x}", flush=True)

if __name__ == "__main__":
    main()
