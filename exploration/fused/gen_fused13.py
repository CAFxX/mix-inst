RC = [0x9e3779b97f4a7c15, 0x3c6ef372fe94f82a, 0xdaa66d2c7ddf743f,
      0x78dde6e5fd29f054, 0x2545f4914f6cdd1d, 0x9e3779b9a1e7c2fa,
      0x3c6ef372eca0ae52, 0xdaa66d2cd6129b3e, 0x78dde6e5a883a5fe,
      0x2545f4914063d212, 0x9e3779b98fba8ce5, 0x3c6ef372fe6bf8d5]

def rotl_py(r):
    return f"_rotl(x,{r})"

def stage_expr_py(op, rots):
    if op == "dchi2":
        a, b, c, d, e = rots
        return (f"(x ^ ({rotl_py(a)} & {rotl_py(b)}) ^ "
                f"({rotl_py(c)} & {rotl_py(d)}) ^ {rotl_py(e)})")
    if op == "tchi":
        a, b, c, d, e, f, g = rots
        return (f"(x ^ ({rotl_py(a)} & {rotl_py(b)}) ^ "
                f"({rotl_py(c)} & {rotl_py(d)}) ^ "
                f"({rotl_py(e)} & {rotl_py(f)}) ^ {rotl_py(g)})")
    if op == "chi":
        a, b, c = rots
        return f"(x ^ ({rotl_py(a)} & {rotl_py(b)}) ^ {rotl_py(c)})"
    if op == "maj3":
        a, b, c = rots
        ra, rb, rc = rotl_py(a), rotl_py(b), rotl_py(c)
        return (f"(x ^ (( {ra} & {rb}) | ({ra} & {rc}) | "
                f"({rb} & {rc})))")
    raise ValueError(op)

def stage_expr_v(op, rots, xr):
    # xr: dict rot -> wire name
    if op == "dchi2":
        a, b, c, d, e = rots
        return (f"(x ^ ({xr[a]} & {xr[b]}) ^ "
                f"({xr[c]} & {xr[d]}) ^ {xr[e]})")
    if op == "tchi":
        a, b, c, d, e, f, g = rots
        return (f"(x ^ ({xr[a]} & {xr[b]}) ^ "
                f"({xr[c]} & {xr[d]}) ^ "
                f"({xr[e]} & {xr[f]}) ^ {xr[g]})")
    if op == "chi":
        a, b, c = rots
        return f"(x ^ ({xr[a]} & {xr[b]}) ^ {xr[c]})"
    if op == "maj3":
        a, b, c = rots
        return (f"(x ^ (({xr[a]} & {xr[b]}) | ({xr[a]} & {xr[c]}) | "
                f"({xr[b]} & {xr[c]})))")
    raise ValueError(op)

def gen_model(name, op, stages, desc):
    L = [f'"""Fused wave-13 candidate {name}: {desc} (generated by gen_fused13.py)."""',
         "import numpy as np", "",
         "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
         "RC = np.array([%s], dtype=np.uint64)" % ", ".join(hex(v) for v in RC),
         "def _rotl(x, r):",
         "    r %= 64",
         "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64 if r else x",
         "STAGES = ["]
    for st in stages:
        if op == "het":
            sop, rots = st
            L.append(f"    ({sop!r}, {rots}),")
        else:
            L.append(f"    {st},")
    L.append("]")
    L += ["def mix_np(V, K):",
          "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
          "    x = (x ^ k) & M64"]
    for st in stages:
        if op == "het":
            sop, rots = st
            a, b, c = rots
            if sop == "chi":
                L.append(f"    x = (x ^ (_rotl(x,{a}) & _rotl(x,{b})) ^ _rotl(x,{c})) & M64")
            else:  # maj3
                L.append(f"    ra, rb, rc = _rotl(x,{a}), _rotl(x,{b}), _rotl(x,{c})")
                L.append("    x = (x ^ ((ra & rb) | (ra & rc) | (rb & rc))) & M64")
        elif op == "dchi2":
            a, b, c, d, e = st
            L.append(f"    x = (x ^ (_rotl(x,{a}) & _rotl(x,{b})) ^ (_rotl(x,{c}) & _rotl(x,{d})) ^ _rotl(x,{e})) & M64")
        elif op == "tchi":
            a, b, c, d, e, f, g = st
            L.append(f"    x = (x ^ (_rotl(x,{a}) & _rotl(x,{b})) ^ (_rotl(x,{c}) & _rotl(x,{d})) ^ (_rotl(x,{e}) & _rotl(x,{f})) ^ _rotl(x,{g})) & M64")
        elif op == "chi":
            a, b, c = st
            L.append(f"    x = (x ^ (_rotl(x,{a}) & _rotl(x,{b})) ^ _rotl(x,{c})) & M64")
    L += ["    x = (x ^ _rotl(k, 13)) & M64",
          "    return x & M64",
          "def mix(v, k):",
          "    return int(mix_np(np.uint64(v), np.uint64(k)))",
          ""]
    return "\n".join(L)

def gen_c(name, op, stages):
    L = ["#include <stdint.h>",
         f"/* {name}: generated by gen_fused13.py */",
         "static inline uint64_t rotl64(uint64_t x, unsigned r) {",
         "    r &= 63; return r ? (x << r) | (x >> (64 - r)) : x; }",
         "uint64_t mix_hash(uint64_t v, uint64_t k) {",
         "    uint64_t x = v ^ k;"]
    for st in stages:
        if op == "het":
            sop, (a, b, c) = st
            if sop == "chi":
                L.append(f"    x = x ^ (rotl64(x,{a}) & rotl64(x,{b})) ^ rotl64(x,{c});")
            else:
                L.append(f"    {{ uint64_t ra=rotl64(x,{a}), rb=rotl64(x,{b}), rc=rotl64(x,{c});")
                L.append(f"      x = x ^ ((ra & rb) | (ra & rc) | (rb & rc)); }}")
        else:
            n = len(st)
            rs = ", ".join(str(r) for r in st)
            L.append(f"    {{ uint64_t r[] = {{{rs}}};")
            if op == "dchi2":
                L.append("      x = x ^ (rotl64(x,r[0]) & rotl64(x,r[1])) ^ (rotl64(x,r[2]) & rotl64(x,r[3])) ^ rotl64(x,r[4]); }")
            elif op == "tchi":
                L.append("      x = x ^ (rotl64(x,r[0]) & rotl64(x,r[1])) ^ (rotl64(x,r[2]) & rotl64(x,r[3])) ^ (rotl64(x,r[4]) & rotl64(x,r[5])) ^ rotl64(x,r[6]); }")
            elif op == "chi":
                L.append("      x = x ^ (rotl64(x,r[0]) & rotl64(x,r[1])) ^ rotl64(x,r[2]); }")
    L += ["    x = x ^ rotl64(k, 13);",
          "    return x;",
          "}",
          ""]
    return "\n".join(L)

def gen_rtl(name, op, stages):
    L = [f"// {name}: generated by gen_fused13.py",
         f"module {name}(",
         "    input  wire [63:0] v,",
         "    input  wire [63:0] k,",
         "    output wire [63:0] out",
         ");",
         "    function [63:0] rotl;",
         "        input [63:0] x;",
         "        input integer r;",
         "        begin",
         "            r = r % 64;",
         "            rotl = r ? ((x << r) | (x >> (64 - r))) : x;",
         "        end",
         "    endfunction"]
    # collect all rotations
    allrots = set()
    for st in stages:
        rots = st[1] if op == "het" else st
        allrots.update(rots)
    L.append("    wire [63:0] x0 = v ^ k;")
    prev = "x0"
    for i, st in enumerate(stages):
        sop = st[0] if op == "het" else op
        rots = st[1] if op == "het" else st
        wn = {}
        for r in sorted(set(rots)):
            w = f"r{i}_{r}"
            L.append(f"    wire [63:0] {w} = rotl({prev}, {r});")
            wn[r] = w
        expr = stage_expr_v(sop, rots, wn).replace("x", prev)
        L.append(f"    wire [63:0] x{i+1} = {expr};")
        prev = f"x{i+1}"
    L.append(f"    wire [63:0] k13 = rotl(k, 13);")
    L.append(f"    assign out = {prev} ^ k13;")
    L.append("endmodule")
    L.append("")
    return "\n".join(L)

def gen_meta(name, desc):
    return {
        "name": name,
        "description": desc,
        "rtl_top": name,
        "screen_keys": ["0x123456789abcdef0", "0x0"],
        "practrand_keys": ["0x123456789abcdef0", "0x0"],
    }

def main():
    for name, op, stages, desc in SPECS:
        d = os.path.join(FB, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "model.py"), "w") as f:
            f.write(gen_model(name, op, stages, desc))
        with open(os.path.join(d, "impl.c"), "w") as f:
            f.write(gen_c(name, op, stages))
        with open(os.path.join(d, "rtl.v"), "w") as f:
            f.write(gen_rtl(name, op, stages))
        with open(os.path.join(d, "meta.json"), "w") as f:
            json.dump(gen_meta(name, desc), f, indent=2)
        print(f"generated {name}")

if __name__ == "__main__":
    main()
