#!/usr/bin/env python3
"""Fused Wave-13 generator: WORD-LEVEL PIVOT — stronger per-stage nonlinear
functions to allow FEWER stages than the 6-stage AND cascade (al_and6a 20.1u).

Design hypothesis: the AND cascade's chi `x ^ (ra&rb) ^ rc` is ~3.35u/stage.
If a stronger nonlinear function costs ~3.5-4u/stage but diffuses enough to
drop from 6 to 5 (or 4) stages, total latency beats 20.1u.

Candidate families:
  dchi2 : x ^= (ra&rb) ^ (rc&rd) ^ re          (dual-AND chi, degree 2, 5 rots)
  tchi  : x ^= (ra&rb) ^ (rc&rd) ^ (re&rf) ^ rg (triple-AND chi, degree 2, 7 rots)
  het   : heterogeneous: chi stages + 1 maj3 stage (co-designed: maj3 where
          chi diffusion is weakest — middle stage)

Key schedule: pre-whiten x ^= k; post x ^= rotl(k,13) (al_and6a convention).

Each spec -> fast_battery/candidates/<name>/{model.py, impl.c, rtl.v, meta.json}
bit-identical in Python/numpy, C, Verilog.
"""
