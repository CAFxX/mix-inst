#!/usr/bin/env python3
"""Fused Wave-2 generator: pure nonlinear diffusion, NO linear XOR terms.

The wave-1 failure: linear ^re^rf terms created deterministic trails that 2-3
stages of nonlinear ops couldn't mask. Wave-2 removes linear terms entirely —
the wide nonlinear function does ALL the diffusion.

Opcodes (x is 64-bit state):
  aor3 : x ^= (ra&rb&rc)|(rd&re&rf)|(rg&rh&ri)   (9-input, degree 3, ~2u)
  aor2w: x ^= (ra&rb)|(rc&rd)|(re&rf)|(rg&rh)    (8-input, degree 2, ~2u, wider)
  maj8 : x ^= maj(ra,rb,rc,rd,re,rf,rg,rh)       (8-input majority, degree 4)

Key schedule: pre-whiten x ^= k; post x ^= rotl(k,13).
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_aor3_3", "aor3", [
        (1, 7, 13, 29, 41, 53, 5, 23, 37),
        (3, 11, 19, 37, 47, 59, 9, 31, 43),
        (7, 17, 23, 43, 51, 61, 13, 35, 49),
    ], "3-stage fused 3x3-AND-OR: x ^= (ra&rb&rc)|(rd&re&rf)|(rg&rh&ri)"),
    ("fz_aor3_2", "aor3", [
        (1, 9, 17, 29, 43, 55, 7, 25, 39),
        (5, 15, 27, 39, 51, 61, 11, 33, 47),
    ], "2-stage fused 3x3-AND-OR"),
    ("fz_aor2w_3", "aor2w", [
        (1, 7, 13, 29, 41, 53, 5, 23),
        (3, 11, 19, 37, 47, 59, 9, 31),
        (7, 17, 23, 43, 51, 61, 13, 35),
    ], "3-stage fused 4x2-AND-OR: x ^= (ra&rb)|(rc&rd)|(re&rf)|(rg&rh)"),
    ("fz_aor2w_2", "aor2w", [
        (1, 9, 17, 29, 43, 55, 7, 25),
        (5, 15, 27, 39, 51, 61, 11, 33),
    ], "2-stage fused 4x2-AND-OR"),
]

def gen_model(name, op, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused2.py)."""',
        "import numpy as np",
        "",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0:",
        "        return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        "",
        f"STAGES = {stages!r}",
        "",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        rs = ", ".join(f"_rotl(x,{r})" for r in rots)
        rvars = [f"r{j}" for j in range(len(rots))]
        lines.append(f"    {','.join(rvars)} = {rs}")
        if op == "aor3":
            a,b,c,d,e,f,g,h,ii = rvars
            lines.append(f"    x = (x ^ (({a}&{b}&{c})|({d}&{e}&{f})|({g}&{h}&{ii}))) & M64")
        elif op == "aor2w":
            a,b,c,d,e,f,g,h = rvars
            lines.append(f"    x = (x ^ (({a}&{b})|({c}&{d})|({e}&{f})|({g}&{h}))) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, op, stages, desc):
    lines = [
        f"// Fused candidate {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x, int r) {",
        "    r &= 63; if (!r) return x;",
        "    return (x << r) | (x >> (64 - r));",
        "}",
        "uint64_t mix_hash(uint64_t v, uint64_t k) {",
        "    uint64_t x = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    uint64_t {rv} = rotl64(x, {r});")
            rvars.append(rv)
        if op == "aor3":
            a,b,c,d,e,f,g,h,ii = rvars
            lines.append(f"    x ^= (({a}&{b}&{c})|({d}&{e}&{f})|({g}&{h}&{ii}));")
        elif op == "aor2w":
            a,b,c,d,e,f,g,h = rvars
            lines.append(f"    x ^= (({a}&{b})|({c}&{d})|({e}&{f})|({g}&{h}));")
    lines += [
        "    x ^= rotl64(k, 13);",
        "    return x;",
        "}",
        "",
    ]
    return "\n".join(lines)

def rotl_v(sig, r):
    if r == 0:
        return sig
    return f"{{{sig}[{63-r}:0], {sig}[63:{64-r}]}}"

def gen_v(name, op, stages, desc):
    lines = [
        f"// {name}: {desc} (generated by gen_fused2.py)",
        f"module {name}(",
        "    input [63:0] v,",
        "    input [63:0] k,",
        "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    wire [63:0] {rv} = {rotl_v(f'x{i}', r)};")
            rvars.append(rv)
        if op == "aor3":
            a,b,c,d,e,f,g,h,ii = rvars
            lines.append(f"    wire [63:0] x{i+1} = x{i} ^ (({a}&{b}&{c})|({d}&{e}&{f})|({g}&{h}&{ii}));")
        elif op == "aor2w":
            a,b,c,d,e,f,g,h = rvars
            lines.append(f"    wire [63:0] x{i+1} = x{i} ^ (({a}&{b})|({c}&{d})|({e}&{f})|({g}&{h}));")
    n = len(stages)
    lines += [
        "    wire [63:0] kr = {k[50:0], k[63:51]};",
        f"    assign o = x{n} ^ kr;",
        "endmodule",
        "",
    ]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, op, stages, desc) in SPECS:
        if only and name not in only:
            continue
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        model_src = gen_model(name, op, stages, desc)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(model_src)
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_c(name, op, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_v(name, op, stages, desc))
        sys.path.insert(0, cdir)
        import importlib.util
        spec = importlib.util.spec_from_file_location("fz2_" + name, os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: golden1={g1:#018x}", flush=True)

if __name__ == "__main__":
    main()
