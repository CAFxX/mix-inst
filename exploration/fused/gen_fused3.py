#!/usr/bin/env python3
"""Fused Wave-3: pure nonlinear state replacement, NO ^x linear trail.

Wave-2 failure analysis: `x ^= F(rotations)` has a fatal flaw — since all rotations
are non-zero, F[i] never depends on x[i], so flipping input bit i ALWAYS flips
output bit i through the `^ x` path (p=1.0). 2-3 stages can't mask this; 6 stages
(al_chi6) barely can.

Wave-3: x_new = N1 ^ N2 ^ N3 where each N is a nonlinear function of rotations.
No linear component. Complete state replacement (like SPN round without linear layer).

Opcodes:
  r3x3 : x = ((ra&rb&rc)|(rd&re&rf)|(rg&rh&ri)) ^ ((rj&rk&rl)|(rm&rn&ro)|(rp&rq&rr))
         (18-input, degree 3, two balanced AND-OR terms)
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_r3x3_3", [
        (1,7,13, 29,41,53, 5,23,37,  11,19,31, 43,51,61, 9,27,47),
        (3,11,19, 37,47,59, 9,31,43,  17,23,35, 49,55,63, 13,29,45),
        (7,17,23, 43,51,61, 13,35,49,  5,15,27, 39,53,59, 21,33,57),
    ], "3-stage pure replacement: x = AOR3a ^ AOR3b (18-input, degree 3)"),
    ("fz_r3x3_2", [
        (1,9,17, 29,43,55, 7,25,39,  13,23,33, 47,57,61, 5,19,37),
        (5,15,27, 39,51,61, 11,33,47,  3,17,29, 43,53,59, 9,25,49),
    ], "2-stage pure replacement: x = AOR3a ^ AOR3b"),
]

def gen_model(name, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused3.py)."""',
        "import numpy as np",
        "",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0:",
        "        return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        "",
        f"STAGES = {stages!r}",
        "",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        assert len(rots) == 18
        rvars = [f"r{j}" for j in range(18)]
        lines.append(f"    {','.join(rvars)} = {', '.join(f'_rotl(x,{r})' for r in rots)}")
        a,b,c,d,e,f,g,h,ii,j,k_,l,m,n,o,p,q,r = rvars
        # Note: k_ to avoid clash with key k; but we use r-vars so fine
        t1 = f"(({a}&{b}&{c})|({d}&{e}&{f})|({g}&{h}&{ii}))"
        t2 = f"(({j}&{k_}&{l})|({m}&{n}&{o})|({p}&{q}&{r}))"
        lines.append(f"    x = ({t1} ^ {t2}) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, stages, desc):
    lines = [
        f"// Fused candidate {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x, int r) {",
        "    r &= 63; if (!r) return x;",
        "    return (x << r) | (x >> (64 - r));",
        "}",
        "uint64_t mix_hash(uint64_t v, uint64_t k) {",
        "    uint64_t x = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    uint64_t {rv} = rotl64(x, {r});")
            rvars.append(rv)
        a,b,c,d,e,f,g,h,ii,j,k_,l,m,n,o,p,q,r = rvars
        t1 = f"(({a}&{b}&{c})|({d}&{e}&{f})|({g}&{h}&{ii}))"
        t2 = f"(({j}&{k_}&{l})|({m}&{n}&{o})|({p}&{q}&{r}))"
        lines.append(f"    x = ({t1} ^ {t2});")
    lines += [
        "    x ^= rotl64(k, 13);",
        "    return x;",
        "}",
        "",
    ]
    return "\n".join(lines)

def rotl_v(sig, r):
    if r == 0:
        return sig
    return f"{{{sig}[{63-r}:0], {sig}[63:{64-r}]}}"

def gen_v(name, stages, desc):
    lines = [
        f"// {name}: {desc} (generated by gen_fused3.py)",
        f"module {name}(",
        "    input [63:0] v,",
        "    input [63:0] k,",
        "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    wire [63:0] {rv} = {rotl_v(f'x{i}', r)};")
            rvars.append(rv)
        a,b,c,d,e,f,g,h,ii,j,k_,l,m,n,o,p,q,r = rvars
        t1 = f"(({a}&{b}&{c})|({d}&{e}&{f})|({g}&{h}&{ii}))"
        t2 = f"(({j}&{k_}&{l})|({m}&{n}&{o})|({p}&{q}&{r}))"
        lines.append(f"    wire [63:0] x{i+1} = {t1} ^ {t2};")
    n = len(stages)
    lines += [
        "    wire [63:0] kr = {k[50:0], k[63:51]};",
        f"    assign o = x{n} ^ kr;",
        "endmodule",
        "",
    ]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, stages, desc) in SPECS:
        if only and name not in only:
            continue
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        model_src = gen_model(name, stages, desc)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(model_src)
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_c(name, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_v(name, stages, desc))
        sys.path.insert(0, cdir)
        import importlib.util
        spec = importlib.util.spec_from_file_location("fz3_" + name, os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: golden1={g1:#018x}", flush=True)

if __name__ == "__main__":
    main()
