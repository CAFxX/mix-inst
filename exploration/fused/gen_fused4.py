#!/usr/bin/env python3
"""Fused Wave-4: balanced 3-input majority, pure replacement, mixed-parity rotations.

Design principles from wave-1/2/3 failures:
1. NO `^ x` (linear trail: out[i] always flips when in[i] flips)
2. Mixed-parity rotations (all-odd partitions state into even/odd sublattices)
3. Balanced nonlinear function (AND-OR biased P(1)~0.33; 3-input majority P(1)=0.5)

Construction: x_new = maj3(ra,rb,rc) ^ maj3(rd,re,rf) ^ maj3(rg,rh,ri)
  maj3(a,b,c) = (a&b)|(a&c)|(b&c)  [balanced, degree 2, ~2u]
  9 inputs/output bit, degree 2, ~4u/stage (maj3 parallel + XOR3 tree)

Key schedule: pre-whiten x ^= k; post x ^= rotl(k,13).
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

# Mixed-parity rotations: distinct, spread, both even and odd in each stage.
SPECS = [
    ("fz_maj3r_3", [
        (1, 8, 15, 29, 42, 53, 6, 23, 38),   # 1o,8e,15o,29o,42e,53o,6e,23o,38e
        (3, 12, 21, 37, 48, 59, 10, 31, 44),  # 3o,12e,21o,37o,48e,59o,10e,31o,44e
        (7, 18, 25, 43, 52, 61, 14, 35, 50),  # 7o,18e,25o,43o,52e,61o,14e,35o,50e
    ], "3-stage balanced maj3 replacement: x = maj3a ^ maj3b ^ maj3c"),
    ("fz_maj3r_2", [
        (1, 10, 19, 29, 44, 55, 7, 26, 41),
        (5, 16, 27, 39, 52, 61, 11, 34, 47),
    ], "2-stage balanced maj3 replacement"),
]

def gen_model(name, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused4.py)."""',
        "import numpy as np",
        "",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0:",
        "        return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        "",
        "def _maj3(a, b, c):",
        "    return ((a&b)|(a&c)|(b&c)) & M64",
        "",
        f"STAGES = {stages!r}",
        "",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        assert len(rots) == 9
        rvars = [f"r{j}" for j in range(9)]
        lines.append(f"    {','.join(rvars)} = {', '.join(f'_rotl(x,{r})' for r in rots)}")
        a,b,c,d,e,f,g,h,ii = rvars
        lines.append(f"    x = (_maj3({a},{b},{c}) ^ _maj3({d},{e},{f}) ^ _maj3({g},{h},{ii})) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, stages, desc):
    lines = [
        f"// Fused candidate {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x, int r) {",
        "    r &= 63; if (!r) return x;",
        "    return (x << r) | (x >> (64 - r));",
        "}",
        "static uint64_t maj3(uint64_t a, uint64_t b, uint64_t c) {",
        "    return (a&b)|(a&c)|(b&c);",
        "}",
        "uint64_t mix_hash(uint64_t v, uint64_t k) {",
        "    uint64_t x = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    uint64_t {rv} = rotl64(x, {r});")
            rvars.append(rv)
        a,b,c,d,e,f,g,h,ii = rvars
        lines.append(f"    x = maj3({a},{b},{c}) ^ maj3({d},{e},{f}) ^ maj3({g},{h},{ii});")
    lines += [
        "    x ^= rotl64(k, 13);",
        "    return x;",
        "}",
        "",
    ]
    return "\n".join(lines)

def rotl_v(sig, r):
    if r == 0:
        return sig
    return f"{{{sig}[{63-r}:0], {sig}[63:{64-r}]}}"

def gen_v(name, stages, desc):
    lines = [
        f"// {name}: {desc} (generated by gen_fused4.py)",
        f"module {name}(",
        "    input [63:0] v,",
        "    input [63:0] k,",
        "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        rvars = []
        for j, r in enumerate(rots):
            rv = f"s{i}r{j}"
            lines.append(f"    wire [63:0] {rv} = {rotl_v(f'x{i}', r)};")
            rvars.append(rv)
        a,b,c,d,e,f,g,h,ii = rvars
        m1 = f"(({a}&{b})|({a}&{c})|({b}&{c}))"
        m2 = f"(({d}&{e})|({d}&{f})|({e}&{f}))"
        m3 = f"(({g}&{h})|({g}&{ii})|({h}&{ii}))"
        lines.append(f"    wire [63:0] x{i+1} = {m1} ^ {m2} ^ {m3};")
    n = len(stages)
    lines += [
        "    wire [63:0] kr = {k[50:0], k[63:51]};",
        f"    assign o = x{n} ^ kr;",
        "endmodule",
        "",
    ]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, stages, desc) in SPECS:
        if only and name not in only:
            continue
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        model_src = gen_model(name, stages, desc)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(model_src)
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_c(name, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_v(name, stages, desc))
        sys.path.insert(0, cdir)
        import importlib.util
        spec = importlib.util.spec_from_file_location("fz4_" + name, os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: golden1={g1:#018x}", flush=True)

if __name__ == "__main__":
    main()
