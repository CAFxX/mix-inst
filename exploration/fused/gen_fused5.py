#!/usr/bin/env python3
"""Fused Wave-5: include x (rotation 0) in nonlinear function to break linear trail.

Insight: `x ^= F(rotations)` has linear trail because F[i] doesn't depend on x[i]
(all rotations non-zero). If F includes x itself (rotation 0), then flipping x[i]
affects F[i] nonlinearly, masking the direct `^ x` path.

Construction: x ^= maj3(x, ra, rb) ^ maj3(rc, rd, re) ^ maj3(rf, rg, rh)
  - First maj3 includes x (rotation 0)
  - 8 non-zero rotations + x itself = 9 inputs
  - Balanced, degree 2

Key schedule: pre-whiten x ^= k; post x ^= rotl(k,13).
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_majx_3", [
        (0, 7, 13, 29, 41, 53, 5, 23, 37),
        (0, 11, 19, 37, 47, 59, 9, 31, 43),
        (0, 17, 23, 43, 51, 61, 13, 35, 49),
    ], "3-stage: x ^= maj3(x,ra,rb) ^ maj3(rc,rd,re) ^ maj3(rf,rg,rh)"),
    ("fz_majx_4", [
        (0, 7, 13, 29, 41, 53, 5, 23, 37),
        (0, 11, 19, 37, 47, 59, 9, 31, 43),
        (0, 17, 23, 43, 51, 61, 13, 35, 49),
        (0, 5, 29, 33, 45, 57, 11, 27, 39),
    ], "4-stage: x ^= maj3(x,ra,rb) ^ maj3(rc,rd,re) ^ maj3(rf,rg,rh)"),
    ("fz_majx_5", [
        (0, 7, 13, 29, 41, 53, 5, 23, 37),
        (0, 11, 19, 37, 47, 59, 9, 31, 43),
        (0, 17, 23, 43, 51, 61, 13, 35, 49),
        (0, 5, 29, 33, 45, 57, 11, 27, 39),
        (0, 9, 21, 35, 49, 59, 7, 25, 43),
    ], "5-stage: x ^= maj3(x,ra,rb) ^ maj3(rc,rd,re) ^ maj3(rf,rg,rh)"),
]

def gen_model(name, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused5.py)."""',
        "import numpy as np",
        "",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0:",
        "        return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        "",
        "def _maj3(a, b, c):",
        "    return ((a&b)|(a&c)|(b&c)) & M64",
        "",
        f"STAGES = {stages!r}",
        "",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        assert len(rots) == 9 and rots[0] == 0
        rvars = ["x"] + [f"_rotl(x,{r})" for r in rots[1:]]
        # r0=x, r1..r8 are rotations
        lines.append(f"    r0 = x")
        for j, r in enumerate(rots[1:], 1):
            lines.append(f"    r{j} = _rotl(x,{r})")
        lines.append(f"    x = (x ^ _maj3(r0,r1,r2) ^ _maj3(r3,r4,r5) ^ _maj3(r6,r7,r8)) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, stages, desc):
    lines = [
        f"// Fused candidate {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x, int r) {",
        "    r &= 63; if (!r) return x;",
        "    return (x << r) | (x >> (64 - r));",
        "}",
        "static uint64_t maj3(uint64_t a, uint64_t b, uint64_t c) {",
        "    return (a&b)|(a&c)|(b&c);",
        "}",
        "uint64_t mix_hash(uint64_t v, uint64_t k) {",
        "    uint64_t x = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        lines.append(f"    x ^= maj3(x, rotl64(x,{rots[1]}), rotl64(x,{rots[2]}))")
        lines.append(f"         ^ maj3(rotl64(x,{rots[3]}), rotl64(x,{rots[4]}), rotl64(x,{rots[5]}))")
        lines.append(f"         ^ maj3(rotl64(x,{rots[6]}), rotl64(x,{rots[7]}), rotl64(x,{rots[8]}));")
    lines += [
        "    x ^= rotl64(k, 13);",
        "    return x;",
        "}",
        "",
    ]
    return "\n".join(lines)

def rotl_v(sig, r):
    if r == 0:
        return sig
    return f"{{{sig}[{63-r}:0], {sig}[63:{64-r}]}}"

def gen_v(name, stages, desc):
    lines = [
        f"// {name}: {desc} (generated by gen_fused5.py)",
        f"module {name}(",
        "    input [63:0] v,",
        "    input [63:0] k,",
        "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        # r0 = x_i, r1..r8 are rotations
        for j, r in enumerate(rots[1:], 1):
            lines.append(f"    wire [63:0] s{i}r{j} = {rotl_v(f'x{i}', r)};")
        m1 = f"((x{i}&s{i}r1)|(x{i}&s{i}r2)|(s{i}r1&s{i}r2))"
        m2 = f"((s{i}r3&s{i}r4)|(s{i}r3&s{i}r5)|(s{i}r4&s{i}r5))"
        m3 = f"((s{i}r6&s{i}r7)|(s{i}r6&s{i}r8)|(s{i}r7&s{i}r8))"
        lines.append(f"    wire [63:0] x{i+1} = x{i} ^ {m1} ^ {m2} ^ {m3};")
    n = len(stages)
    lines += [
        "    wire [63:0] kr = {k[50:0], k[63:51]};",
        f"    assign o = x{n} ^ kr;",
        "endmodule",
        "",
    ]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, stages, desc) in SPECS:
        if only and name not in only:
            continue
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        model_src = gen_model(name, stages, desc)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(model_src)
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_c(name, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_v(name, stages, desc))
        sys.path.insert(0, cdir)
        import importlib.util
        spec = importlib.util.spec_from_file_location("fz5_" + name, os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: golden1={g1:#018x}", flush=True)

if __name__ == "__main__":
    main()
