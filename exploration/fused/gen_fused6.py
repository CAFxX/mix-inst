#!/usr/bin/env python3
"""Fused Wave-6: chi-with-x-included, lower per-stage latency.

Wave-5 (maj3-x) works but 4u/stage (maj3=2u + XOR4=2u). 
Wave-6 uses chi-like AND terms: ((~x)&ra) ^ ((~rb)&rc) ^ ((~rd)&re)
  - AND2 = 1u (NOT folds in), 4-input XOR = 2u → 3u/stage
  - 5 stages = ~15u (vs 19.8u floor)
  - Including x in first term breaks linear trail.

Key schedule: pre-whiten x ^= k; post x ^= rotl(k,13).
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_chix_5", [
        (7, 13, 29, 41, 53),
        (11, 19, 37, 47, 59),
        (17, 23, 43, 51, 61),
        (5, 29, 33, 45, 57),
        (9, 21, 35, 49, 59),
    ], "5-stage: x ^= ((~x)&ra) ^ ((~rb)&rc) ^ ((~rd)&re)"),
    ("fz_chix_4", [
        (7, 13, 29, 41, 53),
        (11, 19, 37, 47, 59),
        (17, 23, 43, 51, 61),
        (5, 29, 33, 45, 57),
    ], "4-stage: x ^= ((~x)&ra) ^ ((~rb)&rc) ^ ((~rd)&re)"),
]

def gen_model(name, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused6.py)."""',
        "import numpy as np",
        "",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0:",
        "        return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        "",
        f"STAGES = {stages!r}",
        "",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        assert len(rots) == 5
        a, b, c, d, e = rots
        lines.append(f"    ra,rb,rc,rd,re = _rotl(x,{a}),_rotl(x,{b}),_rotl(x,{c}),_rotl(x,{d}),_rotl(x,{e})")
        lines.append(f"    x = (x ^ ((~x)&ra) ^ ((~rb)&rc) ^ ((~rd)&re)) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, stages, desc):
    lines = [
        f"// Fused candidate {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x, int r) {",
        "    r &= 63; if (!r) return x;",
        "    return (x << r) | (x >> (64 - r));",
        "}",
        "uint64_t mix_hash(uint64_t v, uint64_t k) {",
        "    uint64_t x = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        a, b, c, d, e = rots
        lines.append(f"    x ^= ((~x)&rotl64(x,{a})) ^ ((~rotl64(x,{b}))&rotl64(x,{c})) ^ ((~rotl64(x,{d}))&rotl64(x,{e}));")
    lines += [
        "    x ^= rotl64(k, 13);",
        "    return x;",
        "}",
        "",
    ]
    return "\n".join(lines)

def rotl_v(sig, r):
    if r == 0:
        return sig
    return f"{{{sig}[{63-r}:0], {sig}[63:{64-r}]}}"

def gen_v(name, stages, desc):
    lines = [
        f"// {name}: {desc} (generated by gen_fused6.py)",
        f"module {name}(",
        "    input [63:0] v,",
        "    input [63:0] k,",
        "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;",
    ]
    for i, rots in enumerate(stages):
        a, b, c, d, e = rots
        lines.append(f"    wire [63:0] s{i}a = {rotl_v(f'x{i}', a)};")
        lines.append(f"    wire [63:0] s{i}b = {rotl_v(f'x{i}', b)};")
        lines.append(f"    wire [63:0] s{i}c = {rotl_v(f'x{i}', c)};")
        lines.append(f"    wire [63:0] s{i}d = {rotl_v(f'x{i}', d)};")
        lines.append(f"    wire [63:0] s{i}e = {rotl_v(f'x{i}', e)};")
        t1 = f"((~x{i})&s{i}a)"
        t2 = f"((~s{i}b)&s{i}c)"
        t3 = f"((~s{i}d)&s{i}e)"
        lines.append(f"    wire [63:0] x{i+1} = x{i} ^ {t1} ^ {t2} ^ {t3};")
    n = len(stages)
    lines += [
        "    wire [63:0] kr = {k[50:0], k[63:51]};",
        f"    assign o = x{n} ^ kr;",
        "endmodule",
        "",
    ]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, stages, desc) in SPECS:
        if only and name not in only:
            continue
        cdir = os.path.join(FB, name)
        os.makedirs(cdir, exist_ok=True)
        model_src = gen_model(name, stages, desc)
        with open(os.path.join(cdir, "model.py"), "w") as f:
            f.write(model_src)
        with open(os.path.join(cdir, "impl.c"), "w") as f:
            f.write(gen_c(name, stages, desc))
        with open(os.path.join(cdir, "rtl.v"), "w") as f:
            f.write(gen_v(name, stages, desc))
        sys.path.insert(0, cdir)
        import importlib.util
        spec = importlib.util.spec_from_file_location("fz6_" + name, os.path.join(cdir, "model.py"))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        g1 = m.mix(0x0, 0x123456789ABCDEF0)
        g2 = m.mix(0x123456789ABCDEF0, 0x0)
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0", "out": hex(g1)},
                {"val": "0x123456789abcdef0", "key": "0x0", "out": hex(g2)},
            ],
        }
        with open(os.path.join(cdir, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: golden1={g1:#018x}", flush=True)

if __name__ == "__main__":
    main()
