#!/usr/bin/env python3
"""Fused Wave-7: fast AND-based, accept bias, test if avalanche still works.

Wave-5 maj3-x: triage PASS but 29.7u (5.94u/stage, too slow).
Wave-7: x ^= (x&ra) ^ (rb&rc) ^ (rd&re) — AND2=1u, XOR4=2u → 3u/stage, 5 stages=15u.
Biased (P~0.44) but maybe avalanche still good?
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_andx_5", [
        (7, 13, 29, 41, 53),
        (11, 19, 37, 47, 59),
        (17, 23, 43, 51, 61),
        (5, 29, 33, 45, 57),
        (9, 21, 35, 49, 59),
    ], "5-stage: x ^= (x&ra) ^ (rb&rc) ^ (rd&re)"),
]

def gen_model(name, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused7.py)."""',
        "import numpy as np",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0: return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        f"STAGES = {stages!r}",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        a,b,c,d,e = rots
        lines.append(f"    ra,rb,rc,rd,re = _rotl(x,{a}),_rotl(x,{b}),_rotl(x,{c}),_rotl(x,{d}),_rotl(x,{e})")
        lines.append(f"    x = (x ^ (x&ra) ^ (rb&rc) ^ (rd&re)) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, stages, desc):
    lines = [f"// {name}: {desc}", "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x,int r){r&=63;if(!r)return x;return (x<<r)|(x>>(64-r));}",
        "uint64_t mix_hash(uint64_t v,uint64_t k){", "    uint64_t x=v^k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e = rots
        lines.append(f"    x^=(x&rotl64(x,{a}))^(rotl64(x,{b})&rotl64(x,{c}))^(rotl64(x,{d})&rotl64(x,{e}));")
    lines += ["    x^=rotl64(k,13);", "    return x;", "}", ""]
    return "\n".join(lines)

def rotl_v(sig, r):
    return sig if r==0 else f"{{{sig}[{63-r}:0],{sig}[63:{64-r}]}}"

def gen_v(name, stages, desc):
    lines = [f"// {name}: {desc} (gen_fused7.py)", f"module {name}(",
        "    input [63:0] v,", "    input [63:0] k,", "    output [63:0] o", ");",
        "    wire [63:0] x0 = v ^ k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e = rots
        for j,r in enumerate(rots):
            lines.append(f"    wire [63:0] s{i}{chr(97+j)} = {rotl_v(f'x{i}',r)};")
        lines.append(f"    wire [63:0] x{i+1} = x{i} ^ (x{i}&s{i}a) ^ (s{i}b&s{i}c) ^ (s{i}d&s{i}e);")
    n=len(stages)
    lines += ["    wire [63:0] kr = {k[50:0],k[63:51]};", f"    assign o = x{n} ^ kr;", "endmodule", ""]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, stages, desc) in SPECS:
        if only and name not in only: continue
        cdir = os.path.join(FB, name); os.makedirs(cdir, exist_ok=True)
        with open(os.path.join(cdir,"model.py"),"w") as f: f.write(gen_model(name,stages,desc))
        with open(os.path.join(cdir,"impl.c"),"w") as f: f.write(gen_c(name,stages,desc))
        with open(os.path.join(cdir,"rtl.v"),"w") as f: f.write(gen_v(name,stages,desc))
        sys.path.insert(0,cdir); import importlib.util
        spec=importlib.util.spec_from_file_location("fz7_"+name,os.path.join(cdir,"model.py"))
        m=importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
        g1=m.mix(0x0,0x123456789ABCDEF0); g2=m.mix(0x123456789ABCDEF0,0x0)
        meta={"name":name,"description":desc,"screen_keys":["0x123456789abcdef0","0x0"],
              "practrand_keys":["0x123456789abcdef0","0x0"],
              "goldens":[{"val":"0x0","key":"0x123456789abcdef0","out":hex(g1)},
                         {"val":"0x123456789abcdef0","key":"0x0","out":hex(g2)}]}
        with open(os.path.join(cdir,"meta.json"),"w") as f: json.dump(meta,f,indent=1)
        sys.path.remove(cdir)
        print(f"generated {name}: {g1:#018x}",flush=True)

if __name__=="__main__": main()
