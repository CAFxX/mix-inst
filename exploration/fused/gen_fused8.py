#!/usr/bin/env python3
"""Fused Wave-8: MUX-based constructions.

Wave-5 maj3-x: triage PASS but 29.7u (5.94u/stage, too slow).
Wave-7 andx: KILL (aval 0.12) — AND bias hurts.

Wave-8: MUX(x,a,b) = (x&a)|(~x&b) — balanced, includes x nonlinearly,
potentially faster than maj3 (MUX2 cell vs 3-AND+OR).

Constructions:
- fz_mux_5: 5-stage pure replacement: x = MUX(x,ra,rb) ^ MUX(rc,rd,re) ^ MUX(rf,rg,rh)
  (no ^x term, no linear trail possible)
- fz_muxx_5: 5-stage: x ^= MUX(x,ra,rb) ^ MUX(rc,rd,re) (x in MUX breaks trail)
- fz_mux_4: 4-stage pure replacement (test if 4 stages suffice with MUX)
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

# 5 stages, 6 rotations each (for 3 MUXes), 4 stages for the 4-stage variant
SPECS = [
    ("fz_mux_5", 5, [
        (3, 11, 23, 31, 43, 53),
        (7, 17, 29, 37, 47, 59),
        (5, 13, 27, 41, 49, 61),
        (9, 19, 33, 39, 51, 57),
        (11, 23, 35, 45, 55, 63),
    ], "5-stage pure MUX replacement: x = MUX(x,ra,rb)^MUX(rc,rd,re)^MUX(rf,rg,rh)"),
    ("fz_muxx_5", 5, [
        (3, 11, 23, 31, 43, 53),
        (7, 17, 29, 37, 47, 59),
        (5, 13, 27, 41, 49, 61),
        (9, 19, 33, 39, 51, 57),
        (11, 23, 35, 45, 55, 63),
    ], "5-stage: x ^= MUX(x,ra,rb)^MUX(rc,rd,re)"),
    ("fz_mux_4", 4, [
        (3, 11, 23, 31, 43, 53),
        (7, 17, 29, 37, 47, 59),
        (5, 13, 27, 41, 49, 61),
        (9, 19, 33, 39, 51, 57),
    ], "4-stage pure MUX replacement"),
]

def mux_expr(x, a, b):
    # MUX(x,a,b) = (x&a)|(~x&b) — for numpy: use ^1 for NOT
    return f"(({x}&{a})|((({x})^_M64)&{b}))"

def gen_model(name, nstages, stages, desc, use_xor_x):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused8.py)."""',
        "import numpy as np",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "_M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0: return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        f"STAGES = {stages!r}",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f = rots
        lines.append(f"    ra,rb,rc,rd,re,rf = _rotl(x,{a}),_rotl(x,{b}),_rotl(x,{c}),_rotl(x,{d}),_rotl(x,{e}),_rotl(x,{f})")
        m1 = mux_expr("x", "ra", "rb")
        m2 = mux_expr("rc", "rd", "re")
        m3 = mux_expr("rf", "rg", "rh") if not use_xor_x else None
        # need rg, rh for 3rd mux in pure replacement
        if not use_xor_x:
            # pure replacement uses 3 MUXes, need 9 rotations but we have 6
            # use: MUX(x,ra,rb) ^ MUX(rc,rd,re) ^ MUX(rf,ra,rc) — reuse
            m3 = mux_expr("rf", "ra", "rc")
            lines.append(f"    x = ({m1} ^ {m2} ^ {m3}) & M64")
        else:
            lines.append(f"    x = (x ^ {m1} ^ {m2}) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, nstages, stages, desc, use_xor_x):
    lines = [f"// {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x,int r){r&=63;if(!r)return x;return (x<<r)|(x>>(64-r));}",
        "static uint64_t mux64(uint64_t s,uint64_t a,uint64_t b){return (s&a)|(~s&b);}",
        "uint64_t mix_hash(uint64_t v,uint64_t k){",
        "    uint64_t x=v^k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f = rots
        lines.append(f"    x=mux64(x,rotl64(x,{a}),rotl64(x,{b}))^mux64(rotl64(x,{c}),rotl64(x,{d}),rotl64(x,{e}))^mux64(rotl64(x,{f}),rotl64(x,{a}),rotl64(x,{c}));" if not use_xor_x else f"    x^=mux64(x,rotl64(x,{a}),rotl64(x,{b}))^mux64(rotl64(x,{c}),rotl64(x,{d}),rotl64(x,{e}));")
    lines += ["    x^=rotl64(k,13);", "    return x;", "}", ""]
    return "\n".join(lines)

def rotl_v(sig, r):
    return sig if r==0 else f"{{{sig}[{63-r}:0],{sig}[63:{64-r}]}}"

def gen_v(name, nstages, stages, desc, use_xor_x):
    lines = [f"// {name}: {desc} (gen_fused8.py)", f"module {name}(",
        "    input [63:0] v,", "    input [63:0] k,", "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f = rots
        for j,r in enumerate(rots):
            lines.append(f"    wire [63:0] s{i}{chr(97+j)} = {rotl_v(f'x{i}',r)};")
        # MUX(s,a,b) = (s&a)|(~s&b)
        lines.append(f"    wire [63:0] m{i}a = (x{i}&s{i}a)|(~x{i}&s{i}b);")
        lines.append(f"    wire [63:0] m{i}b = (s{i}c&s{i}d)|(~s{i}c&s{i}e);")
        if not use_xor_x:
            lines.append(f"    wire [63:0] m{i}c = (s{i}f&s{i}a)|(~s{i}f&s{i}c);")
            lines.append(f"    wire [63:0] x{i+1} = m{i}a ^ m{i}b ^ m{i}c;")
        else:
            lines.append(f"    wire [63:0] x{i+1} = x{i} ^ m{i}a ^ m{i}b;")
    n=len(stages)
    lines += ["    wire [63:0] kr = {k[50:0],k[63:51]};", f"    assign o = x{n} ^ kr;", "endmodule", ""]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, nstages, stages, desc) in SPECS:
        if only and name not in only: continue
        use_xor_x = "x ^=" in desc
        cdir = os.path.join(FB, name); os.makedirs(cdir, exist_ok=True)
        open(os.path.join(cdir, "model.py"), "w").write(gen_model(name, nstages, stages, desc, use_xor_x))
        open(os.path.join(cdir, "impl.c"), "w").write(gen_c(name, nstages, stages, desc, use_xor_x))
        open(os.path.join(cdir, "rtl.v"), "w").write(gen_v(name, nstages, stages, desc, use_xor_x))
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
        }
        open(os.path.join(cdir, "meta.json"), "w").write(json.dumps(meta, indent=1))
        print(f"generated {name}")

if __name__ == "__main__":
    main()
