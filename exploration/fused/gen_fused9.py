#!/usr/bin/env python3
"""Fused Wave-9: chi-based fusion.

Wave-8 MUX: KILL (diff 15.5-97.8) — MUX differentially weak.
Wave-5 maj3: PASS but 29.7u (too slow).

Wave-9: x ^= chi(x,ra,rb) ^ chi(rc,rd,re) ^ chi(rf,rg,rh)
chi(a,b,c) = a ^ ((~b)&c), so chi(x,ra,rb) = x ^ ((~ra)&rb).
x ^ chi(x,ra,rb) = (~ra)&rb — x cancels! Pure replacement, no linear trail.
chi is fast (~3.3u/stage like al_chi6). 5 stages est ~16.5u < 19.8u floor.

Also try 4-stage version.
"""
import json, os, sys

EXP = "/home/hatch/workspace/mix/exploration"
FB = os.path.join(EXP, "fast_battery", "candidates")

SPECS = [
    ("fz_chif_5", 5, [
        (3, 11, 23, 31, 43, 53),
        (7, 17, 29, 37, 47, 59),
        (5, 13, 27, 41, 49, 61),
        (9, 19, 33, 39, 51, 57),
        (11, 23, 35, 45, 55, 63),
    ], "5-stage fused chi: x ^= chi(x,ra,rb)^chi(rc,rd,re)^chi(rf,rg,rh)"),
    ("fz_chif_4", 4, [
        (3, 11, 23, 31, 43, 53),
        (7, 17, 29, 37, 47, 59),
        (5, 13, 27, 41, 49, 61),
        (9, 19, 33, 39, 51, 57),
    ], "4-stage fused chi"),
]

def chi_expr(a, b, c):
    # chi(a,b,c) = a ^ ((~b) & c); for numpy use ^_M64 for NOT
    return f"({a} ^ ((({b})^_M64)&{c}))"

def gen_model(name, nstages, stages, desc):
    lines = [
        f'"""Fused candidate {name}: {desc} (generated by gen_fused9.py)."""',
        "import numpy as np",
        "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "_M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
        "def _rotl(x, r):",
        "    r %= 64",
        "    if r == 0: return x",
        "    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
        f"STAGES = {stages!r}",
        "def mix_np(V, K):",
        "    x = np.asarray(V, dtype=np.uint64); k = np.asarray(K, dtype=np.uint64)",
        "    x = (x ^ k) & M64",
    ]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f = rots
        lines.append(f"    ra,rb,rc,rd,re,rf = _rotl(x,{a}),_rotl(x,{b}),_rotl(x,{c}),_rotl(x,{d}),_rotl(x,{e}),_rotl(x,{f})")
        t1 = chi_expr("x", "ra", "rb")
        t2 = chi_expr("rc", "rd", "re")
        t3 = chi_expr("rf", "ra", "rc")
        lines.append(f"    x = (x ^ {t1} ^ {t2} ^ {t3}) & M64")
    lines += [
        "    x = (x ^ _rotl(k, 13)) & M64",
        "    return x & M64",
        "def mix(v, k):",
        "    return int(mix_np(np.uint64(v), np.uint64(k)))",
        "",
    ]
    return "\n".join(lines)

def gen_c(name, nstages, stages, desc):
    lines = [f"// {name}: {desc}",
        "#include <stdint.h>",
        "static uint64_t rotl64(uint64_t x,int r){r&=63;if(!r)return x;return (x<<r)|(x>>(64-r));}",
        "static uint64_t chi64(uint64_t a,uint64_t b,uint64_t c){return a^((~b)&c);}",
        "uint64_t mix_hash(uint64_t v,uint64_t k){",
        "    uint64_t x=v^k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f = rots
        lines.append(f"    x^=chi64(x,rotl64(x,{a}),rotl64(x,{b}))^chi64(rotl64(x,{c}),rotl64(x,{d}),rotl64(x,{e}))^chi64(rotl64(x,{f}),rotl64(x,{a}),rotl64(x,{c}));")
    lines += ["    x^=rotl64(k,13);", "    return x;", "}", ""]
    return "\n".join(lines)

def rotl_v(sig, r):
    return sig if r==0 else f"{{{sig}[{63-r}:0],{sig}[63:{64-r}]}}"

def gen_v(name, nstages, stages, desc):
    lines = [f"// {name}: {desc} (gen_fused9.py)", f"module {name}(",
        "    input [63:0] v,", "    input [63:0] k,", "    output [63:0] o",
        ");",
        "    wire [63:0] x0 = v ^ k;"]
    for i, rots in enumerate(stages):
        a,b,c,d,e,f = rots
        for j,r in enumerate(rots):
            lines.append(f"    wire [63:0] s{i}{chr(97+j)} = {rotl_v(f'x{i}',r)};")
        # chi(a,b,c) = a ^ ((~b)&c)
        lines.append(f"    wire [63:0] t{i}a = x{i} ^ ((~s{i}a)&s{i}b);")
        lines.append(f"    wire [63:0] t{i}b = s{i}c ^ ((~s{i}d)&s{i}e);")
        lines.append(f"    wire [63:0] t{i}c = s{i}f ^ ((~s{i}a)&s{i}c);")
        lines.append(f"    wire [63:0] x{i+1} = x{i} ^ t{i}a ^ t{i}b ^ t{i}c;")
    n=len(stages)
    lines += ["    wire [63:0] kr = {k[50:0],k[63:51]};", f"    assign o = x{n} ^ kr;", "endmodule", ""]
    return "\n".join(lines)

def main():
    only = sys.argv[1:] or None
    for (name, nstages, stages, desc) in SPECS:
        if only and name not in only: continue
        cdir = os.path.join(FB, name); os.makedirs(cdir, exist_ok=True)
        open(os.path.join(cdir, "model.py"), "w").write(gen_model(name, nstages, stages, desc))
        open(os.path.join(cdir, "impl.c"), "w").write(gen_c(name, nstages, stages, desc))
        open(os.path.join(cdir, "rtl.v"), "w").write(gen_v(name, nstages, stages, desc))
        meta = {
            "name": name,
            "description": desc,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
        }
        open(os.path.join(cdir, "meta.json"), "w").write(json.dumps(meta, indent=1))
        print(f"generated {name}")

if __name__ == "__main__":
    main()
