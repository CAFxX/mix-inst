#!/usr/bin/env python3
"""Bundle generator for wave-37h (single-lane N-stage 1-AND + L-linear) KEEPs.

Usage: gen_wave37h.py <JSONL_FILE> <TRY> <NAME>
Reads the screen jsonl, extracts the KEEP schedule, writes model.py/impl.c/
rtl.v/meta.json into fast_battery/candidates/<NAME>/, and verifies model vs
triage bit-exactness on 2000 random vectors + golden vectors.
"""
import json
import random
import sys

import numpy as np

sys.path.insert(0, "/home/hatch/workspace/mix/exploration/fused")
sys.path.insert(0, "/home/hatch/workspace/mix/exploration")
from wave35_lib import rotl, M64

JSONL, TRY, NAME = sys.argv[1], int(sys.argv[2]), sys.argv[3]
rec = None
for line in open(JSONL):
    r = json.loads(line)
    if r["try"] == TRY:
        rec = r
        break
assert rec is not None, f"fail-loud: try {TRY} not found in {JSONL}"
assert rec["status"] == "KEEP", f"fail-loud: try {TRY} is {rec['status']}, not KEEP"
sched = [(s[0], s[1], tuple(s[2])) for s in rec["sched"]]
NSTAGES = len(sched)
NLIN = len(sched[0][2])
print(f"37h bundle: {NSTAGES} stages, L={NLIN}, z={rec['z']:.2f} zr={rec['zr']:.2f}")


def mix_ref(xs, K):
    xs = np.asarray(xs, dtype=np.uint64)
    K = np.asarray(K, dtype=np.uint64)
    x = (xs ^ K) & M64
    for a, b, lins in sched:
        v = x ^ (rotl(x, a) & rotl(x, b))
        for c in lins:
            v ^= rotl(x, c)
        x = v & M64
    return (x ^ rotl(K, 13)) & M64


import os
OUTD = f"/home/hatch/workspace/mix/exploration/fast_battery/candidates/{NAME}"
os.makedirs(OUTD, exist_ok=True)

# --- model.py ---
L = ["#!/usr/bin/env python3",
     '"""Wave-37h single-lane candidate (generated by gen_wave37h.py)."""',
     "import numpy as np",
     "",
     "M64 = (1 << 64) - 1",
     f"SCHED = {[(a, b, list(l)) for a, b, l in sched]!r}",
     "",
     "",
     "def _rotl(v, r):",
     "    r &= 63",
     "    if r == 0:",
     "        return v & M64",
     "    return ((v << r) | (v >> (64 - r))) & M64",
     "",
     "",
     "def mix(xs, k):",
     "    xs = np.asarray(xs, dtype=np.uint64)",
     "    k = np.asarray(k, dtype=np.uint64)",
     "    x = (xs ^ k) & M64",
     "    for a, b, lins in SCHED:",
     "        v = x ^ (_rotl(x, a) & _rotl(x, b))",
     "        for c in lins:",
     "            v ^= _rotl(x, c)",
     "        x = v & M64",
     "    return (x ^ _rotl(k, 13)) & M64",
     ""]
open(f"{OUTD}/model.py", "w").write("\n".join(L))

# --- impl.c ---
def rl64(var, r):
    if r == 0:
        return var
    return f"rotl64({var}, {r})"

C = ["#include <stdint.h>",
     "static inline uint64_t rotl64(uint64_t x, unsigned r) {",
     "    r &= 63;",
     "    return r ? (uint64_t)((x << r) | (x >> (64 - r))) : x;",
     "}",
     "",
     f"uint64_t mix_{NAME}(uint64_t x, uint64_t key) {{",
     "    x ^= key;"]
for i, (a, b, lins) in enumerate(sched):
    expr = f"x ^ ({rl64('x', a)} & {rl64('x', b)})"
    for c in lins:
        expr += f" ^ {rl64('x', c)}"
    C.append(f"    x = {expr};  /* stage {i+1} */")
C.append("    return x ^ rotl64(key, 13);")
C.append("}")
open(f"{OUTD}/impl.c", "w").write("\n".join(C) + "\n")

# --- rtl.v ---
def rtl_rot(var, r):
    r %= 64
    if r == 0:
        return var
    return "{%s[%d:0], %s[63:%d]}" % (var, 63 - r, var, 64 - r)

V = ["`timescale 1ns/1ps",
     f"module {NAME} (input wire [63:0] x, input wire [63:0] key, output wire [63:0] out);"]
for i in range(NSTAGES):
    V.append(f"    wire [63:0] x{i+1};")
V.append("    wire [63:0] x0;")
V.append("    assign x0 = x ^ key;")
for i, (a, b, lins) in enumerate(sched):
    terms = [f"x{i}", f"({rtl_rot(f'x{i}', a)} & {rtl_rot(f'x{i}', b)})"]
    for c in lins:
        terms.append(rtl_rot(f"x{i}", c))
    V.append(f"    assign x{i+1} = " + " ^ ".join(terms) + ";")
V.append(f"    assign out = x{NSTAGES} ^ {rtl_rot('key', 13)};")
V.append("endmodule")
open(f"{OUTD}/rtl.v", "w").write("\n".join(V) + "\n")

meta = {"name": NAME, "family": "wave37h-single-lane-dense",
        "construction": f"single-lane {NSTAGES}-stage 1-AND+{NLIN}-linear; pre x^K; post ^rotl(K,13)",
        "sched": [[a, b, list(l)] for a, b, l in sched],
        "triage": {"marg_margin": rec["marg_margin"], "seq_z": rec["z"], "rnd64_z": rec["zr"]},
        "source": f"fused/{JSONL.split('/')[-1]} try {TRY}"}
open(f"{OUTD}/meta.json", "w").write(json.dumps(meta, indent=2))

# --- verify: generated model vs triage reference, bit-exact ---
sys.path.insert(0, OUTD)
import importlib.util
spec = importlib.util.spec_from_file_location("cand_model", f"{OUTD}/model.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
rng = random.Random(0xBEEF)
xs = np.array([rng.getrandbits(64) for _ in range(2000)], dtype=np.uint64)
ks = np.array([rng.getrandbits(64) for _ in range(2000)], dtype=np.uint64)
got = mod.mix(xs, ks)
exp = mix_ref(xs, ks)
assert np.array_equal(got, exp), "FAIL-LOUD: generated model != triage reference"
print("model.py bit-exact vs triage reference on 2000 random vectors: OK")
gold = [(0, 0), (1, 0), (0, 1), (2**64 - 1, 2**64 - 1), (0xDEADBEEF, 0x123456789)]
gxs = np.array([g[0] for g in gold], dtype=np.uint64)
gks = np.array([g[1] for g in gold], dtype=np.uint64)
print("goldens:", [hex(int(v)) for v in mix_ref(gxs, gks)])
print(f"bundle written: {OUTD}")
