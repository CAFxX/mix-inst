#!/usr/bin/env python3
"""Batch-18 hybrid generator (Track 5, 2026-10-10).

Dual-AND-last-stage 5-stage hybrids, co-designed with track-3's 5-stage
DIFF wall theorem (DESIGN_RULES.md).

Thesis: a dual-AND stage `x ^= (ra&rb)^(rc&rd)^re` has a STRICTER quiet
condition than single AND (BOTH pairs must be missed by the input
difference). Per Rule 6 (S-box escape hatch: "any layer with a
stricter-than-pair quiet condition breaks the wall") and Rule 8 (strong
layer LAST), a dual-AND final stage should break the 5-stage wall at
~18.4u (4x3.35 + 5.0) -- under the 20.1u frontier.

Stage types:
  ('and', a, b, c):      x ^= (ra&rb)^rc            (3.35u)
  ('t3', a, b, c, e):    x ^= (ra&rb)^rc^re         (4.5u)
  ('dual', a,b,c,d,e):   x ^= (ra&rb)^(rc&rd)^re    (~5.0u)

Key schedule: x = val^key ... out = x^rotl(key,13).
Generates impl.c, rtl.v, model.py (bit-exact), meta.json.
"""
import json, os, subprocess, sys
import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

# Proxy search hits (2026-10-10)
SPECS = [
    ("hyb18_dual_a",
     [('t3', 19, 18, 9, 7), ('and', 21, 39, 56), ('and', 15, 59, 38),
      ('and', 51, 63, 56), ('dual', 10, 5, 55, 41, 3)],
     "5-stage [t3,and,and,and,dual]: dual-last-stage breaks wall, proxy z=6.0, est 19.55u"),
    ("hyb18_dual_b",
     [('and', 5, 4, 38), ('and', 63, 14, 12), ('and', 17, 49, 58),
      ('t3', 12, 62, 52, 4), ('dual', 12, 47, 45, 7, 50)],
     "5-stage [and,and,and,t3,dual]: dual-last-stage, proxy z=7.9, est 19.55u"),
    ("hyb18_dual_c",
     [('and', 59, 15, 57), ('and', 18, 12, 6), ('and', 37, 49, 53),
      ('and', 20, 41, 40), ('dual', 39, 63, 2, 11, 50)],
     "5-stage [and,and,and,and,dual]: cheapest dual-last-stage, proxy z=8.0, est 18.40u"),
]

def rotl(x, r):
    r %= 64
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64 if r else x

def apply_stage(x, st):
    if st[0] == 'and':
        _, a, b, c = st
        return (x ^ (rotl(x,a) & rotl(x,b)) ^ rotl(x,c)) & M64
    elif st[0] == 't3':
        _, a, b, c, e = st
        return (x ^ (rotl(x,a) & rotl(x,b)) ^ rotl(x,c) ^ rotl(x,e)) & M64
    elif st[0] == 'dual':
        _, a, b, c, d, e = st
        return (x ^ (rotl(x,a) & rotl(x,b)) ^ (rotl(x,c) & rotl(x,d)) ^ rotl(x,e)) & M64
    raise ValueError(st)

def model_hash(val, key, stages):
    x = np.uint64(val) ^ np.uint64(key)
    for st in stages:
        x = apply_stage(x, st)
    return int((x ^ rotl(np.uint64(key), 13)) & M64)

def rotl_v(sig, r):
    r %= 64
    if r == 0: return sig
    return "{%s[%d:0], %s[63:%d]}" % (sig, 63-r, sig, 64-r)

def build(name, stages, desc):
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)

    # ---- model.py ----
    with open(os.path.join(d, "model.py"), "w") as f:
        f.write('"""%s: %s (generated by hybrid/batch18/gen_batch18.py)"""\n' % (name, desc))
        f.write("import numpy as np\nM64=np.uint64(0xFFFFFFFFFFFFFFFF)\n")
        f.write("def rotl(x,r):\n    r%=64\n    return ((x<<np.uint64(r))|(x>>np.uint64(64-r)))&M64 if r else x\n")
        f.write("STAGES=%s\n" % repr([list(s) for s in stages]))
        f.write("def apply_stage(x,st):\n")
        f.write("    t=st[0]\n")
        f.write("    if t=='and':\n        _,a,b,c=st; return (x^(rotl(x,a)&rotl(x,b))^rotl(x,c))&M64\n")
        f.write("    if t=='t3':\n        _,a,b,c,e=st; return (x^(rotl(x,a)&rotl(x,b))^rotl(x,c)^rotl(x,e))&M64\n")
        f.write("    if t=='dual':\n        _,a,b,c,dd,e=st; return (x^(rotl(x,a)&rotl(x,b))^(rotl(x,c)&rotl(x,dd))^rotl(x,e))&M64\n")
        f.write("    raise ValueError(st)\n")
        f.write("def mix_hash(val,key):\n    x=np.uint64(val)^np.uint64(key)\n")
        f.write("    for st in STAGES:\n        x=apply_stage(x,st)\n")
        f.write("    return int((x^rotl(np.uint64(key),13))&M64)\n")
        # Battery interface: s1_screen.py load_candidate() requires module
        # attributes `mix` (scalar) and `mix_np` (vectorized). mix_hash alone
        # INFRA_FAILs (hyb18 batch, 2026-10-10). Keep all three consistent.
        f.write("def mix_np(V,K):\n")
        f.write("    x=np.asarray(V,dtype=np.uint64);k=np.asarray(K,dtype=np.uint64)\n")
        f.write("    x=(x^k)&M64\n")
        f.write("    for st in STAGES:\n        x=apply_stage(x,st)\n")
        f.write("    return (x^rotl(k,13))&M64\n")
        f.write("def mix(v,k):\n    return int(mix_np(np.uint64(v),np.uint64(k)))\n")

    # ---- impl.c ----
    L = []
    L.append("// %s: %s (generated by hybrid/batch18/gen_batch18.py)" % (name, desc))
    L.append("#include <stdint.h>")
    L.append("static inline uint64_t rotl64(uint64_t x, int r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    L.append("uint64_t mix_hash(uint64_t val, uint64_t key) {")
    L.append("    uint64_t x = val ^ key;")
    for i, st in enumerate(stages):
        if st[0] == 'and':
            _, a, b, c = st
            L.append("    { /* AND stage %d */" % i)
            L.append("        uint64_t ra=rotl64(x,%d),rb=rotl64(x,%d),rc=rotl64(x,%d);" % (a,b,c))
            L.append("        x ^= (ra & rb) ^ rc;")
            L.append("    }")
        elif st[0] == 't3':
            _, a, b, c, e = st
            L.append("    { /* T3 stage %d */" % i)
            L.append("        uint64_t ra=rotl64(x,%d),rb=rotl64(x,%d),rc=rotl64(x,%d),re=rotl64(x,%d);" % (a,b,c,e))
            L.append("        x ^= (ra & rb) ^ rc ^ re;")
            L.append("    }")
        elif st[0] == 'dual':
            _, a, b, c, dd, e = st
            L.append("    { /* DUAL stage %d */" % i)
            L.append("        uint64_t ra=rotl64(x,%d),rb=rotl64(x,%d),rc=rotl64(x,%d),rd=rotl64(x,%d),re=rotl64(x,%d);" % (a,b,c,dd,e))
            L.append("        x ^= (ra & rb) ^ (rc & rd) ^ re;")
            L.append("    }")
    L.append("    return x ^ rotl64(key, 13);")
    L.append("}")
    with open(os.path.join(d, "impl.c"), "w") as f:
        f.write("\n".join(L) + "\n")

    # ---- rtl.v ----
    V = []
    V.append("// %s: %s (generated by hybrid/batch18/gen_batch18.py)" % (name, desc))
    V.append("module mix_hash(input [63:0] val, input [63:0] key, output [63:0] out);")
    V.append("    wire [63:0] x0 = val ^ key;")
    for i, st in enumerate(stages):
        xi = "x%d" % i
        xo = "x%d" % (i+1)
        if st[0] == 'and':
            _, a, b, c = st
            V.append("    wire [63:0] %s_ra = %s;" % (xo, rotl_v(xi, a)))
            V.append("    wire [63:0] %s_rb = %s;" % (xo, rotl_v(xi, b)))
            V.append("    wire [63:0] %s_rc = %s;" % (xo, rotl_v(xi, c)))
            V.append("    wire [63:0] %s = %s ^ (%s_ra & %s_rb) ^ %s_rc;" % (xo, xi, xo, xo, xo))
        elif st[0] == 't3':
            _, a, b, c, e = st
            V.append("    wire [63:0] %s_ra = %s;" % (xo, rotl_v(xi, a)))
            V.append("    wire [63:0] %s_rb = %s;" % (xo, rotl_v(xi, b)))
            V.append("    wire [63:0] %s_rc = %s;" % (xo, rotl_v(xi, c)))
            V.append("    wire [63:0] %s_re = %s;" % (xo, rotl_v(xi, e)))
            V.append("    wire [63:0] %s = %s ^ (%s_ra & %s_rb) ^ %s_rc ^ %s_re;" % (xo, xi, xo, xo, xo, xo))
        elif st[0] == 'dual':
            _, a, b, c, dd, e = st
            V.append("    wire [63:0] %s_ra = %s;" % (xo, rotl_v(xi, a)))
            V.append("    wire [63:0] %s_rb = %s;" % (xo, rotl_v(xi, b)))
            V.append("    wire [63:0] %s_rc = %s;" % (xo, rotl_v(xi, c)))
            V.append("    wire [63:0] %s_rd = %s;" % (xo, rotl_v(xi, dd)))
            V.append("    wire [63:0] %s_re = %s;" % (xo, rotl_v(xi, e)))
            V.append("    wire [63:0] %s = %s ^ (%s_ra & %s_rb) ^ (%s_rc & %s_rd) ^ %s_re;" % (xo, xi, xo, xo, xo, xo, xo))
    V.append("    assign out = x%d ^ %s;" % (len(stages), rotl_v("key", 13)))
    V.append("endmodule")
    with open(os.path.join(d, "rtl.v"), "w") as f:
        f.write("\n".join(V) + "\n")

    # ---- meta.json ----
    meta = {"name": name, "desc": desc, "track": "5/hybrid",
            "batch": 18, "stages": [list(s) for s in stages]}
    with open(os.path.join(d, "meta.json"), "w") as f:
        json.dump(meta, f, indent=1)

    # ---- bit-exact check: model vs C ----
    test_c = os.path.join("/tmp", "test_%s.c" % name)
    with open(test_c, "w") as f:
        f.write('#include <stdio.h>\n#include <stdint.h>\n')
        # inline impl.c content minus the mix_hash def, then add main
        impl = open(os.path.join(d, "impl.c")).read()
        f.write(impl + "\n")
        f.write('int main(){uint64_t vs[]={0,1,0x123456789abcdef0ULL,0xffffffffffffffffULL,4660};')
        f.write('uint64_t ks[]={0,0x123456789abcdef0ULL};')
        f.write('for(int i=0;i<5;i++)for(int j=0;j<2;j++)printf("%llx\\n",(unsigned long long)mix_hash(vs[i],ks[j]));return 0;}')
    exe = os.path.join("/tmp", "test_%s" % name)
    r = subprocess.run(["gcc", "-O2", "-o", exe, test_c], capture_output=True, text=True)
    if r.returncode != 0:
        print("GCC FAIL", name, r.stderr[:500]); return False
    r = subprocess.run([exe], capture_output=True, text=True)
    c_out = r.stdout.strip().split("\n")
    sys.path.insert(0, d)
    import importlib.util
    spec = importlib.util.spec_from_file_location("m_%s" % name, os.path.join(d, "model.py"))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    vals = [0,1,0x123456789abcdef0,0xffffffffffffffff,4660]
    keys = [0,0x123456789abcdef0]
    ok = True
    idx = 0
    for v in vals:
        for k in keys:
            py = m.mix_hash(v, k)
            cc = int(c_out[idx], 16); idx += 1
            if py != cc:
                print("MISMATCH", name, hex(v), hex(k), hex(py), hex(cc)); ok = False
            # battery interface must agree with mix_hash
            if m.mix(v, k) != py:
                print("MIX-IFACE MISMATCH", name, hex(v), hex(k)); ok = False
    # vectorized interface on arrays
    V = [0,1,0x123456789abcdef0,0xffffffffffffffff,4660]*2
    K = [0x123456789abcdef0,0]*5
    vn = np.array(V, dtype=np.uint64); kn = np.array(K, dtype=np.uint64)
    on = m.mix_np(vn, kn)
    for i in range(len(V)):
        if int(on[i]) != m.mix_hash(V[i], K[i]):
            print("MIXNP MISMATCH", name, i); ok = False
            break
    print(("BITEXACT OK " if ok else "BITEXACT FAIL ") + name)
    return ok

if __name__ == '__main__':
    if not SPECS:
        print("No SPECS defined; populate from proxy search hits.")
        sys.exit(1)
    allok = True
    for name, stages, desc in SPECS:
        allok &= build(name, stages, desc)
    sys.exit(0 if allok else 1)
