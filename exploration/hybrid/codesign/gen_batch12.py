#!/usr/bin/env python3
"""Batch-12 hybrid generator (Track 5, 2026-10-10 respawn).

Heterogeneous AND/S-box cascade co-design.

Thesis: the 5-stage AND cascade dies on DIFF (batch-7, batch-11/and5_finalPL).
A 4-bit S-box layer (rasC2_0 -- proven S2-clean in cd2 batch-4, degree 3,
max DDT 4) adds a full layer of degree-3 nonlinearity in ~2-4u, where a
P-box (batch-11 finalPL) added zero differential strength and failed.

Co-design point: the AND stages' rotations are free wiring. Placing the
S-box layer AFTER/AMONG AND stages lets the surrounding AND triplets
diffuse the S-box nibbles -- the rotation schedule does double duty.
This is NOT "P-boxes in al_and6a" (batch-6/8, exhausted); the nonlinear
layer changes the differential game.

Candidates (all: x=val^key ... x=L513(x) ... out=x^rotl(key,13)):
  hyb12_asb5a   5xAND (triplets 1-5) -> SBOX -> L   quality probe: does the
               S-box fix the 5-stage DIFF death? (~21-22u, likely dominated)
  hyb12_asb4a   4xAND (triplets 1-4) -> SBOX -> L   FRONTIER CHALLENGER
               (~18-19u if S-box ~3u)
  hyb12_sand2a  2xAND -> SBOX -> 2xAND (triplets 3-4) -> L   interleaved:
               S-box sees less-diffused input, output gets 2 more AND stages.

S-box: rasC2_0 = [0,1,2,3,4,6,8,11,13,9,7,15,12,10,5,14] (S2-clean).

Generates impl.c, rtl.v, model.py (self-contained, bit-exact), meta.json.
Verifies: model vs C (N vecs), RTL vs model via iverilog (N vecs).
"""
import json
import os
import random
import subprocess
import sys

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

AND6A = [(1, 2, 13), (7, 19, 5), (3, 11, 29),
         (17, 31, 7), (11, 23, 37), (19, 41, 23)]
SBOX = [0, 1, 2, 3, 4, 6, 8, 11, 13, 9, 7, 15, 12, 10, 5, 14]  # rasC2_0
KEYS = ["0x123456789abcdef0", "0x0"]

# (name, kind, params, desc)
# kind "asb": n_and AND stages, then SBOX, then L
# kind "sand": n1 AND stages, SBOX, n2 AND stages (triplet offset), then L
SPECS = [
    ("hyb12_asb5a", "asb", dict(n_and=5),
     "5xAND (al_and6a triplets 1-5) + rasC2_0 S-box layer + L(5,13): does S-box fix 5-stage DIFF death?"),
    ("hyb12_asb4a", "asb", dict(n_and=4),
     "4xAND (triplets 1-4) + rasC2_0 S-box layer + L(5,13): FRONTIER CHALLENGER"),
    ("hyb12_sand2a", "sand", dict(n1=2, n2=2, off=2),
     "2xAND + S-box + 2xAND (triplets 3-4) + L(5,13): interleaved heterogeneous"),
]


def rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def sbox64(x):
    y = np.uint64(0)
    for i in range(16):
        nib = (x >> np.uint64(4 * i)) & np.uint64(0xF)
        y |= np.uint64(SBOX[int(nib)]) << np.uint64(4 * i)
    return y & M64


def lin513(x):
    return (x ^ rotl(x, 5) ^ rotl(x, 13)) & M64


def and_stages(x, sched):
    for (a, b, c) in sched:
        ra, rb, rc = rotl(x, a), rotl(x, b), rotl(x, c)
        x = (x ^ (ra & rb) ^ rc) & M64
    return x


def model_hash(val, key, kind, p):
    x = np.uint64(val) ^ np.uint64(key)
    k = np.uint64(key)
    if kind == "asb":
        x = and_stages(x, AND6A[:p["n_and"]])
    else:  # sand: n1 AND, SBOX, n2 AND from offset
        x = and_stages(x, AND6A[:p["n1"]])
        x = sbox64(x)
        x = and_stages(x, AND6A[p["off"]:p["off"] + p["n2"]])
        x = lin513(x)
        return int((x ^ rotl(k, 13)) & M64)
    x = sbox64(x)
    x = lin513(x)
    return int((x ^ rotl(k, 13)) & M64)


def rotl_v(sig, r):
    if r % 64 == 0:
        return sig
    r %= 64
    return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)


def build(name, kind, p, desc):
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)

    # ---- impl.c ----
    L = []
    L.append("// %s: %s (generated by hybrid/codesign/gen_batch12.py)" % (name, desc))
    L.append("#include <stdint.h>")
    L.append("static inline uint64_t rotl64(uint64_t x, int r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    L.append("static const uint8_t SBOX[16] = {%s};" % ",".join(map(str, SBOX)))
    L.append("static inline uint64_t sbox64(uint64_t x) {")
    L.append("    uint64_t y = 0;")
    L.append("    for (int i = 0; i < 16; i++)")
    L.append("        y |= (uint64_t)SBOX[(x >> (4*i)) & 0xFu] << (4*i);")
    L.append("    return y;")
    L.append("}")
    L.append("static inline uint64_t lin513(uint64_t x) {")
    L.append("    return x ^ rotl64(x, 5) ^ rotl64(x, 13);")
    L.append("}")
    L.append("uint64_t mix_hash(uint64_t val, uint64_t key) {")
    L.append("    uint64_t x = val ^ key;")
    if kind == "asb":
        sched = AND6A[:p["n_and"]]
        for i, (a, b, c) in enumerate(sched):
            L.append("    { /* AND stage %d: (%d,%d,%d) */" % (i, a, b, c))
            L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d), rc = rotl64(x, %d);"
                     % (a, b, c))
            L.append("        x ^= (ra & rb) ^ rc;")
            L.append("    }")
        L.append("    x = sbox64(x);")
    else:
        for i, (a, b, c) in enumerate(AND6A[:p["n1"]]):
            L.append("    { /* AND stage %d: (%d,%d,%d) */" % (i, a, b, c))
            L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d), rc = rotl64(x, %d);"
                     % (a, b, c))
            L.append("        x ^= (ra & rb) ^ rc;")
            L.append("    }")
        L.append("    x = sbox64(x);")
        for j, (a, b, c) in enumerate(AND6A[p["off"]:p["off"] + p["n2"]]):
            L.append("    { /* AND stage %d: (%d,%d,%d) */" % (p["off"] + j, a, b, c))
            L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d), rc = rotl64(x, %d);"
                     % (a, b, c))
            L.append("        x ^= (ra & rb) ^ rc;")
            L.append("    }")
    L.append("    x = lin513(x);")
    L.append("    x ^= rotl64(key, 13);")
    L.append("    return x;")
    L.append("}")
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    # ---- rtl.v ----
    V = []
    V.append("// %s: %s (generated by hybrid/codesign/gen_batch12.py)" % (name, desc))
    V.append("module %s(" % name)
    V.append("    input [63:0] val,")
    V.append("    input [63:0] key,")
    V.append("    output [63:0] out")
    V.append(");")
    V.append("    function [3:0] sb(input [3:0] z);")
    V.append("        begin")
    V.append("            case (z)")
    for i, o in enumerate(SBOX):
        V.append("                4'h%x: sb = 4'h%x;" % (i, o))
    V.append("                default: sb = 4'h0;")
    V.append("            endcase")
    V.append("        end")
    V.append("    endfunction")
    V.append("    wire [63:0] x0 = val ^ key;")
    cur = "x0"
    idx = 0
    def and_stage_v(cur, a, b, c, idx):
        vv = []
        vv.append("    wire [63:0] s%da = %s;" % (idx, rotl_v(cur, a)))
        vv.append("    wire [63:0] s%db = %s;" % (idx, rotl_v(cur, b)))
        vv.append("    wire [63:0] s%dc = %s;" % (idx, rotl_v(cur, c)))
        vv.append("    wire [63:0] t%d = %s ^ (s%da & s%db) ^ s%dc;" % (idx, cur, idx, idx, idx))
        return vv, "t%d" % idx
    def sbox_stage_v(cur, tag):
        nibs = []
        for i in range(16):
            nibs.append("sb(%s[%d:%d])" % (cur, 4 * i + 3, 4 * i))
        return ["    wire [63:0] %s = {%s};" % (tag, ", ".join(reversed(nibs)))], tag
    if kind == "asb":
        for (a, b, c) in AND6A[:p["n_and"]]:
            vv, cur = and_stage_v(cur, a, b, c, idx); idx += 1
            V.extend(vv)
        vv, cur = sbox_stage_v(cur, "sbx"); V.extend(vv)
    else:
        for (a, b, c) in AND6A[:p["n1"]]:
            vv, cur = and_stage_v(cur, a, b, c, idx); idx += 1
            V.extend(vv)
        vv, cur = sbox_stage_v(cur, "sbx"); V.extend(vv)
        for (a, b, c) in AND6A[p["off"]:p["off"] + p["n2"]]:
            vv, cur = and_stage_v(cur, a, b, c, idx); idx += 1
            V.extend(vv)
    V.append("    wire [63:0] lf = %s ^ %s ^ %s;" % (cur, rotl_v(cur, 5), rotl_v(cur, 13)))
    V.append("    wire [63:0] kr = {key[50:0], key[63:51]};")
    V.append("    assign out = lf ^ kr;")
    V.append("endmodule")
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    # ---- model.py ----
    P = []
    P.append('"""%s: %s. Self-contained bit-exact model."""' % (name, desc))
    P.append("import numpy as np")
    P.append("M64 = np.uint64(0xFFFFFFFFFFFFFFFF)")
    P.append("SBOX = %s" % SBOX)
    P.append("")
    P.append("def _rotl(x, r):")
    P.append("    r %= 64")
    P.append("    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64")
    P.append("")
    P.append("def _sbox64(x):")
    P.append("    # vectorized: works for scalar np.uint64 AND ndarrays (mix_np path).")
    P.append("    # A scalar-only version (int(...) per nibble) raises TypeError on the")
    P.append("    # S1 vector path -- see hyb12-s1s2-20261010 INFRA_FAIL (2026-10-10).")
    P.append("    x = np.asarray(x, dtype=np.uint64)")
    P.append("    S = np.asarray(SBOX, dtype=np.uint64)")
    P.append("    y = np.zeros_like(x)")
    P.append("    for i in range(16):")
    P.append("        y |= S[((x >> np.uint64(4*i)) & np.uint64(0xF))] << np.uint64(4*i)")
    P.append("    return y & M64")
    P.append("")
    P.append("def _lin(x):")
    P.append("    return (x ^ _rotl(x, 5) ^ _rotl(x, 13)) & M64")
    P.append("")
    P.append("AND6A = %s" % AND6A)
    P.append("")
    P.append("def _mix_core(x, k):")
    if kind == "asb":
        P.append("    for (a, b, c) in AND6A[:%d]:" % p["n_and"])
        P.append("        ra, rb, rc = _rotl(x, a), _rotl(x, b), _rotl(x, c)")
        P.append("        x = (x ^ (ra & rb) ^ rc) & M64")
        P.append("    x = _sbox64(x)")
    else:
        P.append("    for (a, b, c) in AND6A[:%d]:" % p["n1"])
        P.append("        ra, rb, rc = _rotl(x, a), _rotl(x, b), _rotl(x, c)")
        P.append("        x = (x ^ (ra & rb) ^ rc) & M64")
        P.append("    x = _sbox64(x)")
        P.append("    for (a, b, c) in AND6A[%d:%d]:" % (p["off"], p["off"] + p["n2"]))
        P.append("        ra, rb, rc = _rotl(x, a), _rotl(x, b), _rotl(x, c)")
        P.append("        x = (x ^ (ra & rb) ^ rc) & M64")
    P.append("    x = _lin(x)")
    P.append("    return (x ^ _rotl(k, 13)) & M64")
    P.append("")
    P.append("def mix_hash(val, key):")
    P.append("    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))")
    P.append("")
    P.append("def mix_np(V, K):")
    P.append("    V = np.asarray(V, dtype=np.uint64)")
    P.append("    K = np.asarray(K, dtype=np.uint64)")
    P.append("    return _mix_core(V ^ K, K)")
    P.append("")
    P.append("def mix(v, k):")
    P.append("    return mix_hash(v, k)")
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    # ---- meta.json ----
    goldens = []
    for vk, kk in [("0x0", KEYS[0]), (KEYS[0], "0x0")]:
        out = model_hash(int(vk, 16), int(kk, 16), kind, p)
        goldens.append({"val": vk, "key": kk, "out": hex(out)})
    meta = {
        "name": name,
        "description": desc,
        "rtl_top": name,
        "screen_keys": KEYS,
        "practrand_keys": KEYS,
        "goldens": goldens,
    }
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1) + "\n")
    print("generated %s: goldens %s, %s" % (name, goldens[0]["out"], goldens[1]["out"]))
    return d


def verify(d, name, kind, p, nvec=200):
    """Bit-exact: model vs C, RTL vs model (iverilog)."""
    # --- C harness ---
    harness = os.path.join(d, "_harness.c")
    open(harness, "w").write(
        '#include <stdio.h>\n#include <stdint.h>\n#include <inttypes.h>\n'
        'uint64_t mix_hash(uint64_t v, uint64_t k);\n'
        'int main(void){uint64_t v,k;\n'
        ' while(scanf("%"SCNx64" %"SCNx64,&v,&k)==2)\n'
        '  printf("%016"PRIx64"\\n",mix_hash(v,k));\n'
        ' return 0;}\n')
    # strip mix_hash's own main if any (impl.c has none); compile impl.c + harness
    exe = os.path.join(d, "_harness")
    r = subprocess.run(["gcc", "-O2", "-o", exe, os.path.join(d, "impl.c"), harness],
                       capture_output=True, text=True, timeout=60)
    assert r.returncode == 0, "gcc failed: %s" % r.stderr
    random.seed(1234)
    vecs = [(random.getrandbits(64), random.getrandbits(64)) for _ in range(nvec)]
    # model outputs
    sys.path.insert(0, d)
    import importlib
    mod = importlib.import_module("model")
    importlib.reload(mod)
    sys.path.pop(0)
    exp = [mod.mix_hash(v, k) for v, k in vecs]
    inp = "".join("%x %x\n" % (v, k) for v, k in vecs)
    r = subprocess.run([exe], input=inp, capture_output=True, text=True, timeout=120)
    assert r.returncode == 0, "harness failed"
    got = [int(x, 16) for x in r.stdout.strip().split()]
    assert got == exp, "model vs C MISMATCH on %d/%d" % (
        sum(1 for a, b in zip(got, exp) if a != b), nvec)
    print("  %s: model vs C %d/%d OK" % (name, nvec, nvec))

    # --- RTL via iverilog ---
    tb = os.path.join(d, "_tb.v")
    T = []
    T.append("module tb;")
    T.append("  reg [63:0] val, key;")
    T.append("  wire [63:0] out;")
    T.append("  %s dut(.val(val), .key(key), .out(out));" % name)
    T.append("  initial begin")
    for v, k in vecs[:20]:
        T.append("    val = 64'h%016x; key = 64'h%016x; #1;" % (v, k))
        T.append('    $display("%h", out);')
    T.append("    $finish;")
    T.append("  end")
    T.append("endmodule")
    open(tb, "w").write("\n".join(T) + "\n")
    vvp = os.path.join(d, "_tb.vvp")
    r = subprocess.run(["iverilog", "-o", vvp, os.path.join(d, "rtl.v"), tb],
                       capture_output=True, text=True, timeout=120)
    assert r.returncode == 0, "iverilog compile failed: %s" % r.stderr
    r = subprocess.run(["vvp", vvp], capture_output=True, text=True, timeout=120)
    assert r.returncode == 0, "vvp failed: %s" % r.stderr
    import re
    gotv = [int(x, 16) for x in re.findall(r"(?m)^[0-9a-fA-F]{16}$", r.stdout)]
    expv = exp[:20]
    assert gotv == expv, "RTL vs model MISMATCH"
    print("  %s: RTL vs model 20/20 OK" % name)
    # cleanup scratch
    for f in [harness, exe, tb, vvp]:
        try: os.remove(f)
        except OSError: pass


if __name__ == "__main__":
    for spec in SPECS:
        d = build(*spec)
    print("batch-12 generation complete; verifying bit-exactness...")
    for (name, kind, p, desc) in SPECS:
        d = os.path.join(OUT, name)
        verify(d, name, kind, p)
    print("batch-12 ALL BIT-EXACT OK")
