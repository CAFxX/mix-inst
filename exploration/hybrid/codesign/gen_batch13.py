#!/usr/bin/env python3
"""Batch-13 hybrid generator (Track 5, 2026-10-10 respawn).

Co-design for SPEED: get a 5-stage S-box hybrid under 20.1u.

Background (batch-12):
- hyb12_asb4a (4xAND + SBOX + L, 19.4u): S1-FLAG DIFF, CATASTROPHIC.
  Local diffprof: 50/72 deltas |z|>9, max|z|=449 @ bit44.
  4 AND stages provide insufficient differential diffusion; the nibble-local
  S-box cannot compensate for structured input differences.
- hyb12_asb5a (5xAND + SBOX + L, 22.3u): S1 CAL_PASS + S2 PASS (max|z|=6.4).
- hyb12_sand2a (2+2 interleaved, 20.2u): S1-FLAG DIFF.

Diagnosis: the S-box provides ~1-1.5 AND-stages of differential strength for
~5.5u (SBOX 3.5u + L 2u) -- a worse trade than an AND stage (3.35u). Placement
of a single S-box after/between AND stages cannot close the gap for 4xAND.

Batch-13 tries structurally different arrangements:

1. hyb13_sbfirst_a: SBOX -> 4xAND (triplets 1-4) -> L(5,13). ~18.9u est.
   S-box FIRST bounds input differentials cleanly (DDT<=4 per nibble), then
   the AND cascade diffuses. Untested arrangement; the S-box sees raw input
   diffs (not AND-structured ones).

2. hyb13_minispn_a: 3xAND (1-3) -> SBOX -> ROT(2) -> SBOX -> L(5,13). ~19.05u est.
   Mini-SPN: double S-box with free rotation between. ROT(2) splits nibbles
   (bit i -> i+2, so a 4-bit nibble diff spreads across 2 nibbles), ensuring
   the second S-box sees well-distributed differences. Tests whether double
   S-box strength compensates for fewer AND stages.

3. hyb13_rotalign_a: 4xAND (1-4) -> ROT(2) -> SBOX -> L(5,13). ~18.9u est.
   Control: tests whether nibble alignment (not fundamental strength) is the
   issue. Expected to fail (catastrophic failure unlikely alignment-specific),
   but cheap to test and falsifies the hypothesis cleanly.

4. hyb13_sbfirst5_a: SBOX -> 5xAND (1-5) -> L(5,13). ~22.25u est.
   Quality control: if S-box-first is viable, this should pass S1/S2 (dominated
   on speed, but proves the arrangement). If it fails, S-box-first is dead.

S-box: rasC2_0 = [0,1,2,3,4,6,8,11,13,9,7,15,12,10,5,14] (S2-clean, max DDT 4).
"""
import json
import os
import sys

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

AND6A = [(1, 2, 13), (7, 19, 5), (3, 11, 29),
         (17, 31, 7), (11, 23, 37), (19, 41, 23)]
SBOX = [0, 1, 2, 3, 4, 6, 8, 11, 13, 9, 7, 15, 12, 10, 5, 14]  # rasC2_0

# (name, kind, params, desc)
SPECS = [
    ("hyb13_sbfirst_a", "sbfirst", dict(n_and=4),
     "SBOX -> 4xAND (triplets 1-4) + L(5,13): sbox-first arrangement"),
    ("hyb13_minispn_a", "minispn", dict(n_and=3, rot=2),
     "3xAND (1-3) -> SBOX -> ROT(2) -> SBOX -> L(5,13): mini-SPN double sbox"),
    ("hyb13_rotalign_a", "rotalign", dict(n_and=4, rot=2),
     "4xAND (1-4) -> ROT(2) -> SBOX -> L(5,13): nibble-alignment control"),
    ("hyb13_sbfirst5_a", "sbfirst", dict(n_and=5),
     "SBOX -> 5xAND (1-5) + L(5,13): sbox-first quality control (dominated)"),
]


def rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def sbox64(x):
    x = np.asarray(x, dtype=np.uint64)
    S = np.asarray(SBOX, dtype=np.uint64)
    y = np.zeros_like(x)
    for i in range(16):
        y |= S[((x >> np.uint64(4 * i)) & np.uint64(0xF))] << np.uint64(4 * i)
    return y & M64


def lin513(x):
    return (x ^ rotl(x, 5) ^ rotl(x, 13)) & M64


def and_stages(x, sched):
    for (a, b, c) in sched:
        ra, rb, rc = rotl(x, a), rotl(x, b), rotl(x, c)
        x = (x ^ (ra & rb) ^ rc) & M64
    return x


def model_hash(val, key, kind, p):
    x = np.uint64(val) ^ np.uint64(key)
    k = np.uint64(key)
    if kind == "sbfirst":
        x = sbox64(x)
        x = and_stages(x, AND6A[:p["n_and"]])
    elif kind == "minispn":
        x = and_stages(x, AND6A[:p["n_and"]])
        x = sbox64(x)
        x = rotl(x, p["rot"])
        x = sbox64(x)
    elif kind == "rotalign":
        x = and_stages(x, AND6A[:p["n_and"]])
        x = rotl(x, p["rot"])
        x = sbox64(x)
    x = lin513(x)
    return int((x ^ rotl(k, 13)) & M64)


def rotl_v(sig, r):
    if r % 64 == 0:
        return sig
    r %= 64
    return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)


def build(name, kind, p, desc):
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)

    # ---- impl.c ----
    L = []
    L.append("// %s: %s (generated by hybrid/codesign/gen_batch13.py)" % (name, desc))
    L.append("#include <stdint.h>")
    L.append("static inline uint64_t rotl64(uint64_t x, int r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    L.append("static const uint8_t SBOX[16] = {%s};" % ",".join(map(str, SBOX)))
    L.append("static inline uint64_t sbox64(uint64_t x) {")
    L.append("    uint64_t y = 0;")
    L.append("    for (int i = 0; i < 16; i++)")
    L.append("        y |= (uint64_t)SBOX[(x >> (4*i)) & 0xFu] << (4*i);")
    L.append("    return y;")
    L.append("}")
    L.append("static inline uint64_t lin513(uint64_t x) {")
    L.append("    return x ^ rotl64(x, 5) ^ rotl64(x, 13);")
    L.append("}")
    L.append("uint64_t mix_hash(uint64_t val, uint64_t key) {")
    L.append("    uint64_t x = val ^ key;")
    if kind == "sbfirst":
        L.append("    x = sbox64(x);")
        for i, (a, b, c) in enumerate(AND6A[:p["n_and"]]):
            L.append("    { /* AND stage %d: (%d,%d,%d) */" % (i, a, b, c))
            L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d), rc = rotl64(x, %d);"
                     % (a, b, c))
            L.append("        x ^= (ra & rb) ^ rc;")
            L.append("    }")
    elif kind == "minispn":
        for i, (a, b, c) in enumerate(AND6A[:p["n_and"]]):
            L.append("    { /* AND stage %d: (%d,%d,%d) */" % (i, a, b, c))
            L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d), rc = rotl64(x, %d);"
                     % (a, b, c))
            L.append("        x ^= (ra & rb) ^ rc;")
            L.append("    }")
        L.append("    x = sbox64(x);")
        L.append("    x = rotl64(x, %d);" % p["rot"])
        L.append("    x = sbox64(x);")
    elif kind == "rotalign":
        for i, (a, b, c) in enumerate(AND6A[:p["n_and"]]):
            L.append("    { /* AND stage %d: (%d,%d,%d) */" % (i, a, b, c))
            L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d), rc = rotl64(x, %d);"
                     % (a, b, c))
            L.append("        x ^= (ra & rb) ^ rc;")
            L.append("    }")
        L.append("    x = rotl64(x, %d);" % p["rot"])
        L.append("    x = sbox64(x);")
    L.append("    x = lin513(x);")
    L.append("    x ^= rotl64(key, 13);")
    L.append("    return x;")
    L.append("}")
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    # ---- rtl.v ----
    V = []
    V.append("// %s: %s (generated by hybrid/codesign/gen_batch13.py)" % (name, desc))
    V.append("module %s(" % name)
    V.append("    input [63:0] val,")
    V.append("    input [63:0] key,")
    V.append("    output [63:0] out")
    V.append(");")
    V.append("    function [3:0] sb(input [3:0] z);")
    V.append("        begin")
    V.append("            case (z)")
    for i, o in enumerate(SBOX):
        V.append("                4'h%x: sb = 4'h%x;" % (i, o))
    V.append("                default: sb = 4'h0;")
    V.append("            endcase")
    V.append("        end")
    V.append("    endfunction")
    V.append("    wire [63:0] x0 = val ^ key;")
    cur = "x0"
    idx = 0

    def and_stage_v(cur, a, b, c, idx):
        vv = []
        vv.append("    wire [63:0] s%da = %s;" % (idx, rotl_v(cur, a)))
        vv.append("    wire [63:0] s%db = %s;" % (idx, rotl_v(cur, b)))
        vv.append("    wire [63:0] s%dc = %s;" % (idx, rotl_v(cur, c)))
        vv.append("    wire [63:0] t%d = %s ^ (s%da & s%db) ^ s%dc;" % (idx, cur, idx, idx, idx))
        return vv, "t%d" % idx

    def sbox_stage_v(cur, tag):
        nibs = []
        for i in range(16):
            nibs.append("sb(%s[%d:%d])" % (cur, 4 * i + 3, 4 * i))
        return ["    wire [63:0] %s = {%s};" % (tag, ", ".join(reversed(nibs)))], tag

    def rot_stage_v(cur, r, tag):
        return ["    wire [63:0] %s = %s;" % (tag, rotl_v(cur, r))], tag

    if kind == "sbfirst":
        vv, cur = sbox_stage_v(cur, "sbx0"); V.extend(vv)
        for (a, b, c) in AND6A[:p["n_and"]]:
            vv, cur = and_stage_v(cur, a, b, c, idx); idx += 1; V.extend(vv)
    elif kind == "minispn":
        for (a, b, c) in AND6A[:p["n_and"]]:
            vv, cur = and_stage_v(cur, a, b, c, idx); idx += 1; V.extend(vv)
        vv, cur = sbox_stage_v(cur, "sbx0"); V.extend(vv)
        vv, cur = rot_stage_v(cur, p["rot"], "rtx"); V.extend(vv)
        vv, cur = sbox_stage_v(cur, "sbx1"); V.extend(vv)
    elif kind == "rotalign":
        for (a, b, c) in AND6A[:p["n_and"]]:
            vv, cur = and_stage_v(cur, a, b, c, idx); idx += 1; V.extend(vv)
        vv, cur = rot_stage_v(cur, p["rot"], "rtx"); V.extend(vv)
        vv, cur = sbox_stage_v(cur, "sbx0"); V.extend(vv)
    V.append("    wire [63:0] lf = %s ^ %s ^ %s;" % (cur, rotl_v(cur, 5), rotl_v(cur, 13)))
    V.append("    wire [63:0] kr = {key[50:0], key[63:51]};")
    V.append("    assign out = lf ^ kr;")
    V.append("endmodule")
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    # ---- model.py ----
    P = []
    P.append('"""%s: %s. Self-contained bit-exact model."""' % (name, desc))
    P.append("import numpy as np")
    P.append("M64 = np.uint64(0xFFFFFFFFFFFFFFFF)")
    P.append("SBOX = %s" % SBOX)
    P.append("")
    P.append("def _rotl(x, r):")
    P.append("    r %= 64")
    P.append("    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64")
    P.append("")
    P.append("def _sbox64(x):")
    P.append("    x = np.asarray(x, dtype=np.uint64)")
    P.append("    S = np.asarray(SBOX, dtype=np.uint64)")
    P.append("    y = np.zeros_like(x)")
    P.append("    for i in range(16):")
    P.append("        y |= S[((x >> np.uint64(4*i)) & np.uint64(0xF))] << np.uint64(4*i)")
    P.append("    return y & M64")
    P.append("")
    P.append("def _lin(x):")
    P.append("    return (x ^ _rotl(x, 5) ^ _rotl(x, 13)) & M64")
    P.append("")
    P.append("AND6A = %s" % AND6A)
    P.append("")
    P.append("def _mix_core(x, k):")
    if kind == "sbfirst":
        P.append("    x = _sbox64(x)")
        P.append("    for (a, b, c) in AND6A[:%d]:" % p["n_and"])
        P.append("        ra, rb, rc = _rotl(x, a), _rotl(x, b), _rotl(x, c)")
        P.append("        x = (x ^ (ra & rb) ^ rc) & M64")
    elif kind == "minispn":
        P.append("    for (a, b, c) in AND6A[:%d]:" % p["n_and"])
        P.append("        ra, rb, rc = _rotl(x, a), _rotl(x, b), _rotl(x, c)")
        P.append("        x = (x ^ (ra & rb) ^ rc) & M64")
        P.append("    x = _sbox64(x)")
        P.append("    x = _rotl(x, %d)" % p["rot"])
        P.append("    x = _sbox64(x)")
    elif kind == "rotalign":
        P.append("    for (a, b, c) in AND6A[:%d]:" % p["n_and"])
        P.append("        ra, rb, rc = _rotl(x, a), _rotl(x, b), _rotl(x, c)")
        P.append("        x = (x ^ (ra & rb) ^ rc) & M64")
        P.append("    x = _rotl(x, %d)" % p["rot"])
        P.append("    x = _sbox64(x)")
    P.append("    x = _lin(x)")
    P.append("    return (x ^ _rotl(k, 13)) & M64")
    P.append("")
    P.append("def mix_hash(val, key):")
    P.append("    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))")
    P.append("")
    P.append("def mix_np(V, K):")
    P.append("    V = np.asarray(V, dtype=np.uint64)")
    P.append("    K = np.asarray(K, dtype=np.uint64)")
    P.append("    return _mix_core(V ^ K, K)")
    P.append("")
    P.append("def mix(v, k):")
    P.append("    return mix_hash(v, k)")
    P.append("")
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    # meta.json
    meta = {
        "name": name,
        "description": desc,
        "rtl_top": name,
        "screen_keys": ["0x123456789abcdef0", "0x0"],
        "practrand_keys": ["0x123456789abcdef0", "0x0"],
    }
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1))

    # bit-exact verification: model vs C
    sys.path.insert(0, d)
    import importlib
    mod = importlib.import_module("model")
    importlib.reload(mod)
    # compile C
    import subprocess
    cdir = d
    harness = os.path.join(cdir, "_harness.c")
    open(harness, "w").write(
        '#include <stdio.h>\n#include <stdint.h>\n#include <stdlib.h>\n'
        'uint64_t mix_hash(uint64_t val, uint64_t key);\n'
        'int main(int argc, char**argv) {\n'
        '  uint64_t v = strtoull(argv[1], NULL, 16), k = strtoull(argv[2], NULL, 16);\n'
        '  printf("%016llx\\n", (unsigned long long)mix_hash(v, k));\n'
        '  return 0;\n}\n')
    exe = os.path.join(cdir, "_harness")
    r = subprocess.run(["gcc", "-O2", "-o", exe, harness, os.path.join(cdir, "impl.c")],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"{name}: C BUILD FAIL: {r.stderr[-500:]}")
        return False
    import random
    random.seed(12345)
    ok = True
    for _ in range(200):
        v = random.getrandbits(64)
        k = random.getrandbits(64)
        py = mod.mix_hash(v, k)
        r = subprocess.run([exe, format(v, 'x'), format(k, 'x')],
                           capture_output=True, text=True)
        c = int(r.stdout.strip(), 16)
        if py != c:
            print(f"{name}: MISMATCH v={v:x} k={k:x} py={py:016x} c={c:016x}")
            ok = False
            break
    print(f"{name}: {'bit-exact 200/200' if ok else 'MISMATCH'}")
    return ok


if __name__ == "__main__":
    allok = True
    for (name, kind, p, desc) in SPECS:
        allok &= build(name, kind, p, desc)
    sys.exit(0 if allok else 1)
