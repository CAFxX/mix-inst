#!/usr/bin/env python3
"""Batch-14 hybrid generator (Track 5, 2026-10-10).

Pivot: 3-input AND stages. Batch-13 proved 4-bit S-box hybrids cannot reach
sub-20.1u (strength-per-cost unfavorable). 

Hypothesis: a 3-input AND stage x ^= (ra&rb&rc)^rd provides ~1.5x the
differential strength of a 2-input AND stage (degree 3 vs 2, stronger
differential attenuation). If true, 4x3AND (+ S-box) reaches 6-equivalent
strength under 20.1u.

Candidates:
1. hyb14_3and4_a: 4x3AND (no S-box). Tests if 4 strong stages suffice alone.
   Est: 4 x 3.6u = 14.4u.
2. hyb14_3and4s_a: 4x3AND + SBOX + L(5,13). Hybrid with stronger base.
   Est: 14.4 + 3.5 + 2 = 19.9u (UNDER 20.1u if estimates hold).
3. hyb14_3and5_a: 5x3AND (no S-box). Calibration: measures 3-AND strength.
   Est: 5 x 3.6u = 18u.

3-AND schedule: 4 rotations per stage (a,b,c ANDed; d XORed). Chosen to avoid
track-3 danger zones where possible; this is a first probe, not optimized.

S-box: rasC2_0 (same as batch-12/13).
"""
import json
import os
import sys

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

# 3-input AND schedule: (a,b,c,d) -> x ^= (ra&rb&rc)^rd
AND3_SCHED = [
    (1, 2, 3, 13),
    (7, 19, 5, 29),
    (3, 11, 17, 7),
    (11, 23, 37, 19),
    (19, 41, 23, 31),
]
SBOX = [0, 1, 2, 3, 4, 6, 8, 11, 13, 9, 7, 15, 12, 10, 5, 14]

SPECS = [
    ("hyb14_3and4_a", "and3", dict(n_and=4, use_sbox=False),
     "4x3AND (no S-box): do 4 strong stages suffice alone?"),
    ("hyb14_3and4s_a", "and3", dict(n_and=4, use_sbox=True),
     "4x3AND + SBOX + L(5,13): hybrid with stronger base"),
    ("hyb14_3and5_a", "and3", dict(n_and=5, use_sbox=False),
     "5x3AND (no S-box): calibration of 3-AND strength"),
]


def rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def sbox64(x):
    x = np.asarray(x, dtype=np.uint64)
    S = np.asarray(SBOX, dtype=np.uint64)
    y = np.zeros_like(x)
    for i in range(16):
        y |= S[((x >> np.uint64(4 * i)) & np.uint64(0xF))] << np.uint64(4 * i)
    return y & M64


def lin513(x):
    return (x ^ rotl(x, 5) ^ rotl(x, 13)) & M64


def and3_stages(x, sched):
    for (a, b, c, d) in sched:
        ra, rb, rc, rd = rotl(x, a), rotl(x, b), rotl(x, c), rotl(x, d)
        x = (x ^ (ra & rb & rc) ^ rd) & M64
    return x


def model_hash(val, key, p):
    x = np.uint64(val) ^ np.uint64(key)
    k = np.uint64(key)
    x = and3_stages(x, AND3_SCHED[:p["n_and"]])
    if p["use_sbox"]:
        x = sbox64(x)
        x = lin513(x)
    return int((x ^ rotl(k, 13)) & M64)


def rotl_v(sig, r):
    if r % 64 == 0:
        return sig
    r %= 64
    return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)


def build(name, p, desc):
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)

    # ---- impl.c ----
    L = []
    L.append("// %s: %s (generated by hybrid/codesign/gen_batch14.py)" % (name, desc))
    L.append("#include <stdint.h>")
    L.append("static inline uint64_t rotl64(uint64_t x, int r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    if p["use_sbox"]:
        L.append("static const uint8_t SBOX[16] = {%s};" % ",".join(map(str, SBOX)))
        L.append("static inline uint64_t sbox64(uint64_t x) {")
        L.append("    uint64_t y = 0;")
        L.append("    for (int i = 0; i < 16; i++)")
        L.append("        y |= (uint64_t)SBOX[(x >> (4*i)) & 0xFu] << (4*i);")
        L.append("    return y;")
        L.append("}")
        L.append("static inline uint64_t lin513(uint64_t x) {")
        L.append("    return x ^ rotl64(x, 5) ^ rotl64(x, 13);")
        L.append("}")
    L.append("uint64_t mix_hash(uint64_t val, uint64_t key) {")
    L.append("    uint64_t x = val ^ key;")
    for i, (a, b, c, dd) in enumerate(AND3_SCHED[:p["n_and"]]):
        L.append("    { /* 3-AND stage %d: (%d,%d,%d,%d) */" % (i, a, b, c, dd))
        L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d);" % (a, b))
        L.append("        uint64_t rc = rotl64(x, %d), rd = rotl64(x, %d);" % (c, dd))
        L.append("        x ^= (ra & rb & rc) ^ rd;")
        L.append("    }")
    if p["use_sbox"]:
        L.append("    x = sbox64(x);")
        L.append("    x = lin513(x);")
    L.append("    x ^= rotl64(key, 13);")
    L.append("    return x;")
    L.append("}")
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    # ---- rtl.v ----
    V = []
    V.append("// %s: %s (generated by hybrid/codesign/gen_batch14.py)" % (name, desc))
    V.append("module %s(" % name)
    V.append("    input [63:0] val,")
    V.append("    input [63:0] key,")
    V.append("    output [63:0] out")
    V.append(");")
    if p["use_sbox"]:
        V.append("    function [3:0] sb(input [3:0] z);")
        V.append("        begin")
        V.append("            case (z)")
        for i, o in enumerate(SBOX):
            V.append("                4'h%x: sb = 4'h%x;" % (i, o))
        V.append("                default: sb = 4'h0;")
        V.append("            endcase")
        V.append("        end")
        V.append("    endfunction")
    V.append("    wire [63:0] x0 = val ^ key;")
    cur = "x0"
    idx = 0
    for (a, b, c, dd) in AND3_SCHED[:p["n_and"]]:
        V.append("    wire [63:0] s%da = %s;" % (idx, rotl_v(cur, a)))
        V.append("    wire [63:0] s%db = %s;" % (idx, rotl_v(cur, b)))
        V.append("    wire [63:0] s%dc = %s;" % (idx, rotl_v(cur, c)))
        V.append("    wire [63:0] s%dd = %s;" % (idx, rotl_v(cur, dd)))
        V.append("    wire [63:0] t%d = %s ^ (s%da & s%db & s%dc) ^ s%dd;"
                 % (idx, cur, idx, idx, idx, idx))
        cur = "t%d" % idx
        idx += 1
    if p["use_sbox"]:
        nibs = []
        for i in range(16):
            nibs.append("sb(%s[%d:%d])" % (cur, 4 * i + 3, 4 * i))
        V.append("    wire [63:0] sbx = {%s};" % ", ".join(reversed(nibs)))
        cur = "sbx"
        V.append("    wire [63:0] lf = %s ^ %s ^ %s;" % (cur, rotl_v(cur, 5), rotl_v(cur, 13)))
        cur = "lf"
    V.append("    wire [63:0] kr = {key[50:0], key[63:51]};")
    V.append("    assign out = %s ^ kr;" % cur)
    V.append("endmodule")
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    # ---- model.py ----
    P = []
    P.append('"""%s: %s. Self-contained bit-exact model."""' % (name, desc))
    P.append("import numpy as np")
    P.append("M64 = np.uint64(0xFFFFFFFFFFFFFFFF)")
    if p["use_sbox"]:
        P.append("SBOX = %s" % SBOX)
    P.append("")
    P.append("def _rotl(x, r):")
    P.append("    r %= 64")
    P.append("    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64")
    P.append("")
    if p["use_sbox"]:
        P.append("def _sbox64(x):")
        P.append("    x = np.asarray(x, dtype=np.uint64)")
        P.append("    S = np.asarray(SBOX, dtype=np.uint64)")
        P.append("    y = np.zeros_like(x)")
        P.append("    for i in range(16):")
        P.append("        y |= S[((x >> np.uint64(4*i)) & np.uint64(0xF))] << np.uint64(4*i)")
        P.append("    return y & M64")
        P.append("")
        P.append("def _lin(x):")
        P.append("    return (x ^ _rotl(x, 5) ^ _rotl(x, 13)) & M64")
        P.append("")
    P.append("AND3_SCHED = %s" % (AND3_SCHED,))
    P.append("")
    P.append("def _mix_core(x, k):")
    P.append("    for (a, b, c, d) in AND3_SCHED[:%d]:" % p["n_and"])
    P.append("        ra, rb, rc, rd = _rotl(x, a), _rotl(x, b), _rotl(x, c), _rotl(x, d)")
    P.append("        x = (x ^ (ra & rb & rc) ^ rd) & M64")
    if p["use_sbox"]:
        P.append("    x = _sbox64(x)")
        P.append("    x = _lin(x)")
    P.append("    return (x ^ _rotl(k, 13)) & M64")
    P.append("")
    P.append("def mix_hash(val, key):")
    P.append("    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))")
    P.append("")
    P.append("def mix_np(V, K):")
    P.append("    V = np.asarray(V, dtype=np.uint64)")
    P.append("    K = np.asarray(K, dtype=np.uint64)")
    P.append("    return _mix_core(V ^ K, K)")
    P.append("")
    P.append("def mix(v, k):")
    P.append("    return mix_hash(v, k)")
    P.append("")
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    # meta.json
    meta = {
        "name": name,
        "description": desc,
        "rtl_top": name,
        "screen_keys": ["0x123456789abcdef0", "0x0"],
        "practrand_keys": ["0x123456789abcdef0", "0x0"],
    }
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1))

    # bit-exact verification
    sys.path.insert(0, d)
    import importlib
    mod = importlib.import_module("model")
    importlib.reload(mod)
    import subprocess
    harness = os.path.join(d, "_harness.c")
    open(harness, "w").write(
        '#include <stdio.h>\n#include <stdint.h>\n#include <stdlib.h>\n'
        'uint64_t mix_hash(uint64_t val, uint64_t key);\n'
        'int main(int argc, char**argv) {\n'
        '  uint64_t v = strtoull(argv[1], NULL, 16), k = strtoull(argv[2], NULL, 16);\n'
        '  printf("%016llx\\n", (unsigned long long)mix_hash(v, k));\n'
        '  return 0;\n}\n')
    exe = os.path.join(d, "_harness")
    r = subprocess.run(["gcc", "-O2", "-o", exe, harness, os.path.join(d, "impl.c")],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"{name}: C BUILD FAIL: {r.stderr[-500:]}")
        return False
    import random
    random.seed(12345)
    ok = True
    for _ in range(200):
        v = random.getrandbits(64)
        k = random.getrandbits(64)
        py = mod.mix_hash(v, k)
        r = subprocess.run([exe, format(v, 'x'), format(k, 'x')],
                           capture_output=True, text=True)
        c = int(r.stdout.strip(), 16)
        if py != c:
            print(f"{name}: MISMATCH v={v:x} k={k:x} py={py:016x} c={c:016x}")
            ok = False
            break
    print(f"{name}: {'bit-exact 200/200' if ok else 'MISMATCH'}")
    return ok


if __name__ == "__main__":
    allok = True
    for (name, kind, p, desc) in SPECS:
        allok &= build(name, p, desc)
    sys.exit(0 if allok else 1)
