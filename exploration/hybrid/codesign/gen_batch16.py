#!/usr/bin/env python3
"""Batch-16 hybrid generator (Track 5, 2026-10-10).

5-stage 3-AND with co-designed schedules. Batch-15 proved 4x3-AND is
systematically broken (catastrophic repeats). 5x3AND (hyb14_3and5_a) passes
repeats but has |z| bias with the flawed schedule. This batch tests whether
co-designed schedules fix the |z| bias in 5-stage.

Design principles (same as batch-15):
1. Danger-zone-free: no rotations in [28,36], none >= 54
2. Within-triple spread: min pairwise diff >= 7
3. XOR d: large and incommensurate
4. Across-stage: different triple shapes

Candidates (all 5x3AND):
1. hyb16_3and5_A: Schedule A extended to 5 stages
2. hyb16_3and5_B: Schedule B extended to 5 stages
"""
import json
import os
import sys

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

SCHEDULES = {
    "A": [
        (5, 19, 41, 13),
        (7, 23, 47, 17),
        (3, 17, 43, 11),
        (13, 27, 51, 7),
        (9, 21, 45, 19),
    ],
    "B": [
        (3, 13, 37, 19),
        (9, 21, 45, 5),
        (7, 17, 41, 23),
        (5, 19, 43, 11),
        (11, 25, 49, 17),
    ],
}

SPECS = [
    ("hyb16_3and5_A", "A", "5x3AND schedule A: co-designed, 5 stages"),
    ("hyb16_3and5_B", "B", "5x3AND schedule B: co-designed, 5 stages"),
]


def build(name, sched_key, desc):
    sched = SCHEDULES[sched_key]
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)

    # ---- impl.c ----
    L = []
    L.append("// %s: %s (generated by hybrid/codesign/gen_batch16.py)" % (name, desc))
    L.append("#include <stdint.h>")
    L.append("static inline uint64_t rotl64(uint64_t x, int r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    L.append("uint64_t mix_hash(uint64_t val, uint64_t key) {")
    L.append("    uint64_t x = val ^ key;")
    for i, (a, b, c, dd) in enumerate(sched):
        L.append("    { /* 3-AND stage %d: (%d,%d,%d,%d) */" % (i, a, b, c, dd))
        L.append("        uint64_t ra = rotl64(x, %d), rb = rotl64(x, %d);" % (a, b))
        L.append("        uint64_t rc = rotl64(x, %d), rd = rotl64(x, %d);" % (c, dd))
        L.append("        x ^= (ra & rb & rc) ^ rd;")
        L.append("    }")
    L.append("    x ^= rotl64(key, 13);")
    L.append("    return x;")
    L.append("}")
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    # ---- rtl.v ----
    V = []
    V.append("// %s: %s (generated by hybrid/codesign/gen_batch16.py)" % (name, desc))
    V.append("module %s(" % name)
    V.append("    input [63:0] val,")
    V.append("    input [63:0] key,")
    V.append("    output [63:0] out")
    V.append(");")
    def rotl_v(sig, r):
        if r % 64 == 0:
            return sig
        r %= 64
        return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)
    V.append("    wire [63:0] x0 = val ^ key;")
    cur = "x0"
    idx = 0
    for (a, b, c, dd) in sched:
        V.append("    wire [63:0] s%da = %s;" % (idx, rotl_v(cur, a)))
        V.append("    wire [63:0] s%db = %s;" % (idx, rotl_v(cur, b)))
        V.append("    wire [63:0] s%dc = %s;" % (idx, rotl_v(cur, c)))
        V.append("    wire [63:0] s%dd = %s;" % (idx, rotl_v(cur, dd)))
        V.append("    wire [63:0] t%d = %s ^ (s%da & s%db & s%dc) ^ s%dd;"
                 % (idx, cur, idx, idx, idx, idx))
        cur = "t%d" % idx
        idx += 1
    V.append("    wire [63:0] kr = {key[50:0], key[63:51]};")
    V.append("    assign out = %s ^ kr;" % cur)
    V.append("endmodule")
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    # ---- model.py ----
    P = []
    P.append('"""%s: %s. Self-contained bit-exact model."""' % (name, desc))
    P.append("import numpy as np")
    P.append("M64 = np.uint64(0xFFFFFFFFFFFFFFFF)")
    P.append("")
    P.append("def _rotl(x, r):")
    P.append("    r %= 64")
    P.append("    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64")
    P.append("")
    P.append("SCHED = %s" % (sched,))
    P.append("")
    P.append("def _mix_core(x, k):")
    P.append("    for (a, b, c, d) in SCHED:")
    P.append("        ra, rb, rc, rd = _rotl(x, a), _rotl(x, b), _rotl(x, c), _rotl(x, d)")
    P.append("        x = (x ^ (ra & rb & rc) ^ rd) & M64")
    P.append("    return (x ^ _rotl(k, 13)) & M64")
    P.append("")
    P.append("def mix_hash(val, key):")
    P.append("    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))")
    P.append("")
    P.append("def mix_np(V, K):")
    P.append("    V = np.asarray(V, dtype=np.uint64)")
    P.append("    K = np.asarray(K, dtype=np.uint64)")
    P.append("    return _mix_core(V ^ K, K)")
    P.append("")
    P.append("def mix(v, k):")
    P.append("    return mix_hash(v, k)")
    P.append("")
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    # meta.json
    meta = {
        "name": name,
        "description": desc,
        "rtl_top": name,
        "screen_keys": ["0x123456789abcdef0", "0x0"],
        "practrand_keys": ["0x123456789abcdef0", "0x0"],
    }
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1))

    # bit-exact verification
    sys.path.insert(0, d)
    import importlib
    mod = importlib.import_module("model")
    importlib.reload(mod)
    import subprocess
    harness = os.path.join(d, "_harness.c")
    open(harness, "w").write(
        '#include <stdio.h>\n#include <stdint.h>\n#include <stdlib.h>\n'
        'uint64_t mix_hash(uint64_t val, uint64_t key);\n'
        'int main(int argc, char**argv) {\n'
        '  uint64_t v = strtoull(argv[1], NULL, 16), k = strtoull(argv[2], NULL, 16);\n'
        '  printf("%016llx\\n", (unsigned long long)mix_hash(v, k));\n'
        '  return 0;\n}\n')
    exe = os.path.join(d, "_harness")
    r = subprocess.run(["gcc", "-O2", "-o", exe, harness, os.path.join(d, "impl.c")],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"{name}: C BUILD FAIL: {r.stderr[-500:]}")
        return False
    import random
    random.seed(12345)
    ok = True
    for _ in range(200):
        v = random.getrandbits(64)
        k = random.getrandbits(64)
        py = mod.mix_hash(v, k)
        r = subprocess.run([exe, format(v, 'x'), format(k, 'x')],
                           capture_output=True, text=True)
        c = int(r.stdout.strip(), 16)
        if py != c:
            print(f"{name}: MISMATCH v={v:x} k={k:x} py={py:016x} c={c:016x}")
            ok = False
            break
    print(f"{name}: {'bit-exact 200/200' if ok else 'MISMATCH'}")
    return ok


if __name__ == "__main__":
    allok = True
    for (name, sched_key, desc) in SPECS:
        allok &= build(name, sched_key, desc)
    sys.exit(0 if allok else 1)
