#!/usr/bin/env python3
"""Batch-5 hybrid generator: P-box-augmented chi/AND cascades (co-design).

Co-design principle: the P-box is chosen BY chi_pbox_diffuse.py FOR the
cascade rotation schedule -- NOT blindly reused from the S-box SPN.
Metric top tier: a=43, 27, 11. pba19 (a=19) is a negative control
(metric says it HURTS AND-cascade diffusion: score 18 vs 29 baseline).

Structure per candidate:
  x = v ^ k
  for each stage i: x = P( chi_or_and_stage(x) )   [P between stages, not after last]
  o = x ^ rotl(k, 13)

Generates impl.c, rtl.v, model.py (self-contained, bit-exact), meta.json.
Golden vectors computed by running the Python model.
"""
import json
import os
import sys

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

# Base schedules (from gen_wave1.py / al_cascad impl.c)
CHI8 = [(1, 2, 13), (7, 19, 5), (3, 11, 29), (13, 5, 17),
        (17, 31, 7), (11, 23, 37), (29, 43, 11), (19, 41, 23)]
CASC8 = [(1, 8, 2), (3, 11, 5), (7, 19, 13), (2, 9, 4),
         (5, 17, 11), (13, 29, 7), (11, 23, 17), (19, 37, 23)]

SPECS = [
    # (name, op, schedule, pbox_a, pbox_b, desc)
    ("hyb5_chi8_p43", "chi", CHI8, 43, 1,
     "8-stage chi + P(43,1) between stages (metric top tier)"),
    ("hyb5_chi8_p27", "chi", CHI8, 27, 1,
     "8-stage chi + P(27,1) between stages (metric top tier)"),
    ("hyb5_chi8_p19", "chi", CHI8, 19, 1,
     "8-stage chi + P(19,1) NEGATIVE CONTROL (metric: hurts diffusion)"),
    ("hyb5_casc8_p43", "and", CASC8, 43, 1,
     "8-stage AND-cascade + P(43,1) between stages (metric top tier)"),
    ("hyb5_chi6_p43", "chi", CHI8[:6], 43, 1,
     "6-stage chi + P(43,1) (reduced stages, P-box compensates)"),
    ("hyb5_casc6_p43", "and", CASC8[:6], 43, 1,
     "6-stage AND-cascade + P(43,1) (reduced stages, P-box compensates)"),
]

KEYS = ["0x123456789abcdef0", "0x0"]


def rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def pbox_apply(x, a, b):
    """P(i) = (a*i + b) % 64: y[P(i)] = x[i]."""
    y = np.uint64(0)
    for i in range(64):
        if (x >> np.uint64(i)) & np.uint64(1):
            y |= np.uint64(1) << np.uint64((a * i + b) % 64)
    return y & M64


def model_hash(val, key, op, sched, pa, pb):
    x = np.uint64(val) ^ np.uint64(key)
    k = np.uint64(key)
    n = len(sched)
    for i, (a, b, c) in enumerate(sched):
        ra, rb, rc = rotl(x, a), rotl(x, b), rotl(x, c)
        if op == "chi":
            x = (x ^ ((~ra) & rb) ^ rc) & M64
        else:
            x = (x ^ (ra & rb) ^ rc) & M64
        if i < n - 1:
            x = pbox_apply(x, pa, pb)
    x = (x ^ rotl(k, 13)) & M64
    return int(x)


def rotl_v(sig, r):
    """Verilog rotl wire expression."""
    if r % 64 == 0:
        return sig
    r %= 64
    return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)


def pbox_v_correct(sig, a, b, out):
    ainv = pow(a, -1, 64)
    # out[j] = sig[P^{-1}(j)]; in Verilog concat {x63, x62, ..., x0}, first element is bit 63.
    terms = []
    for j in range(63, -1, -1):
        i = (ainv * (j - b)) % 64
        terms.append(f"{sig}[{i}]")
    return f"wire [63:0] {out} = {{{', '.join(terms)}}};"


def build(name, op, sched, pa, pb, desc):
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)
    n = len(sched)

    # ---- impl.c ----
    L = []
    L.append(f"// {name}: {desc} (generated by hybrid/codesign/gen_batch5.py)")
    L.append("#include <stdint.h>")
    L.append("static inline uint64_t rotl64(uint64_t x, int r) {")
    L.append("    r &= 63;")
    L.append("    return r ? (x << r) | (x >> (64 - r)) : x;")
    L.append("}")
    L.append(f"static inline uint64_t pbox64(uint64_t x) {{ /* P(i)=( {pa}*i+{pb})%64 */")
    L.append("    uint64_t y = 0;")
    for i in range(64):
        j = (pa * i + pb) % 64
        L.append(f"    y |= ((x >> {i}) & 1ULL) << {j};")
    L.append("    return y;")
    L.append("}")
    L.append("uint64_t mix_hash(uint64_t val, uint64_t key) {")
    L.append("    uint64_t x = val ^ key;")
    for i, (a, b, c) in enumerate(sched):
        L.append(f"    {{ /* stage {i}: ({a},{b},{c}) */")
        L.append(f"        uint64_t ra = rotl64(x, {a}), rb = rotl64(x, {b}), rc = rotl64(x, {c});")
        if op == "chi":
            L.append("        x ^= ((~ra) & rb) ^ rc;")
        else:
            L.append("        x ^= (ra & rb) ^ rc;")
        L.append("    }")
        if i < n - 1:
            L.append("    x = pbox64(x);")
    L.append("    x ^= rotl64(key, 13);")
    L.append("    return x;")
    L.append("}")
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    # ---- rtl.v ----
    V = []
    V.append(f"// {name}: {desc} (generated by hybrid/codesign/gen_batch5.py)")
    V.append(f"module {name}(")
    V.append("    input [63:0] val,")
    V.append("    input [63:0] key,")
    V.append("    output [63:0] out")
    V.append(");")
    V.append("    wire [63:0] x0 = val ^ key;")
    cur = "x0"
    for i, (a, b, c) in enumerate(sched):
        V.append(f"    wire [63:0] s{i}a = {rotl_v(cur, a)};")
        V.append(f"    wire [63:0] s{i}b = {rotl_v(cur, b)};")
        V.append(f"    wire [63:0] s{i}c = {rotl_v(cur, c)};")
        if op == "chi":
            V.append(f"    wire [63:0] t{i} = {cur} ^ ((~s{i}a) & s{i}b) ^ s{i}c;")
        else:
            V.append(f"    wire [63:0] t{i} = {cur} ^ (s{i}a & s{i}b) ^ s{i}c;")
        if i < n - 1:
            V.append(f"    {pbox_v_correct(f't{i}', pa, pb, f'x{i+1}')}")
            cur = f"x{i+1}"
        else:
            cur = f"t{i}"
    V.append("    wire [63:0] kr = {key[50:0], key[63:51]};")
    V.append(f"    assign out = {cur} ^ kr;")
    V.append("endmodule")
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    # ---- model.py (self-contained) ----
    P = []
    P.append(f'"""{name}: {desc}. Self-contained bit-exact model."""')
    P.append("import numpy as np")
    P.append("M64 = np.uint64(0xFFFFFFFFFFFFFFFF)")
    P.append("")
    P.append("def _rotl(x, r):")
    P.append("    r %= 64")
    P.append("    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64")
    P.append("")
    P.append(f"def _pbox(x):  # P(i)=({pa}*i+{pb})%64")
    P.append("    y = np.uint64(0)")
    for i in range(64):
        j = (pa * i + pb) % 64
        P.append(f"    y |= ((x >> np.uint64({i})) & np.uint64(1)) << np.uint64({j})")
    P.append("    return y & M64")
    P.append("")
    P.append("def _mix_core(x, k):")
    for i, (a, b, c) in enumerate(sched):
        P.append(f"    ra, rb, rc = _rotl(x, {a}), _rotl(x, {b}), _rotl(x, {c})")
        if op == "chi":
            P.append("    x = (x ^ ((~ra) & rb) ^ rc) & M64")
        else:
            P.append("    x = (x ^ (ra & rb) ^ rc) & M64")
        if i < n - 1:
            P.append("    x = _pbox(x)")
    P.append("    return (x ^ _rotl(k, 13)) & M64")
    P.append("")
    P.append("def mix_hash(val, key):")
    P.append("    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))")
    P.append("")
    P.append("def mix_np(V, K):")
    P.append("    V = np.asarray(V, dtype=np.uint64)")
    P.append("    K = np.asarray(K, dtype=np.uint64)")
    P.append("    return _mix_core(V ^ K, K)")
    P.append("")
    P.append('if __name__ == "__main__":')
    P.append("    import sys")
    P.append('    print(hex(mix_hash(int(sys.argv[1], 0), int(sys.argv[2], 0))))')
    P.append("")
    P.append("# s0_delay.py expects m.mix; s1_screen.py expects m.mix_np")
    P.append("def mix(v, k):")
    P.append("    return mix_hash(v, k)")
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    # ---- meta.json with goldens ----
    goldens = []
    for vk, kk in [("0x0", KEYS[0]), (KEYS[0], "0x0")]:
        out = model_hash(int(vk, 16), int(kk, 16), op, sched, pa, pb)
        goldens.append({"val": vk, "key": kk, "out": hex(out)})
    meta = {
        "name": name,
        "description": desc,
        "screen_keys": KEYS,
        "practrand_keys": KEYS,
        "goldens": goldens,
    }
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1) + "\n")
    print(f"generated {name}: goldens {goldens[0]['out']}, {goldens[1]['out']}")


if __name__ == "__main__":
    for spec in SPECS:
        build(*spec)
    print("batch-5 generation complete")
