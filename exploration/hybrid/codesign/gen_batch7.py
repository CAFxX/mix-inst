#!/usr/bin/env python3
"""Batch-7 hybrid generator: 3-input AND cascade.

Lesson from batch-6: inter-stage P-box HURTS al_and6a triplets. The triplets
are a delicate sequence co-design. Don't add linear layers between stages.

New direction: STRONGER per-stage nonlinearity so fewer stages suffice.
3-input AND: x ^= (ra & rb & rc) ^ rd
- Algebraic degree 3 (vs 2 for 2-input AND) -> faster diffusion
- AND3 is 1 gate delay (same as AND2 in unit-delay model)
- 5 stages x ~3.35u = ~16.75u target

Rotation quads (a,b,c,d): derived from al_and6a triplets + 4th rotation
chosen for spread. Stage i uses al_and6a triplet i plus d_i.

Candidates:
- hyb7_and3_5: 5-stage 3-input AND
- hyb7_and3_6: 6-stage 3-input AND (control: is 3-input better at same stage count?)

Generates impl.c, rtl.v, model.py (bit-exact), meta.json (with rtl_top).
"""
import json
import os

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

# al_and6a triplets + 4th rotation for 3-input AND
# d chosen to maximize min distance from {a,b,c} (spread heuristic)
QUADS5 = [
    (1, 2, 13, 41),    # stage 0
    (7, 19, 5, 37),    # stage 1
    (3, 11, 29, 47),   # stage 2
    (17, 31, 7, 43),   # stage 3
    (11, 23, 37, 5),   # stage 4
]
QUADS6 = QUADS5 + [(19, 41, 23, 13)]  # stage 5

SPECS = [
    ("hyb7_and3_5", QUADS5,
     "5-stage 3-input AND cascade: x ^= (ra&rb&rc)^rd"),
    ("hyb7_and3_6", QUADS6,
     "6-stage 3-input AND cascade: x ^= (ra&rb&rc)^rd (control)"),
]

KEYS = ["0x123456789abcdef0", "0x0"]


def rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def model_hash(val, key, quads):
    x = np.uint64(val) ^ np.uint64(key)
    k = np.uint64(key)
    for (a, b, c, d) in quads:
        ra, rb, rc, rd = rotl(x, a), rotl(x, b), rotl(x, c), rotl(x, d)
        x = (x ^ (ra & rb & rc) ^ rd) & M64
    x = (x ^ rotl(k, 13)) & M64
    return int(x)


def rotl_v(sig, r):
    if r % 64 == 0:
        return sig
    r %= 64
    return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)


def build(name, quads, desc):
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)
    n = len(quads)

    # ---- impl.c ----
    L = [f"// {name}: {desc} (generated by hybrid/codesign/gen_batch7.py)",
         "#include <stdint.h>",
         "static inline uint64_t rotl64(uint64_t x, int r) {",
         "    r &= 63;",
         "    return r ? (x << r) | (x >> (64 - r)) : x;",
         "}",
         "uint64_t mix_hash(uint64_t val, uint64_t key) {",
         "    uint64_t x = val ^ key;"]
    for i, (a, b, c, dd) in enumerate(quads):
        L.append(f"    {{ /* stage {i}: ({a},{b},{c},{dd}) */")
        L.append(f"        uint64_t ra = rotl64(x, {a}), rb = rotl64(x, {b});")
        L.append(f"        uint64_t rc = rotl64(x, {c}), rd = rotl64(x, {dd});")
        L.append("        x ^= (ra & rb & rc) ^ rd;")
        L.append("    }")
    L += ["    x ^= rotl64(key, 13);",
          "    return x;",
          "}"]
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    # ---- rtl.v ----
    V = [f"// {name}: {desc} (generated by hybrid/codesign/gen_batch7.py)",
         f"module {name}(",
         "    input [63:0] val,",
         "    input [63:0] key,",
         "    output [63:0] out",
         ");",
         "    wire [63:0] x0 = val ^ key;"]
    cur = "x0"
    for i, (a, b, c, dd) in enumerate(quads):
        V.append(f"    wire [63:0] s{i}a = {rotl_v(cur, a)};")
        V.append(f"    wire [63:0] s{i}b = {rotl_v(cur, b)};")
        V.append(f"    wire [63:0] s{i}c = {rotl_v(cur, c)};")
        V.append(f"    wire [63:0] s{i}d = {rotl_v(cur, dd)};")
        V.append(f"    wire [63:0] t{i} = {cur} ^ (s{i}a & s{i}b & s{i}c) ^ s{i}d;")
        cur = f"t{i}"
    V += ["    wire [63:0] kr = {key[50:0], key[63:51]};",
          f"    assign out = {cur} ^ kr;",
          "endmodule"]
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    # ---- model.py ----
    P = [f'"""{name}: {desc}. Self-contained bit-exact model."""',
         "import numpy as np",
         "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)",
         "",
         "def _rotl(x, r):",
         "    r %= 64",
         "    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
         "",
         "def _mix_core(x, k):"]
    for (a, b, c, dd) in quads:
        P.append(f"    ra, rb, rc, rd = _rotl(x, {a}), _rotl(x, {b}), _rotl(x, {c}), _rotl(x, {dd})")
        P.append("    x = (x ^ (ra & rb & rc) ^ rd) & M64")
    P += ["    return (x ^ _rotl(k, 13)) & M64",
          "",
          "def mix_hash(val, key):",
          "    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))",
          "",
          "def mix_np(V, K):",
          "    V = np.asarray(V, dtype=np.uint64)",
          "    K = np.asarray(K, dtype=np.uint64)",
          "    return _mix_core(V ^ K, K)",
          "",
          "def mix(v, k):",
          "    return mix_hash(v, k)"]
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    # ---- meta.json ----
    goldens = []
    for vk, kk in [("0x0", KEYS[0]), (KEYS[0], "0x0")]:
        out = model_hash(int(vk, 16), int(kk, 16), quads)
        goldens.append({"val": vk, "key": kk, "out": hex(out)})
    meta = {"name": name, "description": desc, "screen_keys": KEYS,
            "practrand_keys": KEYS, "goldens": goldens, "rtl_top": name}
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1) + "\n")
    print(f"generated {name}: goldens {goldens[0]['out']}, {goldens[1]['out']}")


if __name__ == "__main__":
    for spec in SPECS:
        build(*spec)
    print("batch-7 generation complete")
