#!/usr/bin/env python3
"""Batch-8 hybrid generator: split AND cascade with mid-P-box.

Lesson from batch-6: P-box between EVERY stage hurts al_and6a triplets.
Lesson from batch-7: 5 stages insufficient; 6-stage depth necessary.

New idea: 6 stages, but P-box ONLY at the midpoint (between stage 3 and 4).
- Stages 1-3: al_and6a triplets, no inter-stage P-box (preserves co-design)
- P-box (37,1)  [metric top for al_and6a schedule]
- Stages 4-6: al_and6a triplets, no inter-stage P-box

This tests whether a SINGLE permutation at the block boundary helps without
disrupting the intra-block triplet sequence.

Candidate:
- hyb8_midp37: 6-stage al_and6a triplets, P(37,1) between stage 3 and 4
"""
import json
import os

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

# al_and6a exact triplets
TRIPLETS = [(1, 2, 13), (7, 19, 5), (3, 11, 29),
            (17, 31, 7), (11, 23, 37), (19, 41, 23)]
PA, PB = 37, 1  # metric top pick

KEYS = ["0x123456789abcdef0", "0x0"]


def rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def pbox_apply(x, a, b):
    y = np.uint64(0)
    for i in range(64):
        if (x >> np.uint64(i)) & np.uint64(1):
            y |= np.uint64(1) << np.uint64((a * i + b) % 64)
    return y & M64


def model_hash(val, key):
    x = np.uint64(val) ^ np.uint64(key)
    k = np.uint64(key)
    for i, (a, b, c) in enumerate(TRIPLETS):
        ra, rb, rc = rotl(x, a), rotl(x, b), rotl(x, c)
        x = (x ^ (ra & rb) ^ rc) & M64
        if i == 2:  # P-box ONLY after stage 3 (midpoint)
            x = pbox_apply(x, PA, PB)
    x = (x ^ rotl(k, 13)) & M64
    return int(x)


def rotl_v(sig, r):
    if r % 64 == 0:
        return sig
    r %= 64
    return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)


def pbox_v(sig, a, b, out):
    ainv = pow(a, -1, 64)
    terms = []
    for j in range(63, -1, -1):
        i = (ainv * (j - b)) % 64
        terms.append(f"{sig}[{i}]")
    return f"wire [63:0] {out} = {{{', '.join(terms)}}};"


def build():
    name = "hyb8_midp37"
    desc = "6-stage al_and6a triplets, P(37,1) ONLY between stage 3 and 4 (midpoint)"
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)

    # impl.c
    L = [f"// {name}: {desc} (generated by hybrid/codesign/gen_batch8.py)",
         "#include <stdint.h>",
         "static inline uint64_t rotl64(uint64_t x, int r) {",
         "    r &= 63; return r ? (x << r) | (x >> (64 - r)) : x; }",
         f"static inline uint64_t pbox64(uint64_t x) {{",
         "    uint64_t y = 0;"]
    for i in range(64):
        j = (PA * i + PB) % 64
        L.append(f"    y |= ((x >> {i}) & 1ULL) << {j};")
    L += ["    return y;", "}",
          "uint64_t mix_hash(uint64_t val, uint64_t key) {",
          "    uint64_t x = val ^ key;"]
    for i, (a, b, c) in enumerate(TRIPLETS):
        L.append(f"    {{ uint64_t ra = rotl64(x,{a}), rb = rotl64(x,{b}), rc = rotl64(x,{c});")
        L.append("      x ^= (ra & rb) ^ rc; }")
        if i == 2:
            L.append("    x = pbox64(x);  /* midpoint P-box */")
    L += ["    x ^= rotl64(key, 13);", "    return x;", "}"]
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    # rtl.v
    V = [f"// {name}: {desc}",
         f"module {name}(",
         "    input [63:0] val,", "    input [63:0] key,",
         "    output [63:0] out", ");",
         "    wire [63:0] x0 = val ^ key;"]
    cur = "x0"
    for i, (a, b, c) in enumerate(TRIPLETS):
        V.append(f"    wire [63:0] s{i}a = {rotl_v(cur, a)};")
        V.append(f"    wire [63:0] s{i}b = {rotl_v(cur, b)};")
        V.append(f"    wire [63:0] s{i}c = {rotl_v(cur, c)};")
        V.append(f"    wire [63:0] t{i} = {cur} ^ (s{i}a & s{i}b) ^ s{i}c;")
        if i == 2:
            V.append(f"    {pbox_v(f't{i}', PA, PB, f'x{i+1}')}")
            cur = f"x{i+1}"
        else:
            cur = f"t{i}" if i < 5 else f"t{i}"
            if i < 5 and i != 2:
                # Need wire for next stage input
                V.append(f"    wire [63:0] x{i+1} = t{i};")
                cur = f"x{i+1}"
    # Fix: after loop, cur should be t5
    V += ["    wire [63:0] kr = {key[50:0], key[63:51]};",
          f"    assign out = t5 ^ kr;",
          "endmodule"]
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    # model.py
    P = [f'"""{name}: {desc}."""',
         "import numpy as np", "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)", "",
         "def _rotl(x, r):",
         "    r %= 64",
         "    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
         "",
         f"def _pbox(x):",
         "    y = np.uint64(0)"]
    for i in range(64):
        j = (PA * i + PB) % 64
        P.append(f"    y |= ((x >> np.uint64({i})) & np.uint64(1)) << np.uint64({j})")
    P += ["    return y & M64", "",
          "def _mix_core(x, k):"]
    for i, (a, b, c) in enumerate(TRIPLETS):
        P.append(f"    ra, rb, rc = _rotl(x, {a}), _rotl(x, {b}), _rotl(x, {c})")
        P.append("    x = (x ^ (ra & rb) ^ rc) & M64")
        if i == 2:
            P.append("    x = _pbox(x)")
    P += ["    return (x ^ _rotl(k, 13)) & M64", "",
          "def mix_hash(val, key):",
          "    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))",
          "",
          "def mix_np(V, K):",
          "    V = np.asarray(V, dtype=np.uint64)",
          "    K = np.asarray(K, dtype=np.uint64)",
          "    return _mix_core(V ^ K, K)",
          "",
          "def mix(v, k):", "    return mix_hash(v, k)"]
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    # meta.json
    goldens = []
    for vk, kk in [("0x0", KEYS[0]), (KEYS[0], "0x0")]:
        out = model_hash(int(vk, 16), int(kk, 16))
        goldens.append({"val": vk, "key": kk, "out": hex(out)})
    meta = {"name": name, "description": desc, "screen_keys": KEYS,
            "practrand_keys": KEYS, "goldens": goldens, "rtl_top": name}
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1) + "\n")
    print(f"generated {name}: goldens {goldens[0]['out']}, {goldens[1]['out']}")


if __name__ == "__main__":
    build()
    print("batch-8 generation complete")
