#!/usr/bin/env python3
"""Batch-9 hybrid generator: MAJ3 cascade.

P-box direction exhausted (batch-6, batch-8). 3-input AND needs 6 stages (batch-7).
New nonlinear op: MAJ3.
  x ^= maj(ra,rb,rc) ^ rd,  maj(a,b,c) = (a&b)|(b&c)|(a&c)
- Same algebraic degree as AND (2) but different function
- MAJ is balanced and has good diffusion properties

Candidates:
- hyb9_maj3_6: 6-stage MAJ3 (al_and6a quads)
"""
import json
import os

import numpy as np

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
OUT = "/home/hatch/workspace/mix/exploration/fast_battery/candidates"

QUADS6 = [
    (1, 2, 13, 41),
    (7, 19, 5, 37),
    (3, 11, 29, 47),
    (17, 31, 7, 43),
    (11, 23, 37, 5),
    (19, 41, 23, 13),
]

KEYS = ["0x123456789abcdef0", "0x0"]
NAME = "hyb9_maj3_6"
DESC = "6-stage MAJ3 cascade: x ^= maj(ra,rb,rc)^rd"


def rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def maj3(a, b, c):
    return (a & b) | (b & c) | (a & c)


def model_hash(val, key):
    x = np.uint64(val) ^ np.uint64(key)
    k = np.uint64(key)
    for (a, b, c, d) in QUADS6:
        ra, rb, rc, rd = rotl(x, a), rotl(x, b), rotl(x, c), rotl(x, d)
        x = (x ^ maj3(ra, rb, rc) ^ rd) & M64
    x = (x ^ rotl(k, 13)) & M64
    return int(x)


def rotl_v(sig, r):
    if r % 64 == 0:
        return sig
    r %= 64
    return "{%s[%d:0], %s[63:%d]}" % (sig, 64 - 1 - r, sig, 64 - r)


def build():
    d = os.path.join(OUT, NAME)
    os.makedirs(d, exist_ok=True)

    L = [f"// {NAME}: {DESC} (generated by hybrid/codesign/gen_batch9.py)",
         "#include <stdint.h>",
         "static inline uint64_t rotl64(uint64_t x, int r) {",
         "    r &= 63; return r ? (x << r) | (x >> (64 - r)) : x; }",
         "uint64_t mix_hash(uint64_t val, uint64_t key) {",
         "    uint64_t x = val ^ key;"]
    for i, (a, b, c, dd) in enumerate(QUADS6):
        L.append(f"    {{ uint64_t ra=rotl64(x,{a}),rb=rotl64(x,{b}),rc=rotl64(x,{c}),rd=rotl64(x,{dd});")
        L.append("      uint64_t m=(ra&rb)|(rb&rc)|(ra&rc); x ^= m ^ rd; }")
    L += ["    x ^= rotl64(key, 13);", "    return x;", "}"]
    open(os.path.join(d, "impl.c"), "w").write("\n".join(L) + "\n")

    V = [f"// {NAME}: {DESC}",
         f"module {NAME}(",
         "    input [63:0] val,", "    input [63:0] key,",
         "    output [63:0] out", ");",
         "    wire [63:0] x0 = val ^ key;"]
    cur = "x0"
    for i, (a, b, c, dd) in enumerate(QUADS6):
        V.append(f"    wire [63:0] s{i}a = {rotl_v(cur, a)};")
        V.append(f"    wire [63:0] s{i}b = {rotl_v(cur, b)};")
        V.append(f"    wire [63:0] s{i}c = {rotl_v(cur, c)};")
        V.append(f"    wire [63:0] s{i}d = {rotl_v(cur, dd)};")
        V.append(f"    wire [63:0] m{i} = (s{i}a & s{i}b) | (s{i}b & s{i}c) | (s{i}a & s{i}c);")
        V.append(f"    wire [63:0] t{i} = {cur} ^ m{i} ^ s{i}d;")
        cur = f"t{i}"
    V += ["    wire [63:0] kr = {key[50:0], key[63:51]};",
          f"    assign out = {cur} ^ kr;",
          "endmodule"]
    open(os.path.join(d, "rtl.v"), "w").write("\n".join(V) + "\n")

    P = [f'"""{NAME}: {DESC}."""',
         "import numpy as np", "M64 = np.uint64(0xFFFFFFFFFFFFFFFF)", "",
         "def _rotl(x, r):",
         "    r %= 64",
         "    return x if r == 0 else ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64",
         "",
         "def _maj(a,b,c): return (a & b) | (b & c) | (a & c)",
         "",
         "def _mix_core(x, k):"]
    for (a, b, c, dd) in QUADS6:
        P.append(f"    ra,rb,rc,rd = _rotl(x,{a}),_rotl(x,{b}),_rotl(x,{c}),_rotl(x,{dd})")
        P.append("    x = (x ^ _maj(ra,rb,rc) ^ rd) & M64")
    P += ["    return (x ^ _rotl(k, 13)) & M64", "",
          "def mix_hash(val, key):",
          "    return int(_mix_core(np.uint64(val) ^ np.uint64(key), np.uint64(key)))",
          "",
          "def mix_np(V, K):",
          "    V = np.asarray(V, dtype=np.uint64)",
          "    K = np.asarray(K, dtype=np.uint64)",
          "    return _mix_core(V ^ K, K)",
          "",
          "def mix(v, k):", "    return mix_hash(v, k)"]
    open(os.path.join(d, "model.py"), "w").write("\n".join(P) + "\n")

    goldens = []
    for vk, kk in [("0x0", KEYS[0]), (KEYS[0], "0x0")]:
        out = model_hash(int(vk, 16), int(kk, 16))
        goldens.append({"val": vk, "key": kk, "out": hex(out)})
    meta = {"name": NAME, "description": DESC, "screen_keys": KEYS,
            "practrand_keys": KEYS, "goldens": goldens, "rtl_top": NAME}
    open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1) + "\n")
    print(f"generated {NAME}: goldens {goldens[0]['out']}, {goldens[1]['out']}")


if __name__ == "__main__":
    build()
    print("batch-9 generation complete")
