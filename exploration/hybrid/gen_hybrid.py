#!/usr/bin/env python3
"""Hybrid candidate generator for the mix project.

Generates impl.c, rtl.v, model.py (self-contained), meta.json for hybrid
SPN candidates combining S-box, P-box, and linear layer from different
frontier points.

Usage: gen_hybrid.py <specs.json> <outdir>
  specs.json: list of {name, desc, sbox (16-list), pbox (64-list), rots [a,b]}
  outdir: candidates directory (e.g. fast_battery/candidates)
"""
import json
import os
import sys

import numpy as np

RC = [0x9E3779B97F4A7C15, 0x3C6EF372FE94F82A,
      0xDAA66D2C7DDF743F, 0x78DDE6E5FD29F054]
M64 = 0xFFFFFFFFFFFFFFFF


def build_c(spec):
    name = spec["name"]
    sbox = spec["sbox"]
    pbox = spec["pbox"]
    ra, rb = spec["rots"]
    L = []
    L.append(f"/* {name}: {spec['desc']}")
    L.append(" * GENERATED by hybrid/gen_hybrid.py -- do not edit by hand.")
    L.append(" * Bit-exact vs bundled self-contained model.py. */")
    L.append("#include <stdint.h>")
    L.append("")
    L.append("static const uint8_t SBOXT[16] = {%s};" % ",".join(map(str, sbox)))
    L.append("")
    L.append("static uint64_t rotl64(uint64_t x, unsigned r) {")
    L.append("    r &= 63u;")
    L.append("    return r ? (x << r) | (x >> (64u - r)) : x;")
    L.append("}")
    L.append("static uint64_t rk64(uint64_t k, int i) { /* i 0-based; ks=golden */")
    L.append("    static const uint64_t RC[4] = {0x9E3779B97F4A7C15ULL, 0x3C6EF372FE94F82AULL, 0xDAA66D2C7DDF743FULL, 0x78DDE6E5FD29F054ULL};")
    L.append("    unsigned r = (13u * (unsigned)(i + 1)) & 63u;")
    L.append("    return rotl64(k, r) ^ RC[i];")
    L.append("}")
    L.append("static uint64_t sbox64(uint64_t x) {")
    L.append("    uint64_t r = 0;")
    L.append("    for (int i = 0; i < 16; i++)")
    L.append("        r |= (uint64_t)SBOXT[(x >> (4*i)) & 0xFu] << (4*i);")
    L.append("    return r;")
    L.append("}")
    L.append("static uint64_t pbox64(uint64_t x) {")
    L.append("    uint64_t y = 0;")
    for i, d in enumerate(pbox):
        L.append(f"        y |= ((x >> {i}) & 1u) << {d};")
    L.append("    return y;")
    L.append("}")
    L.append(f"static uint64_t lin64(uint64_t x) {{")
    L.append(f"    return x ^ rotl64(x, {ra}) ^ rotl64(x, {rb});")
    L.append("}")
    L.append("uint64_t mix_hash(uint64_t val, uint64_t key) {")
    L.append("    uint64_t x = val;")
    L.append("    for (int i = 0; i < 4; i++) {")
    L.append("        uint64_t t = sbox64(x ^ rk64(key, i));")
    L.append("        uint64_t p = pbox64(t);")
    L.append("        x = lin64(p);")
    L.append("    }")
    L.append("    return x;")
    L.append("}")
    return "\n".join(L) + "\n"


def build_model_py(spec):
    name = spec["name"]
    sbox = spec["sbox"]
    ra, rb = spec["rots"]
    return f'''"""Self-contained numpy model for {name} (hybrid).

{spec['desc']}
"""
import numpy as np

SBOX = np.array({sbox}, dtype=np.uint64)
PBOX = np.array({spec['pbox']}, dtype=np.uint64)
RC = np.array([0x9E3779B97F4A7C15, 0x3C6EF372FE94F82A,
               0xDAA66D2C7DDF743F, 0x78DDE6E5FD29F054], dtype=np.uint64)
M64 = np.uint64(0xFFFFFFFFFFFFFFFF)
ROUNDS = 4
ROTA = {ra}
ROTB = {rb}


def _rotl(x, r):
    r %= 64
    if r == 0:
        return x
    return ((x << np.uint64(r)) | (x >> np.uint64(64 - r))) & M64


def _sbox64(x):
    y = np.zeros_like(x)
    for i in range(16):
        y |= SBOX[((x >> np.uint64(4 * i)) & np.uint64(0xF))] \\
            << np.uint64(4 * i)
    return y & M64


def _pbox64(x):
    y = np.zeros_like(x)
    for i in range(64):
        y |= ((x >> np.uint64(i)) & np.uint64(1)) << PBOX[i]
    return y & M64


def _lin(x):
    return (x ^ _rotl(x, ROTA) ^ _rotl(x, ROTB)) & M64


def _round(x, key, i):
    rk = _rotl(key, 13 * (i + 1)) ^ RC[i]
    return _lin(_pbox64(_sbox64(x ^ rk)))


def mix_np(V, K):
    x = np.asarray(V, dtype=np.uint64)
    k = np.asarray(K, dtype=np.uint64)
    for i in range(ROUNDS):
        x = _round(x, k, i)
    return x & M64


def mix(v, k):
    return int(mix_np(np.uint64(v), np.uint64(k)))
'''


def build_verilog(spec):
    # Simplified: reuse the C structure via direct translation
    # For S0 we need the RTL; use a straightforward always @(*) block
    name = spec["name"]
    sbox = spec["sbox"]
    pbox = spec["pbox"]
    ra, rb = spec["rots"]
    L = []
    L.append(f"// {name}: hybrid 4r SPN")
    L.append(f"// GENERATED by hybrid/gen_hybrid.py -- do not edit by hand.")
    L.append(f"module {name}(")
    L.append("    input  [63:0] val,")
    L.append("    input  [63:0] key,")
    L.append("    output [63:0] out")
    L.append(");")
    L.append("    // S-box as case statements per nibble would go here;")
    L.append("    // for S0 synthesis we use a behavioral model")
    L.append("    reg [63:0] x;")
    L.append("    reg [63:0] rk;")
    L.append("    reg [63:0] t, p, l;")
    L.append("    integer i, r;")
    # S-box function via case
    L.append("    function [3:0] sbox4(input [3:0] v);")
    L.append("        case (v)")
    for idx, val in enumerate(sbox):
        L.append(f"            4'd{idx}: sbox4 = 4'd{val};")
    L.append("            default: sbox4 = 4'd0;")
    L.append("        endcase")
    L.append("    endfunction")
    L.append("    function [63:0] rotl64(input [63:0] v, input [5:0] r);")
    L.append("        rotl64 = (v << r) | (v >> (6'd64 - r));")
    L.append("    endfunction")
    L.append("    always @(*) begin")
    L.append("        x = val;")
    L.append("        for (r = 0; r < 4; r = r + 1) begin")
    L.append("            // round key")
    L.append("            rk = rotl64(key, 13*(r+1));")
    L.append("            case (r)")
    for ri, rc in enumerate(["64'h9E3779B97F4A7C15", "64'h3C6EF372FE94F82A",
                             "64'hDAA66D2C7DDF743F", "64'h78DDE6E5FD29F054"]):
        L.append(f"                {ri}: rk = rk ^ {rc};")
    L.append("            endcase")
    L.append("            // S-box layer")
    L.append("            t = x ^ rk;")
    L.append("            for (i = 0; i < 16; i = i + 1)")
    L.append("                t[4*i +: 4] = sbox4(t[4*i +: 4]);")
    L.append("            // P-box layer")
    L.append("            p = 64'd0;")
    for i, d in enumerate(pbox):
        L.append(f"            p[{d}] = t[{i}];")
    L.append("            // Linear layer")
    L.append(f"            l = p ^ rotl64(p, {ra}) ^ rotl64(p, {rb});")
    L.append("            x = l;")
    L.append("        end")
    L.append("    end")
    L.append("    assign out = x;")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def main():
    specs_file, outdir = sys.argv[1], sys.argv[2]
    specs = json.load(open(specs_file))
    for spec in specs:
        name = spec["name"]
        d = os.path.join(outdir, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "impl.c"), "w") as f:
            f.write(build_c(spec))
        with open(os.path.join(d, "rtl.v"), "w") as f:
            f.write(build_verilog(spec))
        with open(os.path.join(d, "model.py"), "w") as f:
            f.write(build_model_py(spec))
        # Goldens via numpy model
        import importlib.util
        mp = os.path.join(d, "model.py")
        modspec = importlib.util.spec_from_file_location("m_" + name, mp)
        m = importlib.util.module_from_spec(modspec)
        modspec.loader.exec_module(m)
        goldens = []
        for v, k in [(0x0, 0x123456789ABCDEF0), (0x123456789ABCDEF0, 0x0)]:
            goldens.append({"val": hex(v), "key": hex(k),
                            "out": hex(m.mix(v, k))})
        meta = {"name": name, "description": spec["desc"],
                "composition": spec["desc"], "rtl_top": name,
                "screen_keys": ["0x123456789abcdef0", "0x0"],
                "practrand_keys": ["0x123456789abcdef0", "0x0"],
                "goldens": goldens}
        with open(os.path.join(d, "meta.json"), "w") as f:
            json.dump(meta, f, indent=1)
        print("generated", name)


if __name__ == "__main__":
    main()
