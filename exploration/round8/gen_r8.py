C_HDR = """/* {name}: {desc}
 * GENERATED by round8/gen_r8.py -- do not edit by hand.
 * Bit-exact vs Python model round8/models/r8.py ({pyfn}). */
#include <stdint.h>

static const uint8_t S1[16] = {s1c};

static uint32_t sbox_layer32(uint32_t x) {{
    uint32_t r = 0;
    for (int i = 0; i < 8; i++)
        r |= (uint32_t)S1[(x >> (4*i)) & 0xF] << (4*i);
    return r;
}}

static uint32_t rotl32(uint32_t x, int n) {{ return (x << n) | (x >> (32 - n)); }}
static uint64_t rotl64(uint64_t x, int n) {{
    n &= 63; return n ? (x << n) | (x >> (64 - n)) : x;
}}
static uint16_t rotl16(uint16_t x, int n) {{
    n &= 15; return n ? (uint16_t)(((x << n) | (x >> (16 - n))) & 0xFFFF) : x;
}}

static uint64_t rk(uint64_t k, int i) {{
    return rotl64(k, 13 * (i + 1)) ^ ((uint64_t)(i + 1) * 0x9E3779B97F4A7C15ULL);
}}

static uint32_t lin713(uint32_t x) {{ return x ^ rotl32(x, 7) ^ rotl32(x, 13); }}
static uint32_t lin311(uint32_t x) {{ return x ^ rotl32(x, 3) ^ rotl32(x, 11); }}
static uint32_t lin517(uint32_t x) {{ return x ^ rotl32(x, 5) ^ rotl32(x, 17); }}

static uint32_t midori_mc(uint32_t x) {{
    /* Midori64 MixColumn on 8 nibbles as two 4-nibble columns. */
    uint32_t r = 0;
    for (int col = 0; col < 2; col++) {{
        uint32_t n0 = (x >> (16*col + 0)) & 0xF;
        uint32_t n1 = (x >> (16*col + 4)) & 0xF;
        uint32_t n2 = (x >> (16*col + 8)) & 0xF;
        uint32_t n3 = (x >> (16*col + 12)) & 0xF;
        r |= (n1^n2^n3) << (16*col + 0);
        r |= (n0^n2^n3) << (16*col + 4);
        r |= (n0^n1^n3) << (16*col + 8);
        r |= (n0^n1^n2) << (16*col + 12);
    }}
    return r;
}}

static uint32_t p32(uint32_t x) {{
    /* P32 = [(8*i)%31]*31 + [31] */
    uint32_t r = 0;
    {p32_body}
    return r;
}}
"""

P32_C_BODY = "\n".join(
    f"    r |= ((x >> {P32[i]}) & 1u) << {i};" for i in range(32))

C_F = {
    "s1_1sbox": """static uint32_t F_f(uint32_t R, uint64_t rkv) {
    uint32_t t = sbox_layer32(R);
    t = lin713(t);
    return t ^ (uint32_t)rkv;
}""",
    "r311": """static uint32_t F_f(uint32_t R, uint64_t rkv) {
    uint32_t t = sbox_layer32(R);
    t = lin311(t);
    t = sbox_layer32(t);
    return t ^ (uint32_t)rkv;
}""",
    "r517": """static uint32_t F_f(uint32_t R, uint64_t rkv) {
    uint32_t t = sbox_layer32(R);
    t = lin517(t);
    t = sbox_layer32(t);
    return t ^ (uint32_t)rkv;
}""",
    "midori": """static uint32_t F_f(uint32_t R, uint64_t rkv) {
    uint32_t t = sbox_layer32(R);
    t = midori_mc(t);
    return t ^ (uint32_t)rkv;
}""",
    "s1_3sbox": """static uint32_t F_f(uint32_t R, uint64_t rkv) {
    uint32_t t = sbox_layer32(R);
    t = lin713(t);
    t = sbox_layer32(t);
    t = lin713(t);
    t = sbox_layer32(t);
    return t ^ (uint32_t)rkv;
}""",
    "alt": """static uint32_t F_f(uint32_t R, uint64_t rkv, int rnd) {
    uint32_t t = sbox_layer32(R);
    t = lin713(t);
    if ((rnd & 1) == 0)  /* even rounds: second S-box layer */
        t = sbox_layer32(t);
    return t ^ (uint32_t)rkv;
}""",
}

C_MAIN_FEIST = """
uint64_t mix_hash(uint64_t val, uint64_t key) {{
    uint32_t L = (uint32_t)(val >> 32);
    uint32_t R = (uint32_t)val;
{white}
    for (int i = 1; i <= {rounds}; i++) {{
        uint32_t F = F_f(R, rk(key, i){altarg});
        uint32_t nL = R, nR = L ^ F;
{pbox}
        L = nL; R = nR;
    }}
    return ((uint64_t)R << 32) | L;
}}
"""

C_UFEIST = """
static uint16_t F_48to16(uint64_t R, uint16_t rk16) {
    uint64_t s = 0;
    for (int j = 0; j < 12; j++)
        s |= (uint64_t)S1[(R >> (4 * j)) & 0xF] << (4 * j);
    uint16_t f = (uint16_t)(((s >> 32) ^ (s >> 16) ^ s) & 0xFFFF);
    f = (uint16_t)((f ^ rotl16(f, 3) ^ rotl16(f, 7)) & 0xFFFF);
    uint16_t g = 0;
    for (int j = 0; j < 4; j++)
        g |= (uint16_t)S1[(f >> (4 * j)) & 0xF] << (4 * j);
    return (uint16_t)((g ^ rk16) & 0xFFFF);
}

uint64_t mix_hash(uint64_t val, uint64_t key) {
    uint64_t x = val ^ key;
    uint16_t L = (uint16_t)(x >> 48);
    uint64_t R = x & 0xFFFFFFFFFFFFULL;
    for (int i = 1; i <= 8; i++) {
        uint16_t F = F_48to16(R, (uint16_t)rk(key, i));
        uint16_t nL = (uint16_t)(R >> 32);
        uint64_t nR = ((((R & 0xFFFFFFFFULL) << 16) | ((L ^ F) & 0xFFFF))
                       & 0xFFFFFFFFFFFFULL);
        L = nL; R = nR;
    }
    return (((uint64_t)L << 48) | R);
}
"""


def gen_impl(name, rounds, ftype, white, pbox):
    hdr = C_HDR.format(name=name, desc="", pyfn=name, s1c=S1_C,
                       p32_body=P32_C_BODY)
    if ftype == "ufeist_f2":
        return hdr + C_UFEIST
    white_s = ("    L ^= (uint32_t)(key >> 32);\n    R ^= (uint32_t)key;"
               if white else "")
    pbox_s = "        nR = p32(nR);" if pbox else ""
    altarg = ", i" if ftype == "alt" else ""
    return hdr + C_F[ftype] + C_MAIN_FEIST.format(
        rounds=rounds, white=white_s, pbox=pbox_s, altarg=altarg)


# ---------------- Verilog ----------------
V_SBOX_FN = """
function automatic [3:0] sbox_{n}(input [3:0] x);
    begin
        case (x)
{sbox_cases}
            default: sbox_{n} = 4'h0;
        endcase
    end
endfunction
"""

V_HDR = """// {name}: {desc}
// GENERATED by round8/gen_r8.py -- do not edit by hand.
// Bit-exact vs Python model round8/models/r8.py ({pyfn}).
module {name}(
    input  [63:0] val,
    input  [63:0] key,
    output [63:0] out
);
"""

V_RK = """
// Round key: rotl(k, 13*(i+1)) XOR ((i+1)*0x9E3779B97F4A7C15)
function automatic [63:0] rk_{n}(input [63:0] k, input integer i);
    integer r;
    reg [63:0] rc;
    begin
        r = (13 * (i + 1)) % 64;
        rc = (i + 1) * 64'h9E3779B97F4A7C15;
        if (r == 0)
            rk_{n} = k ^ rc;
        else
            rk_{n} = ((k << r) | (k >> (64 - r))) ^ rc;
    end
endfunction
"""

V_F = {
    "s1_1sbox": """
// F = S1 layer -> lin713 -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        t = t ^ {t[24:0], t[31:25]} ^ {t[18:0], t[31:19]};
        F_{n} = t ^ rk32;
    end
endfunction
""",
    "r311": """
// F = S1 -> lin(3,11) -> S1 -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        t = t ^ {t[28:0], t[31:29]} ^ {t[20:0], t[31:21]};
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(t[4*j+:4]);
        F_{n} = t ^ rk32;
    end
endfunction
""",
    "r517": """
// F = S1 -> lin(5,17) -> S1 -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        t = t ^ {t[26:0], t[31:27]} ^ {t[14:0], t[31:15]};
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(t[4*j+:4]);
        F_{n} = t ^ rk32;
    end
endfunction
""",
    "midori": """
// F = S1 -> Midori MixColumn (two 4-nibble columns) -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32);
    reg [31:0] t;
    reg [3:0] n0, n1, n2, n3;
    integer j, col;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        for (col = 0; col < 2; col = col + 1) begin
            n0 = t[16*col+:4];
            n1 = t[16*col+4+:4];
            n2 = t[16*col+8+:4];
            n3 = t[16*col+12+:4];
            t[16*col+:4]    = n1 ^ n2 ^ n3;
            t[16*col+4+:4]  = n0 ^ n2 ^ n3;
            t[16*col+8+:4]  = n0 ^ n1 ^ n3;
            t[16*col+12+:4] = n0 ^ n1 ^ n2;
        end
        F_{n} = t ^ rk32;
    end
endfunction
""",
    "s1_3sbox": """
// F = S1 -> lin713 -> S1 -> lin713 -> S1 -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        t = t ^ {t[24:0], t[31:25]} ^ {t[18:0], t[31:19]};
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(t[4*j+:4]);
        t = t ^ {t[24:0], t[31:25]} ^ {t[18:0], t[31:19]};
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(t[4*j+:4]);
        F_{n} = t ^ rk32;
    end
endfunction
""",
    "alt": """
// F = S1 -> lin713 [-> S1 on even rounds] -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32, input integer rnd);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        t = t ^ {t[24:0], t[31:25]} ^ {t[18:0], t[31:19]};
        if ((rnd & 1) == 0)
            for (j = 0; j < 8; j = j + 1)
                t[4*j+:4] = sbox_{n}(t[4*j+:4]);
        F_{n} = t ^ rk32;
    end
endfunction
""",
}

V_P32_COMMENT = """
// P32 bit permutation (unrolled): Rt_perm[i] = Rt_pre[P32[i]], P32=[(8*i)%31]*31+[31]
"""

V_MAIN = """
reg [31:0] L, R;
reg [31:0] Lt, Rt, Rt_pre;
reg [63:0] rkv;
integer i;
always @(*) begin
{white}
    for (i = 0; i < {rounds}; i = i + 1) begin
        rkv = rk_{n}(key, i+1);
        Lt = R;
        Rt_pre = L ^ F_{n}(R, rkv[31:0]{altarg});
        Rt = {rt_src};
        L = Lt;
        R = Rt;
    end
end

assign out = {{R, L}};

endmodule
"""


def gen_rtl(name, rounds, ftype, white, pbox, desc):
    n = name
    cases = "\n".join(
        f"            4'h{v:X}: sbox_{n} = 4'h{S1[v]:X};" for v in range(16))
    L = [V_HDR.replace('{name}', name).replace('{desc}', desc).replace('{pyfn}', name)]
    L.append(V_SBOX_FN.replace('{n}', n).replace('{sbox_cases}', cases))
    L.append(V_RK.replace('{n}', n))
    L.append(V_F[ftype].replace('{n}', n))
    if pbox:
        # P32 inlined as a blocking assignment INSIDE the always block
        # (Rt = {Rt_pre[P32[31]], ..., Rt_pre[P32[0]]}).
        # Never emit it as a module-level continuous assign: a module-level
        # assign reading an always-block reg (Rt_pre) creates a cross-process
        # read that Yosys collapses into a combinational loop in the mapped
        # netlist (killed r8_feist6_pbox's S0 with an analyzer crash, 2026-10-02).
        concat = ", ".join(f"Rt_pre[{P32[i]}]" for i in range(31, -1, -1))
        # Braces live in the VALUE (format inserts values verbatim); the
        # template's own {rt_src} braces are placeholder syntax, not literals.
        rt_src = "{" + concat + "}"
    else:
        rt_src = "Rt_pre"
    if white:
        white_s = ("    L = val[63:32] ^ key[63:32];\n"
                   "    R = val[31:0]  ^ key[31:0];")
    else:
        white_s = ("    L = val[63:32];\n"
                   "    R = val[31:0];")
    altarg = ", i+1" if ftype == "alt" else ""
    L.append(V_MAIN.format(n=n, rounds=rounds, white=white_s, altarg=altarg,
                           rt_src=rt_src))
    return "".join(L)


V_UFEIST = """// {name}: 8-round unbalanced Feistel 16/48, F = S1(12nib) -> fold -> lin16 -> S1(4nib) -> ^rk16
// GENERATED by round8/gen_r8.py -- do not edit by hand.
module {name}(
    input  [63:0] val,
    input  [63:0] key,
    output [63:0] out
);
{sboxfn}
function automatic [15:0] F48to16_{n}(input [47:0] R, input [15:0] rk16);
    reg [47:0] s;
    reg [15:0] f, g;
    integer j;
    begin
        for (j = 0; j < 12; j = j + 1)
            s[4*j+:4] = sbox_{n}(R[4*j+:4]);
        f = s[47:32] ^ s[31:16] ^ s[15:0];
        f = f ^ {f[12:0], f[15:13]} ^ {f[8:0], f[15:9]};
        for (j = 0; j < 4; j = j + 1)
            g[4*j+:4] = sbox_{n}(f[4*j+:4]);
        F48to16_{n} = g ^ rk16;
    end
endfunction
{rkfn}
reg [15:0] L;
reg [47:0] R;
reg [15:0] Lt;
reg [47:0] Rt;
reg [63:0] rkv;
reg [63:0] x;
integer i;
always @(*) begin
    x = val ^ key;
    L = x[63:48];
    R = x[47:0];
    for (i = 0; i < 8; i = i + 1) begin
        rkv = rk_{n}(key, i+1);
        Lt = R[47:32];
        Rt = {{R[31:0], 16'b0}} | ((L ^ F48to16_{n}(R, rkv[15:0])) & 16'hFFFF);
        L = Lt;
        R = Rt;
    end
end

assign out = {{L, R}};

endmodule
"""


def gen_rtl_ufeist(name, desc):
    n = name
    cases = "\n".join(
        f"            4'h{v:X}: sbox_{n} = 4'h{S1[v]:X};" for v in range(16))
    return (V_UFEIST.replace('{name}', name).replace('{n}', n)
            .replace('{sboxfn}', V_SBOX_FN.replace('{n}', n).replace('{sbox_cases}', cases))
            .replace('{rkfn}', V_RK.replace('{n}', n)))


MODEL_WRAPPER = '''"""Python model wrapper for {name} (fast_battery candidate interface).
Exports scalar `mix(v, k)` and vectorized `mix_np(V, K)`."""
import sys
import numpy as np
sys.path.insert(0, "/home/hatch/workspace/mix/exploration/round8/models")
from r8 import {pyfn} as _np

def mix(v, k):
    return int(_np(np.uint64(v), np.uint64(k)))

mix_np = _np
'''


def main():
    r8fns = {n: fn for n, fn, _ in r8.CANDIDATES_R8}
    descs = {n: d for n, _, d in r8.CANDIDATES_R8}
    for name, rounds, ftype, white, pbox in SPECS:
        d = os.path.join(FB, name)
        os.makedirs(d, exist_ok=True)
        if ftype == "ufeist_f2":
            impl = gen_impl(name, rounds, ftype, white, pbox)
            rtl = gen_rtl_ufeist(name, descs[name])
        else:
            impl = gen_impl(name, rounds, ftype, white, pbox)
            rtl = gen_rtl(name, rounds, ftype, white, pbox, descs[name])
        open(os.path.join(d, "impl.c"), "w").write(impl)
        open(os.path.join(d, "rtl.v"), "w").write(rtl)
        open(os.path.join(d, "model.py"), "w").write(
            MODEL_WRAPPER.format(name=name, pyfn=name))
        fn = r8fns[name]
        g1 = int(fn(np.uint64(0), np.uint64(0x123456789ABCDEF0)))
        g2 = int(fn(np.uint64(0), np.uint64(0)))
        meta = {
            "name": name,
            "description": descs[name],
            "composition": descs[name],
            "rtl_top": name,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0",
                 "out": "0x%016x" % g1},
                {"val": "0x0", "key": "0x0", "out": "0x%016x" % g2},
            ],
        }
        open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1))
        print(f"generated {name}")


if __name__ == "__main__":
    main()
