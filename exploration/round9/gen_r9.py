#!/usr/bin/env python3
"""Round 9 candidate generator: emits impl.c, rtl.v, model.py, meta.json for
each spec in SPECS. The numpy model (round9/models/r9.py) is the reference;
bit-exactness of the generated C/RTL is verified by xcheck + check_rtl.

Usage: python3 round9/gen_r9.py   (writes fast_battery/candidates/r9_*/)
"""
import json
import os
import sys

EXP = "/home/hatch/workspace/mix/exploration"
sys.path.insert(0, os.path.join(EXP, "round9", "models"))
import numpy as np
import r9

FB = os.path.join(EXP, "fast_battery", "candidates")
S1 = [0, 1, 2, 4, 3, 8, 15, 12, 9, 5, 11, 6, 7, 14, 13, 10]
S1_C = "{" + ",".join(str(v) for v in S1) + "}"

# (name, rounds, ftype, ks, whitening)
# ftype: ("rot", a, b) | ("lin2",) | ("altrot", a1, b1, a2, b2)
# ks: "std" | "alt" | "rot" | "none"
SPECS = [
    ("r9_feist5_s1_1sbox_nw", 5, ("rot", 7, 13), "std", False),
    ("r9_feist5_s1_1sbox", 5, ("rot", 7, 13), "std", True),
    ("r9_feist6_rot311_nw", 6, ("rot", 3, 11), "std", False),
    ("r9_feist6_rot517_nw", 6, ("rot", 5, 17), "std", False),
    ("r9_feist6_rot1119_nw", 6, ("rot", 11, 19), "std", False),
    ("r9_feist6_rot0925_nw", 6, ("rot", 9, 25), "std", False),
    ("r9_feist6_rot0719_nw", 6, ("rot", 7, 19), "std", False),
    ("r9_feist6_rot0824_nw", 6, ("rot", 8, 24), "std", False),
    ("r9_feist6_ksalt_nw", 6, ("rot", 7, 13), "alt", False),
    ("r9_feist6_ksrot_nw", 6, ("rot", 7, 13), "rot", False),
    ("r9_feist6_nork", 6, ("rot", 7, 13), "none", True),
    ("r9_feist7_s1_lin2_nw", 7, ("lin2",), "std", False),
    ("r9_feist7_rot517_nw", 7, ("rot", 5, 17), "std", False),
    ("r9_feist6_altrot_nw", 6, ("altrot", 7, 13, 5, 17), "std", False),
]

C_HDR = """/* {name}: {desc}
 * GENERATED by round9/gen_r9.py -- do not edit by hand.
 * Bit-exact vs Python model round9/models/r9.py ({pyfn}). */
#include <stdint.h>

static const uint8_t S1[16] = {s1c};

static uint32_t sbox_layer32(uint32_t x) {{
    uint32_t r = 0;
    for (int i = 0; i < 8; i++)
        r |= (uint32_t)S1[(x >> (4*i)) & 0xF] << (4*i);
    return r;
}}

static uint32_t rotl32(uint32_t x, int n) {{ return (x << n) | (x >> (32 - n)); }}
static uint64_t rotl64(uint64_t x, int n) {{
    n &= 63; return n ? (x << n) | (x >> (64 - n)) : x;
}}
"""

C_KS = {
    "std": """static uint32_t RK32(uint64_t k, int i) {
    /* affine schedule: low32(rotl64(k,13*(i+1)) ^ (i+1)*GOLDEN64) */
    uint64_t rkv = rotl64(k, 13 * (i + 1)) ^ ((uint64_t)(i + 1) * 0x9E3779B97F4A7C15ULL);
    return (uint32_t)rkv;
}""",
    "alt": """static uint32_t RK32(uint64_t k, int i) {
    /* alternating key halves + 32-bit round constant */
    uint32_t half = (i & 1) ? (uint32_t)(k >> 32) : (uint32_t)k;
    return half ^ (uint32_t)((i + 1) * 0x9E3779B9ULL);
}""",
    "rot": """static uint32_t RK32(uint64_t k, int i) {
    /* cheap schedule: low32(rotl64(k, 8*i)) */
    return (uint32_t)rotl64(k, 8 * i);
}""",
    "none": """static uint32_t RK32(uint64_t k, int i) {
    (void)k; (void)i;
    return 0u;  /* no round key: key enters via whitening only */
}""",
}


def c_lin(a, b):
    return (f"static uint32_t lin_ab(uint32_t x) {{ "
            f"return x ^ rotl32(x, {a}) ^ rotl32(x, {b}); }}")


def c_f(ftype):
    if ftype[0] == "rot":
        _, a, b = ftype
        return (c_lin(a, b) + """
static uint32_t F_f(uint32_t R, uint32_t rk32) {
    uint32_t t = sbox_layer32(R);
    t = lin_ab(t);
    return t ^ rk32;
}""", "")
    if ftype[0] == "lin2":
        return (c_lin(7, 13) + """
static uint32_t F_f(uint32_t R, uint32_t rk32) {
    uint32_t t = sbox_layer32(R);
    t = lin_ab(t);
    t = lin_ab(t);
    return t ^ rk32;
}""", "")
    if ftype[0] == "altrot":
        _, a1, b1, a2, b2 = ftype
        return (f"static uint32_t lin_odd(uint32_t x) {{ "
                f"return x ^ rotl32(x, {a1}) ^ rotl32(x, {b1}); }}\n"
                f"static uint32_t lin_even(uint32_t x) {{ "
                f"return x ^ rotl32(x, {a2}) ^ rotl32(x, {b2}); }}\n"
                """static uint32_t F_f(uint32_t R, uint32_t rk32, int rnd) {
    uint32_t t = sbox_layer32(R);
    t = (rnd & 1) ? lin_odd(t) : lin_even(t);
    return t ^ rk32;
}""", ", i")
    raise ValueError(ftype)


C_MAIN = """
uint64_t mix_hash(uint64_t val, uint64_t key) {{
    uint32_t L = (uint32_t)(val >> 32);
    uint32_t R = (uint32_t)val;
{white}
    for (int i = 1; i <= {rounds}; i++) {{
        uint32_t F = F_f(R, RK32(key, i){rndarg});
        uint32_t nL = R, nR = L ^ F;
        L = nL; R = nR;
    }}
    return ((uint64_t)R << 32) | L;
}}
"""


def gen_impl(name, rounds, ftype, ks, white, desc):
    f_code, rndarg = c_f(ftype)
    white_s = ("    L ^= (uint32_t)(key >> 32);\n    R ^= (uint32_t)key;"
               if white else "")
    return (C_HDR.format(name=name, desc=desc, pyfn=name, s1c=S1_C)
            + C_KS[ks] + "\n" + f_code
            + C_MAIN.format(rounds=rounds, white=white_s, rndarg=rndarg))


# ---------------- Verilog ----------------
V_SBOX_FN = """
function automatic [3:0] sbox_{n}(input [3:0] x);
    begin
        case (x)
{sbox_cases}
            default: sbox_{n} = 4'h0;
        endcase
    end
endfunction
"""

V_HDR = """// {name}: {desc}
// GENERATED by round9/gen_r9.py -- do not edit by hand.
// Bit-exact vs Python model round9/models/r9.py ({pyfn}).
module {name}(
    input  [63:0] val,
    input  [63:0] key,
    output [63:0] out
);
"""

V_KS = {
    "std": """
// Round key: low32(rotl64(k, 13*(i+1)) ^ ((i+1)*0x9E3779B97F4A7C15))
function automatic [31:0] RK32_{n}(input [63:0] k, input integer i);
    integer r;
    reg [63:0] rkv;
    begin
        r = (13 * (i + 1)) % 64;
        rkv = ((k << r) | (k >> (64 - r))) ^ ((i + 1) * 64'h9E3779B97F4A7C15);
        RK32_{n} = rkv[31:0];
    end
endfunction
""",
    "alt": """
// Round key: alternating key halves XOR ((i+1)*0x9E3779B9)
function automatic [31:0] RK32_{n}(input [63:0] k, input integer i);
    begin
        if (i & 1)
            RK32_{n} = k[63:32] ^ ((i + 1) * 32'h9E3779B9);
        else
            RK32_{n} = k[31:0]  ^ ((i + 1) * 32'h9E3779B9);
    end
endfunction
""",
    "rot": """
// Round key: low32(rotl64(k, 8*i))
function automatic [31:0] RK32_{n}(input [63:0] k, input integer i);
    integer r;
    begin
        r = (8 * i) % 64;
        if (r == 0)
            RK32_{n} = k[31:0];
        else
            RK32_{n} = ((k << r) | (k >> (64 - r))) & 64'hFFFFFFFF;
    end
endfunction
""",
    "none": """
// No round key (key enters via whitening only)
function automatic [31:0] RK32_{n}(input [63:0] k, input integer i);
    begin
        RK32_{n} = 32'h0;
    end
endfunction
""",
}


def v_rot(n):
    # rotl32(t, n) = {t[32-n-1:0], t[31:32-n]}
    return "{t[%d:0], t[31:%d]}" % (32 - n - 1, 32 - n)


def v_f(ftype, n):
    if ftype[0] == "rot":
        _, a, b = ftype
        lin = f"t ^ {v_rot(a)} ^ {v_rot(b)}"
        body = f"        t = {lin};"
        return f"""
// F = S1 layer -> lin({a},{b}) -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
{body}
        F_{n} = t ^ rk32;
    end
endfunction
""", ""
    if ftype[0] == "lin2":
        lin = f"t ^ {v_rot(7)} ^ {v_rot(13)}"
        return f"""
// F = S1 layer -> lin(7,13) -> lin(7,13) -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        t = {lin};
        t = {lin};
        F_{n} = t ^ rk32;
    end
endfunction
""", ""
    if ftype[0] == "altrot":
        _, a1, b1, a2, b2 = ftype
        lin_o = f"t ^ {v_rot(a1)} ^ {v_rot(b1)}"
        lin_e = f"t ^ {v_rot(a2)} ^ {v_rot(b2)}"
        return f"""
// F = S1 layer -> lin({a1},{b1}) on odd rounds / lin({a2},{b2}) on even -> ^rk32
function automatic [31:0] F_{n}(input [31:0] R, input [31:0] rk32, input integer rnd);
    reg [31:0] t;
    integer j;
    begin
        for (j = 0; j < 8; j = j + 1)
            t[4*j+:4] = sbox_{n}(R[4*j+:4]);
        if (rnd & 1)
            t = {lin_o};
        else
            t = {lin_e};
        F_{n} = t ^ rk32;
    end
endfunction
""", ", i+1"
    raise ValueError(ftype)


V_MAIN = """
reg [31:0] L, R;
reg [31:0] Lt, Rt;
integer i;
always @(*) begin
{white}
    for (i = 0; i < {rounds}; i = i + 1) begin
        Lt = R;
        Rt = L ^ F_{n}(R, RK32_{n}(key, i+1){rndarg});
        L = Lt;
        R = Rt;
    end
end

assign out = {{R, L}};

endmodule
"""


def gen_rtl(name, rounds, ftype, ks, white, desc):
    n = name
    cases = "\n".join(
        f"            4'h{v:X}: sbox_{n} = 4'h{S1[v]:X};" for v in range(16))
    L = [V_HDR.replace('{name}', name).replace('{desc}', desc).replace('{pyfn}', name)]
    L.append(V_SBOX_FN.replace('{n}', n).replace('{sbox_cases}', cases))
    L.append(V_KS[ks].replace('{n}', n))
    f_code, rndarg = v_f(ftype, n)
    L.append(f_code)
    if white:
        white_s = ("    L = val[63:32] ^ key[63:32];\n"
                   "    R = val[31:0]  ^ key[31:0];")
    else:
        white_s = ("    L = val[63:32];\n"
                   "    R = val[31:0];")
    L.append(V_MAIN.format(n=n, rounds=rounds, white=white_s, rndarg=rndarg))
    return "".join(L)


MODEL_WRAPPER = '''"""Python model wrapper for {name} (fast_battery candidate interface).
Exports scalar `mix(v, k)` and vectorized `mix_np(V, K)`."""
import sys
import numpy as np
sys.path.insert(0, "/home/hatch/workspace/mix/exploration/round9/models")
from r9 import {pyfn} as _np

def mix(v, k):
    return int(_np(np.uint64(v), np.uint64(k)))

mix_np = _np
'''


def main():
    r9fns = {n: fn for n, fn, _ in r9.CANDIDATES_R9}
    descs = {n: d for n, _, d in r9.CANDIDATES_R9}
    for name, rounds, ftype, ks, white in SPECS:
        d = os.path.join(FB, name)
        os.makedirs(d, exist_ok=True)
        desc = descs[name]
        open(os.path.join(d, "impl.c"), "w").write(
            gen_impl(name, rounds, ftype, ks, white, desc))
        open(os.path.join(d, "rtl.v"), "w").write(
            gen_rtl(name, rounds, ftype, ks, white, desc))
        open(os.path.join(d, "model.py"), "w").write(
            MODEL_WRAPPER.format(name=name, pyfn=name))
        fn = r9fns[name]
        g1 = int(fn(np.uint64(0), np.uint64(0x123456789ABCDEF0)))
        g2 = int(fn(np.uint64(0), np.uint64(0)))
        meta = {
            "name": name,
            "description": desc,
            "composition": desc,
            "rtl_top": name,
            "screen_keys": ["0x123456789abcdef0", "0x0"],
            "practrand_keys": ["0x123456789abcdef0", "0x0"],
            "goldens": [
                {"val": "0x0", "key": "0x123456789abcdef0",
                 "out": "0x%016x" % g1},
                {"val": "0x0", "key": "0x0", "out": "0x%016x" % g2},
            ],
        }
        open(os.path.join(d, "meta.json"), "w").write(json.dumps(meta, indent=1))
        print(f"generated {name}")


if __name__ == "__main__":
    main()
