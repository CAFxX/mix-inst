DEDUP_VECS = 48


def _fixed_vectors():
    import numpy as np
    rng = np.random.default_rng(0x7E44)
    V = rng.integers(0, 2**64, size=DEDUP_VECS, dtype=np.uint64)
    K = rng.integers(0, 2**64, size=DEDUP_VECS, dtype=np.uint64)
    return V, K


def build_registry():
    """Signature -> candidate name for every existing fast_battery candidate."""
    import numpy as np
    import importlib.util
    V, K = _fixed_vectors()
    reg = {}
    for cand in sorted(os.listdir(CANDDIR)):
        if cand.startswith("rtw_"): continue  # own sweep outputs
        mp = os.path.join(CANDDIR, cand, "model.py")
        if not os.path.exists(mp):
            continue
        try:
            spec = importlib.util.spec_from_file_location(
                "model_" + cand, mp)
            m = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(m)
            out = m.mix_np(V, K)
            sig = ",".join(f"{int(v):016x}" for v in out)
            reg.setdefault(sig, cand)
        except Exception as e:
            print(f"  registry: skip {cand}: {e}")
    return reg


def emit_one(name, spec, desc):
    import numpy as np
    d = os.path.join(CANDDIR, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "impl.c"), "w") as f:
        f.write(gen_impl(name, spec, desc))
    with open(os.path.join(d, "rtl.v"), "w") as f:
        f.write(gen_rtl(name, spec, desc))
    with open(os.path.join(d, "model.py"), "w") as f:
        f.write(MODEL_PY.format(name=name, spec_repr=repr(spec)))
    fn = rtweak.feistel_tw_np
    V = np.array([0], dtype=np.uint64)
    K = np.array([0x123456789ABCDEF0], dtype=np.uint64)
    g0 = f"0x{int(fn(V, K, spec)[0]):016x}"
    V = np.array([0x123456789ABCDEF0], dtype=np.uint64)
    K = np.array([0], dtype=np.uint64)
    g1 = f"0x{int(fn(V, K, spec)[0]):016x}"
    with open(os.path.join(d, "meta.json"), "w") as f:
        f.write(META_JSON.format(name=name, desc=desc.replace('"', "'"),
                                 golden0=g0, golden1=g1))
    # append registration for check_rtl's dotted import (ensure header first)
    regf = os.path.join(MODELS, "rtweak_cands.py")
    if not os.path.exists(regf) or os.path.getsize(regf) == 0:
        with open(regf, "w") as f:
            f.write("import sys\nsys.path.insert(0, %r)\n"
                    "from rtweak import register\n" % MODELS)
    with open(regf, "a") as f:
        f.write(f"globals()['{name}'] = register('{name}', {spec!r})\n")
    return d


def emit_all(progress_cb=None):
    specs = list(enumerate_specs())
    print(f"{len(specs)} specs enumerated", flush=True)
    reg = build_registry()
    print(f"registry: {len(reg)} existing signatures", flush=True)
    V, K = _fixed_vectors()
    import numpy as np
    seen = {}
    emitted, dup = 0, 0
    # reset candidate registry module
    regf = os.path.join(MODELS, "rtweak_cands.py")
    with open(regf, "w") as f:
        f.write("import sys\nsys.path.insert(0, %r)\n"
                "from rtweak import register\n" % MODELS)
    for idir in (RTW, MODELS):
        ip = os.path.join(idir, "__init__.py")
        if not os.path.exists(ip):
            open(ip, "w").write("")
    for name, spec, desc, nb in specs:
        sig = ",".join(f"{int(v):016x}"
                       for v in rtweak.feistel_tw_np(V, K, spec))
        if sig in reg:
            dup += 1
            if progress_cb:
                progress_cb(name, "DUP_EXISTING", reg[sig])
            continue
        if sig in seen:
            dup += 1
            if progress_cb:
                progress_cb(name, "DUP_SWEEP", seen[sig])
            continue
        seen[sig] = name
        if spec.get('rkmult', 13) != 13:
            rks = [int(rtweak.rk32_np(np.uint64(0x123456789ABCDEF0), i,
                                     spec['rkmult'])) for i in range(1, 7)]
            assert len(set(rks)) == 6, f"rk collision: {name}"
        emit_one(name, spec, desc)
        emitted += 1
        if progress_cb:
            progress_cb(name, "EMITTED", nb)
    print(f"emitted={emitted} dups={dup}", flush=True)
    return emitted


