# Precompute S1 DNF once (same table for every candidate).
_S1_DNF = {b: dnf_for_sbox_bit(S1, b) for b in range(4)}


def _s1_assigns(dst, src):
    cube_v = gen_r20._cube_verilog
    lines = []
    for j in range(8):
        b = 4 * j
        for bit in range(4):
            cubes = _S1_DNF[bit]
            expr = (" | ".join(cube_v(m, cb, b, src)
                               for m, cb in cubes) if cubes else "1'b0")
            lines.append(f"            {dst}[{b + bit}] = {expr};")
    return "\n".join(lines)


def perm_id(perm):
    kind, arg = perm
    if kind == 'rev':
        return 'rev'
    if kind == 'byteswap':
        return 'byteswap'
    if kind == 'nibperm':
        return 'nibperm_' + ''.join(str(x) for x in arg)
    if kind == 'rot':
        return f'rot{arg:02d}'
    raise ValueError(perm)


def perm_index_list(perm):
    return rtweak._perm_index(perm[0], perm[1]).tolist()


# ---------------- C ----------------
C_HDR = """/* {name}: {desc}
 * GENERATED by round_tweak/gen_tweak.py -- do not edit by hand.
 * Bit-exact vs Python model round_tweak/models/rtweak.py ({name}). */
#include <stdint.h>

static const uint8_t S1T[16] = {{0,1,2,4,3,8,15,12,9,5,11,6,7,14,13,10}};
static uint32_t rotl32(uint32_t x, int n) {{ n &= 31; return n ? (x << n) | (x >> (32 - n)) : x; }}
static uint32_t rotr32(uint32_t x, int n) {{ n &= 31; return n ? (x >> n) | (x << (32 - n)) : x; }}
static uint64_t rotl64(uint64_t x, int n) {{ n &= 63; return n ? (x << n) | (x >> (64 - n)) : x; }}
static uint32_t sbox32(uint32_t x, const uint8_t *T) {{
    uint32_t r = 0;
    for (int i = 0; i < 8; i++) r |= (uint32_t)T[(x >> (4*i)) & 0xF] << (4*i);
    return r;
}}
static uint32_t chi_off(uint32_t x, int o1, int o2) {{
    uint32_t r = 0;
    for (int i = 0; i < 32; i++) {{
        uint32_t a0 = (x >> i) & 1u, a1 = (x >> ((i + o1) % 32)) & 1u, a2 = (x >> ((i + o2) % 32)) & 1u;
        r |= (a0 ^ ((~a1) & a2)) << i;
    }}
    return r;
}}
static uint32_t pbox32(uint32_t x, const uint8_t *P) {{
    uint32_t r = 0;
    for (int i = 0; i < 32; i++) r |= ((x >> P[i]) & 1u) << i;
    return r;
}}
static uint32_t RK32(uint64_t k, int i, int c) {{
    return (uint32_t)(rotl64(k, (c * (i + 1)) % 64) ^ ((uint64_t)(i + 1) * 0x9E3779B97F4A7C15ULL));
}}
"""

C_MAIN = """
uint64_t mix_hash(uint64_t val, uint64_t key) {{
    val ^= 0x{pre:016x}ULL;
    uint32_t L = (uint32_t)(val >> 32), R = (uint32_t)val;
    for (int i = 1; i <= 6; i++) {{
        uint32_t rk = RK32(key, i, {c});
        uint32_t F = i==1?F1(R,rk):i==2?F2(R,rk):i==3?F3(R,rk):i==4?F4(R,rk):i==5?F5(R,rk):F6(R,rk);
        uint32_t nL = R, nR = L ^ F;
        L = nL; R = nR;
    }}
    return (((uint64_t)R << 32) | L) ^ 0x{post:016x}ULL;
}}
"""


def c_round_fn(ri, rs):
    L = [f"static uint32_t F{ri}(uint32_t R, uint32_t rk){{"]
    src = "R"
    if rs.get('pin'):
        pid = perm_id(rs['pin'])
        L.append(f"    uint32_t w = pbox32(R, P_{pid});")
        src = "w"
    nl = rs['nl']
    if nl[0] == 's1':
        L.append(f"    uint32_t t = sbox32({src}, S1T);")
    else:
        L.append(f"    uint32_t t = chi_off({src}, {nl[1]}, {nl[2]});")
    ms = rs.get('mask')
    if ms:
        L.append(f"    t ^= rotr32(t, {ms[0]}) & 0x{ms[1]:08x}u;")
    lin = rs.get('lin')
    if lin:
        if len(lin) == 3:
            L.append(f"    t = rotl32(t, {lin[0]}) ^ rotl32(t, {lin[1]}) ^ rotl32(t, {lin[2]});")
        elif len(lin) == 2:
            L.append(f"    t = t ^ rotl32(t, {lin[0]}) ^ rotl32(t, {lin[1]});")
        else:
            L.append(f"    t = t ^ rotl32(t, {lin[0]});")
    if rs.get('pout'):
        pid = perm_id(rs['pout'])
        L.append(f"    t = pbox32(t, P_{pid});")
    rc = rs.get('rc', 0)
    fm = rs.get('fm', 0)
    if fm == '311':
        L.append(f"    return rotl32(t, 3) ^ rotl32(t, 11) ^ rk ^ 0x{rc:08x}u;")
    elif fm:
        L.append(f"    uint32_t y = t ^ rk ^ 0x{rc:08x}u;")
        L.append(f"    return y ^ rotl32(y, {fm});")
    else:
        L.append(f"    return t ^ rk ^ 0x{rc:08x}u;")
    L.append("}")
    return "\n".join(L)


def gen_impl(name, spec, desc):
    c = spec.get('rkmult', 13)
    # permutation tables used by this candidate (deduped)
    tables = {}
    for rs in spec['rounds']:
        for pk in ('pin', 'pout'):
            if rs.get(pk):
                pid = perm_id(rs[pk])
                tables[pid] = perm_index_list(rs[pk])
    tbl_txt = "".join("static const uint8_t P_%s[32] = {%s};\n" % (
        pid, ",".join(str(i) for i in idx)) for pid, idx in tables.items())
    body = C_HDR.format(name=name, desc=desc) + tbl_txt
    for ri, rs in enumerate(spec['rounds'], start=1):
        body += c_round_fn(ri, rs) + "\n"
    body += C_MAIN.format(pre=spec.get('pre', 0), post=spec.get('post', 0),
                          c=c)
    return body

