def v_rotr_expr(reg, r):
    # rotr(reg, r), 1 <= r <= 31
    return f"{{{reg}[{r - 1}:0], {reg}[31:{r}]}}"


def v_round_assigns(rs):
    """Assigns computing F into t. Returns (text, fm_flag)."""
    lines = []
    src = "R"
    pin = rs.get('pin')
    if pin:
        idx = perm_index_list(pin)
        for j in range(32):
            lines.append(f"            u[{j}] = R[{idx[j]}];")
        src = "u"
    nl = rs['nl']
    if nl[0] == 's1':
        lines.append(_s1_assigns("t", src))
    else:
        o1, o2 = nl[1], nl[2]
        for j in range(32):
            lines.append(
                f"            t[{j}] = {src}[{j}] ^ "
                f"(~{src}[{(j + o1) % 32}] & {src}[{(j + o2) % 32}]);")
    ms = rs.get('mask')
    if ms:
        r, m = ms
        lines.append(f"            t = t ^ ({v_rotr_expr('t', r)} & 32'h{m:08x});")
    lin = rs.get('lin')
    if lin:
        if len(lin) == 3:
            lines.append(f"            t = {_rotl_expr('t', lin[0])} ^ "
                         f"{_rotl_expr('t', lin[1])} ^ {_rotl_expr('t', lin[2])};")
        elif len(lin) == 2:
            lines.append(f"            t = t ^ {_rotl_expr('t', lin[0])} ^ "
                         f"{_rotl_expr('t', lin[1])};")
        else:
            lines.append(f"            t = t ^ {_rotl_expr('t', lin[0])};")
    pout = rs.get('pout')
    if pout:
        idx = perm_index_list(pout)
        for j in range(32):
            lines.append(f"            u[{j}] = t[{idx[j]}];")
        lines.append("            t = u;")
    fm = rs.get('fm', 0)
    rc = rs.get('rc', 0)
    if fm == '311':
        lines.append(f"            t = {_rotl_expr('t', 3)} ^ {_rotl_expr('t', 11)} ^ rk32 ^ 32'h{rc:08x};")
    elif fm:
        lines.append(f"            u = t ^ rk32 ^ 32'h{rc:08x};")
        lines.append(f"            t = u ^ {_rotl_expr('u', fm)};")
    return "\n".join(lines), bool(fm)


def gen_rtl(name, spec, desc):
    c = spec.get('rkmult', 13)
    assert c % 2 == 1, "rkmult must be odd (else r=0 shift hazard)"
    pre = spec.get('pre', 0)
    post = spec.get('post', 0)
    rounds = spec['rounds']
    body = ["always @(*) begin"]
    if pre:
        body.append(f"    L = val[63:32] ^ 32'h{(pre >> 32) & 0xffffffff:08x};")
        body.append(f"    R = val[31:0] ^ 32'h{pre & 0xffffffff:08x};")
    else:
        body.append("    L = val[63:32];")
        body.append("    R = val[31:0];")
    body.append("    for (i = 0; i < 6; i = i + 1) begin")
    body.append(f"        r = ({c} * (i + 2)) % 64;")
    body.append("        rkv = ((key << r) | (key >> (64 - r))) ^ "
                "((i + 2) * 64'h9E3779B97F4A7C15);")
    body.append("        rk32 = rkv[31:0];")
    fm_flags = []
    for ri, rs in enumerate(rounds):
        kw = "if" if ri == 0 else "else if"
        body.append(f"        {kw} (i == {ri}) begin")
        assigns, is_fm = v_round_assigns(rs)
        fm_flags.append(is_fm)
        for line in assigns.split("\n"):
            body.append(line)
        body.append("        end")
    # tail: Rt per round kind
    tail_kinds = {}
    for ri, rs in enumerate(rounds):
        rc = rs.get('rc', 0)
        if fm_flags[ri]:
            expr = "L ^ t"
        elif rc:
            expr = f"L ^ t ^ rk32 ^ 32'h{rc:08x}"
        else:
            expr = "L ^ t ^ rk32"
        tail_kinds.setdefault(expr, []).append(ri)
    body.append("        Lt = R;")
    items = list(tail_kinds.items())
    for k, (expr, ris) in enumerate(items):
        kw = "if" if k == 0 else "else if"
        cond = " || ".join(f"i == {ri}" for ri in ris)
        if len(items) == 1 and len(ris) == 6:
            body.append(f"        Rt = {expr};")
        elif k == len(items) - 1 and len(items) > 1:
            body.append(f"        else Rt = {expr};")
        else:
            body.append(f"        {kw} ({cond}) Rt = {expr};")
    body.append("        L = Lt;")
    body.append("        R = Rt;")
    body.append("    end")
    body.append("end")
    body.append("")
    if post:
        body.append(f"assign out = ({{R, L}} ^ 64'h{post:016x});")
    else:
        body.append("assign out = {R, L};")
    body.append("")
    body.append("endmodule")
    return V_HDR.format(name=name, desc=desc) + V_DECL + "\n".join(body) + "\n"


