"""Dual critical-latency synthesis runner: Sky130 HD and HS liberty flows.

Mirrors exploration/run_synth.py methodology, but uses real Sky130 Liberty
timing instead of the unit-delay mini.genlib.

Usage:
  python3 run_synth_hs.py <verilog> <top> <workdir> [--lib hd|hs]

  --lib hd : sky130_fd_sc_hd__tt_100C_1v80.lib (high density, baseline)
  --lib hs : sky130_fd_sc_hs__tt_100C_1v80.lib (high speed, optimized)

Flow per design:
  read_verilog SRC
  hierarchy -check -top TOP
  proc; opt; flatten; opt
  memory_map; opt
  techmap; opt
  abc -liberty <lib>
  opt; clean
  stat
  write_verilog -noattr mapped_TOP.v
then analyze_liberty.py (topological critical path with Liberty delays).

Prints a one-line RESULT record with real delays in ns. Also measures the
mul64.v reference fresh and reports ratios, mirroring run_synth.py.
"""
import os, re, subprocess, sys

MIX = "/home/hatch/workspace/mix"
SYNTH = os.path.join(MIX, "synth")
REF_V = os.path.join(SYNTH, "mul64.v")
ADD_V = os.path.join(SYNTH, "add64.v")
YOSYS = "/home/hatch/tools/micromamba-root/envs/sky130/bin/yosys"
YOSYS_WANT = "0.69"

PDK = "/home/hatch/.volare/volare/sky130/versions/c6d73a35f524070e85faff4a6a9eef49553ebc2b/sky130A"
LIBS = {
    "hd": os.path.join(PDK, "libs.ref/sky130_fd_sc_hd/lib/sky130_fd_sc_hd__tt_100C_1v80.lib"),
    # HS liberty extracted from chipfoundry/volare sky130_fd_sc_hs tarball.
    "hs": os.path.join(SYNTH, "pdk_hs/sky130_fd_sc_hs/lib/sky130_fd_sc_hs__tt_100C_1v80.lib"),
}

YS_TMPL = """# Auto-generated by synth/run_synth_hs.py
read_verilog {src}
hierarchy -check -top {top}
proc; opt; flatten; opt
memory_map; opt
techmap; opt
abc -liberty {lib}
opt; clean
stat
write_verilog -noattr {mapped}
"""


def parse_analyze(out):
    m = re.search(r"cells:\s*(\d+)\s+total_area:\s*([\d.]+)\s+critical_path:\s*([\d.]+)", out)
    assert m, f"could not parse analyzer output:\n{out}"
    return dict(cells=int(m.group(1)), area=float(m.group(2)), crit=float(m.group(3)))


def synth_one(src, top, workdir, lib):
    workdir = os.path.abspath(workdir)
    os.makedirs(workdir, exist_ok=True)
    src = os.path.abspath(src)
    mapped = os.path.join(workdir, f"mapped_{top}.v")
    ys = os.path.join(workdir, f"s_{top}.ys")
    with open(ys, "w") as f:
        f.write(YS_TMPL.format(src=src, top=top, lib=lib, mapped=mapped))
    vv = subprocess.run([YOSYS, "-V"], capture_output=True, text=True, timeout=60)
    if YOSYS_WANT not in (vv.stdout + vv.stderr):
        raise RuntimeError(f"wrong yosys at {YOSYS}")
    # Serialize yosys (same lock as run_synth.py — the ABC pipe deadlock).
    yosys_lock = os.path.join(MIX, "exploration", ".yosys.lock")
    yosys_env = dict(os.environ, TMPDIR="/tmp")
    r = subprocess.run(["flock", yosys_lock, YOSYS, "-s", ys],
                       capture_output=True, text=True,
                       cwd=workdir, timeout=900, env=yosys_env)
    if r.returncode != 0 or not os.path.exists(mapped):
        raise RuntimeError(f"yosys failed for {top}:\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    a = subprocess.run([sys.executable, os.path.join(SYNTH, "analyze_liberty.py"),
                        mapped, lib], capture_output=True, text=True, timeout=300)
    if a.returncode != 0:
        raise RuntimeError(f"analyze_liberty.py failed for {top}:\n{a.stderr[-2000:]}")
    return parse_analyze(a.stdout)


def main():
    args = sys.argv[1:]
    libsel = "hd"
    if "--lib" in args:
        i = args.index("--lib")
        libsel = args[i + 1]
        del args[i:i + 2]
    src, top, workdir = args[0], args[1], args[2]
    lib = LIBS[libsel]
    if not os.path.exists(lib):
        raise RuntimeError(f"liberty not found: {lib}")
    ref = synth_one(REF_V, "mul64", os.path.join(workdir, "_ref"), lib)
    dut = synth_one(src, top, os.path.join(workdir, "_dut"), lib)
    rd = dut["crit"] / ref["crit"]
    ra = dut["area"] / ref["area"]
    print(f"REF mul64 [{libsel}]: cells={ref['cells']} area={ref['area']:.0f} crit={ref['crit']:.4f}ns")
    print(f"DUT {top} [{libsel}]: cells={dut['cells']} area={dut['area']:.0f} crit={dut['crit']:.4f}ns")
    print(f"RESULT name={top} lib={libsel} cells={dut['cells']} area={dut['area']:.0f} "
          f"crit_ns={dut['crit']:.4f} delay_ratio={rd:.3f} area_ratio={ra:.3f} "
          f"ref_crit_ns={ref['crit']:.4f} ref_area={ref['area']:.0f}")


if __name__ == "__main__":
    main()
